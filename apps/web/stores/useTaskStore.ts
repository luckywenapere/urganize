'use client';

import { create } from 'zustand';
import { supabase } from '@/lib/supabase/client';
import {
  TASK_DONE_STATUS,
  TASK_LOCKED_STATUS,
  TASK_PENDING_STATUS,
  type ExecutionTask,
  type ReleasePipelineState,
  type TaskRequirement,
} from '@/lib/execution-types';
import { getTaskCompletionBlocker } from '@/lib/release-execution';
import { type TaskStatus } from '@/lib/tasks';

type TaskCreateInput = {
  title: string;
  releaseId: string;
  dueDate?: string | null;
  state: ReleasePipelineState;
  requirement?: TaskRequirement | null;
  dependencies?: string[];
  autoGenerated?: boolean;
};

type TaskStore = {
  tasks: ExecutionTask[];
  selectedTaskId: string | null;
  error: string;
  setTasks: (tasks: ExecutionTask[]) => void;
  selectTask: (taskId: string | null) => void;
  createTask: (input: TaskCreateInput) => Promise<ExecutionTask | null>;
  updateRequirement: (taskId: string, requirement: TaskRequirement | null) => Promise<void>;
  completeTask: (taskId: string) => Promise<ExecutionTask | null>;
  updateTaskStatus: (taskId: string, status: TaskStatus) => Promise<ExecutionTask | null>;
  tasksForRelease: (releaseId: string) => ExecutionTask[];
};

const getAccessToken = async () => {
  const {
    data: { session },
  } = await supabase.auth.getSession();
  return session?.access_token || '';
};

export const useTaskStore = create<TaskStore>((set, get) => ({
  tasks: [],
  selectedTaskId: null,
  error: '',
  setTasks: (tasks) => set({ tasks, error: '' }),
  selectTask: (taskId) => set({ selectedTaskId: taskId }),
  tasksForRelease: (releaseId) => get().tasks.filter((task) => task.releaseId === releaseId),
  createTask: async (input) => {
    const accessToken = await getAccessToken();
    if (!accessToken) {
      set({ error: 'Session expired. Please sign in again.' });
      return null;
    }

    const hasIncompleteDependencies = (input.dependencies || []).some((id) => {
      const dependency = get().tasks.find((task) => task.id === id);
      return dependency && dependency.status !== TASK_DONE_STATUS;
    });

    const response = await fetch('/api/tasks', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Bearer ${accessToken}`,
      },
      body: JSON.stringify({
        title: input.title,
        releaseId: input.releaseId,
        dueDate: input.dueDate || null,
        state: input.state,
        status: hasIncompleteDependencies ? TASK_LOCKED_STATUS : TASK_PENDING_STATUS,
        requirement: input.requirement || null,
        dependencies: input.dependencies || [],
        autoGenerated: input.autoGenerated === true,
        source: input.autoGenerated ? 'inline' : 'quick_create',
      }),
    });

    const payload = (await response.json().catch(() => ({}))) as { task?: ExecutionTask; error?: string };
    if (!response.ok || !payload.task) {
      set({ error: payload.error || 'Could not create task.' });
      return null;
    }

    set((state) => ({ tasks: [payload.task as ExecutionTask, ...state.tasks], error: '' }));
    return payload.task as ExecutionTask;
  },
  updateRequirement: async (taskId, requirement) => {
    const task = get().tasks.find((candidate) => candidate.id === taskId);
    if (!task) return;

    const accessToken = await getAccessToken();
    if (!accessToken) {
      set({ error: 'Session expired. Please sign in again.' });
      return;
    }

    const response = await fetch(`/api/tasks/${taskId}`, {
      method: 'PATCH',
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Bearer ${accessToken}`,
      },
      body: JSON.stringify({ requirement }),
    });
    const payload = (await response.json().catch(() => ({}))) as { task?: ExecutionTask; error?: string };
    if (!response.ok || !payload.task) {
      set({ error: payload.error || 'Could not update requirement.' });
      return;
    }

    set((state) => ({
      tasks: state.tasks.map((candidate) => (candidate.id === taskId ? (payload.task as ExecutionTask) : candidate)),
      error: '',
    }));
  },
  completeTask: async (taskId) => {
    const task = get().tasks.find((candidate) => candidate.id === taskId);
    if (!task) return null;

    const blocker = getTaskCompletionBlocker(task, get().tasks);
    if (blocker) {
      set({ error: blocker });
      return null;
    }

    const accessToken = await getAccessToken();
    if (!accessToken) {
      set({ error: 'Session expired. Please sign in again.' });
      return null;
    }

    const response = await fetch(`/api/tasks/${taskId}`, {
      method: 'PATCH',
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Bearer ${accessToken}`,
      },
      body: JSON.stringify({ status: TASK_DONE_STATUS }),
    });

    const payload = (await response.json().catch(() => ({}))) as { task?: ExecutionTask; error?: string };
    if (!response.ok || !payload.task) {
      set({ error: payload.error || 'Could not complete task.' });
      return null;
    }

    set((state) => ({
      tasks: state.tasks.map((candidate) => {
        if (candidate.id === taskId) return payload.task as ExecutionTask;
        if (candidate.status === TASK_LOCKED_STATUS && candidate.dependencies.includes(taskId)) {
          const dependenciesComplete = candidate.dependencies.every((id) => {
            if (id === taskId) return true;
            return state.tasks.find((dependency) => dependency.id === id)?.status === TASK_DONE_STATUS;
          });
          return dependenciesComplete ? { ...candidate, status: TASK_PENDING_STATUS } : candidate;
        }
        return candidate;
      }),
      error: '',
    }));

    return payload.task as ExecutionTask;
  },
  updateTaskStatus: async (taskId, status) => {
    const task = get().tasks.find((candidate) => candidate.id === taskId);
    if (!task) return null;

    const accessToken = await getAccessToken();
    if (!accessToken) {
      set({ error: 'Session expired. Please sign in again.' });
      return null;
    }

    const response = await fetch(`/api/tasks/${taskId}`, {
      method: 'PATCH',
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Bearer ${accessToken}`,
      },
      body: JSON.stringify({ status }),
    });

    const payload = (await response.json().catch(() => ({}))) as { task?: ExecutionTask; error?: string };
    if (!response.ok || !payload.task) {
      set({ error: payload.error || 'Could not update task status.' });
      return null;
    }

    set((state) => ({
      tasks: state.tasks.map((candidate) => (candidate.id === taskId ? (payload.task as ExecutionTask) : candidate)),
      error: '',
    }));

    return payload.task as ExecutionTask;
  },
}));
