'use client';

import { create } from 'zustand';
import { supabase } from '@/lib/supabase/client';
import {
  TASK_DONE_STATUS,
  TASK_LOCKED_STATUS,
  TASK_PENDING_STATUS,
  type ExecutionTask,
  type TaskRequirement,
} from '@/lib/execution-types';
import { getTaskCompletionBlocker } from '@/lib/release-execution';
import { type TaskPriority } from '@/lib/tasks';

type TaskCreateInput = {
  title: string;
  releaseId: string;
  dueDate?: string | null;
  requirement?: TaskRequirement | null;
  dependencies?: string[];
  autoGenerated?: boolean;
  priority?: TaskPriority;
  assignedToUserId?: string | null;
};

/**
 * Toast snapshot for the "Task completed · Undo" notification surfaced by the
 * UndoCompletionToast component (mounted globally in TaskUIProvider). A
 * monotonically increasing `tick` keeps the same taskId completed twice in a
 * row from collapsing into a single toast — every completion shows a fresh
 * countdown.
 */
export type CompletionToastState = {
  taskId: string;
  title: string;
  tick: number;
};

type TaskStore = {
  tasks: ExecutionTask[];
  selectedTaskId: string | null;
  error: string;
  /**
   * Task ids whose status flipped to `done` but whose row should keep its
   * original time-based bucket for ~1.5s before sliding into Done. Used by
   * `groupTasksIntoSections` as a render-time override. Cleared when the in-
   * place beat ends, or earlier by `undoCompletion`.
   */
  pendingCompletionIds: Record<string, true>;
  /** Latest completion eligible for an Undo toast. Null when no toast active. */
  completionToast: CompletionToastState | null;
  setTasks: (tasks: ExecutionTask[]) => void;
  selectTask: (taskId: string | null) => void;
  createTask: (input: TaskCreateInput) => Promise<ExecutionTask | null>;
  updateRequirement: (taskId: string, requirement: TaskRequirement | null) => Promise<void>;
  completeTask: (taskId: string) => Promise<ExecutionTask | null>;
  /**
   * Reverses the most recent completion of `taskId` by patching it back to
   * `todo`, clearing any pending in-place beat, and dismissing the undo toast
   * for that id. Safe to call from inside or outside the 1.5s in-place window.
   */
  undoCompletion: (taskId: string) => Promise<void>;
  dismissCompletionToast: (taskId?: string) => void;
  tasksForRelease: (releaseId: string) => ExecutionTask[];
};

/**
 * Module-scoped timers keyed by task id. Kept outside React state because they
 * are operational handles (cleanup metadata), not rendered values — and so a
 * later tick on the same task can cancel its predecessor without a re-render.
 */
const pendingBeatTimers = new Map<string, ReturnType<typeof setTimeout>>();
const completionToastTimers = new Map<string, ReturnType<typeof setTimeout>>();
// One in-flight complete/reopen mutation per task. The optimistic flip means
// a second click during the round trip would route to the opposite branch
// (done → reopen) and race the first PATCH — so clicks are ignored while a
// mutation is in the air, and undoCompletion waits for it to settle before
// sending its own PATCH.
//
// Two structures on purpose: the Set is stamped SYNCHRONOUSLY at completeTask
// entry (before any await), so two clicks in the same token-refresh window
// can't both pass the guard; the Map holds the network promise undoCompletion
// awaits for ordering, which only exists once the PATCH is dispatched.
const inFlightCompletionIds = new Set<string>();
const inFlightCompletionPatches = new Map<string, Promise<unknown>>();

const PENDING_BEAT_MS = 1500;
const TOAST_DURATION_MS = 5000;
let completionToastTick = 0;

const getAccessToken = async () => {
  const {
    data: { session },
  } = await supabase.auth.getSession();
  return session?.access_token || '';
};

export const useTaskStore = create<TaskStore>((set, get) => ({
  tasks: [],
  selectedTaskId: null,
  error: '',
  pendingCompletionIds: {},
  completionToast: null,
  setTasks: (tasks) => set({ tasks, error: '' }),
  selectTask: (taskId) => set({ selectedTaskId: taskId }),
  tasksForRelease: (releaseId) => get().tasks.filter((task) => task.releaseId === releaseId),
  createTask: async (input) => {
    const accessToken = await getAccessToken();
    if (!accessToken) {
      set({ error: 'Session expired. Please sign in again.' });
      return null;
    }

    const hasIncompleteDependencies = (input.dependencies || []).some((id) => {
      const dependency = get().tasks.find((task) => task.id === id);
      return dependency && dependency.status !== TASK_DONE_STATUS;
    });

    const response = await fetch('/api/tasks', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Bearer ${accessToken}`,
      },
      body: JSON.stringify({
        title: input.title,
        releaseId: input.releaseId,
        dueDate: input.dueDate || null,
        status: hasIncompleteDependencies ? TASK_LOCKED_STATUS : TASK_PENDING_STATUS,
        requirement: input.requirement || null,
        dependencies: input.dependencies || [],
        autoGenerated: input.autoGenerated === true,
        source: input.autoGenerated ? 'inline' : 'quick_create',
        priority: input.priority,
        assignedToUserId: input.assignedToUserId ?? undefined,
      }),
    });

    const payload = (await response.json().catch(() => ({}))) as { task?: ExecutionTask; error?: string };
    if (!response.ok || !payload.task) {
      set({ error: payload.error || 'Could not create task.' });
      return null;
    }

    set((state) => ({ tasks: [payload.task as ExecutionTask, ...state.tasks], error: '' }));
    return payload.task as ExecutionTask;
  },
  updateRequirement: async (taskId, requirement) => {
    const task = get().tasks.find((candidate) => candidate.id === taskId);
    if (!task) return;

    const accessToken = await getAccessToken();
    if (!accessToken) {
      set({ error: 'Session expired. Please sign in again.' });
      return;
    }

    const response = await fetch(`/api/tasks/${taskId}`, {
      method: 'PATCH',
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Bearer ${accessToken}`,
      },
      body: JSON.stringify({ requirement }),
    });
    const payload = (await response.json().catch(() => ({}))) as { task?: ExecutionTask; error?: string };
    if (!response.ok || !payload.task) {
      set({ error: payload.error || 'Could not update requirement.' });
      return;
    }

    set((state) => ({
      tasks: state.tasks.map((candidate) => (candidate.id === taskId ? (payload.task as ExecutionTask) : candidate)),
      error: '',
    }));
  },
  completeTask: async (taskId) => {
    // Ignore clicks while a previous complete/reopen for this task is still
    // running. Clear the error first so callers' `!result` blocker checks
    // read an empty message and treat the ignored click as a no-op rather
    // than a failure.
    if (inFlightCompletionIds.has(taskId)) {
      set({ error: '' });
      return null;
    }
    inFlightCompletionIds.add(taskId);
    // The whole mutation runs inside this try so every exit path — early
    // returns included — releases the in-flight marker in the finally at the
    // bottom of this method.
    try {

    const accessToken = await getAccessToken();
    if (!accessToken) {
      set({ error: 'Session expired. Please sign in again.' });
      return null;
    }

    // Hydrate the store if this task isn't loaded yet (e.g. cross-release
    // entry from a notification or the flat Tasks page). The blocker check
    // and cascade-unlock both rely on store state, so we want a single
    // hydration path before either runs.
    let task = get().tasks.find((candidate) => candidate.id === taskId);
    if (!task) {
      const fetchResponse = await fetch(`/api/tasks/${taskId}`, {
        headers: { Authorization: `Bearer ${accessToken}` },
        cache: 'no-store',
      });
      const fetchPayload = (await fetchResponse.json().catch(() => ({}))) as {
        task?: ExecutionTask;
        error?: string;
      };
      if (!fetchResponse.ok || !fetchPayload.task) {
        set({ error: fetchPayload.error || 'Could not load task.' });
        return null;
      }
      task = fetchPayload.task;
      set((state) => ({ tasks: [...state.tasks, task!] }));
    }

    // Toggle: clicking the checkbox on a done task reopens it. We PATCH
    // straight to todo with no blocker check and no cascade — reopening is
    // an admin action that doesn't need the gate, and re-locking dependents
    // is more confusing than helpful at v1 scale.
    //
    // Also covers the "re-tick inside the in-place beat" case: the row is
    // still rendered in its source bucket via pendingCompletionIds, but the
    // task itself is already `done` in the store, so the click lands here.
    // Cancelling the beat + toast timers below makes the row stay put and
    // the toast disappear instead of stranding state behind.
    if (task.status === TASK_DONE_STATUS) {
      const beatTimer = pendingBeatTimers.get(taskId);
      if (beatTimer) {
        clearTimeout(beatTimer);
        pendingBeatTimers.delete(taskId);
      }
      const toastTimer = completionToastTimers.get(taskId);
      if (toastTimer) {
        clearTimeout(toastTimer);
        completionToastTimers.delete(taskId);
      }

      // Optimistic reopen: the checkbox unticks on this frame; the PATCH
      // settles in the background and rolls the row back on failure.
      const taskBeforeReopen = task;
      const optimisticReopened = { ...task, status: TASK_PENDING_STATUS } as ExecutionTask;
      set((state) => {
        const nextPending = { ...state.pendingCompletionIds };
        delete nextPending[taskId];
        const nextToast =
          state.completionToast?.taskId === taskId ? null : state.completionToast;
        return {
          tasks: state.tasks.map((candidate) =>
            candidate.id === taskId ? optimisticReopened : candidate
          ),
          pendingCompletionIds: nextPending,
          completionToast: nextToast,
          error: '',
        };
      });

      const reopenRequest = (async () => {
        const reopenResponse = await fetch(`/api/tasks/${taskId}`, {
          method: 'PATCH',
          headers: {
            'Content-Type': 'application/json',
            Authorization: `Bearer ${accessToken}`,
          },
          body: JSON.stringify({ status: TASK_PENDING_STATUS }),
        });
        const reopenPayload = (await reopenResponse.json().catch(() => ({}))) as {
          task?: ExecutionTask;
          error?: string;
        };
        if (!reopenResponse.ok || !reopenPayload.task) {
          throw new Error(reopenPayload.error || 'Could not reopen task.');
        }
        return reopenPayload.task as ExecutionTask;
      })();
      inFlightCompletionPatches.set(taskId, reopenRequest.catch(() => null));

      try {
        const reopenedTask = await reopenRequest;
        set((state) => ({
          tasks: state.tasks.map((candidate) =>
            candidate.id === taskId ? reopenedTask : candidate
          ),
          error: '',
        }));
        return reopenedTask;
      } catch (error) {
        // Roll the row back to done — the server never accepted the reopen.
        set((state) => ({
          tasks: state.tasks.map((candidate) =>
            candidate.id === taskId ? taskBeforeReopen : candidate
          ),
          error: error instanceof Error ? error.message : 'Could not reopen task.',
        }));
        return null;
      } finally {
        inFlightCompletionPatches.delete(taskId);
      }
    }

    const blocker = getTaskCompletionBlocker(task, get().tasks);
    if (blocker) {
      set({ error: blocker });
      return null;
    }

    // ── Optimistic completion ───────────────────────────────────────────
    // The tick, the in-place beat, and the toast all render on THIS frame;
    // the completion PATCH settles in the background and the flip rolls back
    // if the server rejects it. This used to wait for the completion PATCH
    // plus every cascade-unlock PATCH before showing anything — the checkbox
    // sat visually empty for 1-2+ round trips on every tick.
    //
    // Dependency unlocks are deliberately NOT optimistic: flipping a
    // dependent to todo before its PATCH lands would let the user complete a
    // task whose server row is still `locked` (the PATCH route doesn't
    // validate transitions), so unlocked rows only flip once the server
    // confirms them below.
    const taskBeforeComplete = task;
    const optimisticDone = { ...task, status: TASK_DONE_STATUS } as ExecutionTask;

    // Identify tasks that are locked today, depend on the just-completed
    // task, and have every dependency satisfied. Those flip to todo once
    // their PATCH succeeds.
    const tasksAfterComplete = get().tasks.map((candidate) =>
      candidate.id === taskId ? optimisticDone : candidate
    );
    const unlockCandidates = tasksAfterComplete.filter(
      (candidate) =>
        candidate.status === TASK_LOCKED_STATUS &&
        candidate.dependencies.includes(taskId) &&
        candidate.dependencies.every(
          (id) => tasksAfterComplete.find((dep) => dep.id === id)?.status === TASK_DONE_STATUS
        )
    );

    // Schedule the "in-place beat then move to Done" handoff. Any earlier
    // timer for this id (rapid re-ticks) is cancelled so the latest tick
    // wins. The pending flag is set synchronously alongside the data write
    // so React renders the row in its source bucket on this same frame.
    const existingBeatTimer = pendingBeatTimers.get(taskId);
    if (existingBeatTimer) {
      clearTimeout(existingBeatTimer);
    }
    const beatTimer = setTimeout(() => {
      pendingBeatTimers.delete(taskId);
      set((state) => {
        if (!state.pendingCompletionIds[taskId]) return state;
        const nextPending = { ...state.pendingCompletionIds };
        delete nextPending[taskId];
        return { pendingCompletionIds: nextPending };
      });
    }, PENDING_BEAT_MS);
    pendingBeatTimers.set(taskId, beatTimer);

    // Mirror the same single-active-timer rule for the toast — the toast
    // lifetime (TOAST_DURATION_MS) is independent of the in-place beat so
    // a mis-tick is recoverable after the row has moved to Done.
    const existingToastTimer = completionToastTimers.get(taskId);
    if (existingToastTimer) {
      clearTimeout(existingToastTimer);
    }
    const toastTimer = setTimeout(() => {
      completionToastTimers.delete(taskId);
      set((state) => {
        if (state.completionToast?.taskId !== taskId) return state;
        return { completionToast: null };
      });
    }, TOAST_DURATION_MS);
    completionToastTimers.set(taskId, toastTimer);

    completionToastTick += 1;
    const toastSnapshot: CompletionToastState = {
      taskId,
      title: optimisticDone.title,
      tick: completionToastTick,
    };

    set((state) => ({
      tasks: state.tasks.map((candidate) =>
        candidate.id === taskId ? optimisticDone : candidate
      ),
      pendingCompletionIds: { ...state.pendingCompletionIds, [taskId]: true },
      completionToast: toastSnapshot,
      error: '',
    }));

    const rollbackCompletion = (message: string) => {
      const pendingBeat = pendingBeatTimers.get(taskId);
      if (pendingBeat) {
        clearTimeout(pendingBeat);
        pendingBeatTimers.delete(taskId);
      }
      const pendingToast = completionToastTimers.get(taskId);
      if (pendingToast) {
        clearTimeout(pendingToast);
        completionToastTimers.delete(taskId);
      }
      set((state) => {
        const nextPending = { ...state.pendingCompletionIds };
        delete nextPending[taskId];
        return {
          tasks: state.tasks.map((candidate) =>
            candidate.id === taskId ? taskBeforeComplete : candidate
          ),
          pendingCompletionIds: nextPending,
          completionToast:
            state.completionToast?.taskId === taskId ? null : state.completionToast,
          error: message,
        };
      });
    };

    const completionRequest = (async () => {
      const response = await fetch(`/api/tasks/${taskId}`, {
        method: 'PATCH',
        headers: {
          'Content-Type': 'application/json',
          Authorization: `Bearer ${accessToken}`,
        },
        body: JSON.stringify({ status: TASK_DONE_STATUS }),
      });
      const payload = (await response.json().catch(() => ({}))) as {
        task?: ExecutionTask;
        error?: string;
      };
      if (!response.ok || !payload.task) {
        throw new Error(payload.error || 'Could not complete task.');
      }
      return payload.task as ExecutionTask;
    })();
    inFlightCompletionPatches.set(taskId, completionRequest.catch(() => null));

    try {
      const completedTask = await completionRequest;

      // Reconcile the optimistic row with the server's authoritative one.
      set((state) => ({
        tasks: state.tasks.map((candidate) =>
          candidate.id === taskId ? completedTask : candidate
        ),
      }));

      // Persist each unlock, then flip only the rows the server confirmed —
      // a failed unlock simply stays locked on screen, matching its server
      // state. Failures are logged; the completion stands either way.
      const unlockResults = await Promise.all(
        unlockCandidates.map(async (candidate) => {
          try {
            const unlockResponse = await fetch(`/api/tasks/${candidate.id}`, {
              method: 'PATCH',
              headers: {
                'Content-Type': 'application/json',
                Authorization: `Bearer ${accessToken}`,
              },
              body: JSON.stringify({ status: TASK_PENDING_STATUS }),
            });
            const unlockPayload = (await unlockResponse.json().catch(() => ({}))) as {
              task?: ExecutionTask;
              error?: string;
            };
            if (!unlockResponse.ok || !unlockPayload.task) {
              console.error(
                'Auto-unlock PATCH failed for task',
                candidate.id,
                unlockPayload.error || unlockResponse.statusText
              );
              return null;
            }
            return unlockPayload.task as ExecutionTask;
          } catch (error) {
            console.error('Auto-unlock PATCH threw for task', candidate.id, error);
            return null;
          }
        })
      );

      const unlockedById = new Map<string, ExecutionTask>();
      for (const unlocked of unlockResults) {
        if (unlocked) {
          unlockedById.set(unlocked.id, unlocked);
        }
      }

      if (unlockedById.size) {
        set((state) => ({
          tasks: state.tasks.map(
            (candidate) => unlockedById.get(candidate.id) || candidate
          ),
        }));
      }

      return completedTask;
    } catch (error) {
      rollbackCompletion(
        error instanceof Error ? error.message : 'Could not complete task.'
      );
      return null;
    } finally {
      inFlightCompletionPatches.delete(taskId);
    }

    } finally {
      // Releases the click guard for every exit path of this method.
      inFlightCompletionIds.delete(taskId);
    }
  },
  undoCompletion: async (taskId) => {
    const beatTimer = pendingBeatTimers.get(taskId);
    if (beatTimer) {
      clearTimeout(beatTimer);
      pendingBeatTimers.delete(taskId);
    }
    const toastTimer = completionToastTimers.get(taskId);
    if (toastTimer) {
      clearTimeout(toastTimer);
      completionToastTimers.delete(taskId);
    }

    // Optimistic clears so the row drops out of pending + the toast hides
    // immediately, even before the PATCH lands. The store self-heals if the
    // patch fails (the next refresh will reload the authoritative status).
    set((state) => {
      const nextPending = { ...state.pendingCompletionIds };
      delete nextPending[taskId];
      const nextToast =
        state.completionToast?.taskId === taskId ? null : state.completionToast;
      return { pendingCompletionIds: nextPending, completionToast: nextToast };
    });

    // The completion toast (and its Undo) now appears while the completion
    // PATCH may still be in flight — wait for it to settle so this undo
    // PATCH can't be overtaken by the earlier request on the server.
    const inFlight = inFlightCompletionPatches.get(taskId);
    if (inFlight) {
      await inFlight;
    }

    const accessToken = await getAccessToken();
    if (!accessToken) {
      set({ error: 'Session expired. Please sign in again.' });
      return;
    }

    const response = await fetch(`/api/tasks/${taskId}`, {
      method: 'PATCH',
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Bearer ${accessToken}`,
      },
      body: JSON.stringify({ status: TASK_PENDING_STATUS }),
    });
    const payload = (await response.json().catch(() => ({}))) as {
      task?: ExecutionTask;
      error?: string;
    };
    if (!response.ok || !payload.task) {
      set({ error: payload.error || 'Could not undo completion.' });
      return;
    }
    const restored = payload.task as ExecutionTask;
    set((state) => ({
      tasks: state.tasks.map((candidate) =>
        candidate.id === taskId ? restored : candidate
      ),
      error: '',
    }));
  },
  dismissCompletionToast: (taskId) => {
    set((state) => {
      if (!state.completionToast) return state;
      if (taskId && state.completionToast.taskId !== taskId) return state;
      const targetId = taskId ?? state.completionToast.taskId;
      const timer = completionToastTimers.get(targetId);
      if (timer) {
        clearTimeout(timer);
        completionToastTimers.delete(targetId);
      }
      return { completionToast: null };
    });
  },
}));
