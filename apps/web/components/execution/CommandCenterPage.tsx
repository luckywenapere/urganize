'use client';

import { useEffect, useMemo, useState } from 'react';
import { Bell, Plus, Search } from 'lucide-react';
import { useRouter } from 'next/navigation';
import { useAuthStore } from '@/lib/auth-store';
import type { AISignal, ExecutionRelease, ExecutionTask } from '@/lib/execution-types';
import { TASK_DONE_STATUS } from '@/lib/execution-types';
import { calculateOverallReadiness, selectPrimaryRelease } from '@/lib/release-execution';
import { useActivityStore } from '@/stores/useActivityStore';
import { useAIStore } from '@/stores/useAIStore';
import { useReleaseStore } from '@/stores/useReleaseStore';
import { useTaskStore } from '@/stores/useTaskStore';
import { AISignal as AISignalCard } from '@/components/execution/AISignal';
import { FocusCard } from '@/components/execution/FocusCard';
import { ReadinessBar } from '@/components/execution/ReadinessBar';
import { TaskDetailModal } from '@/components/execution/TaskDetailModal';

function QuickCreateModal({
  onClose,
  onCreate,
}: {
  onClose: () => void;
  onCreate: (title: string) => void;
}) {
  const [title, setTitle] = useState('');

  return (
    <div role="dialog" aria-modal="true" className="fixed inset-0 z-[140] flex items-center justify-center bg-black/70 p-4">
      <div className="w-full max-w-md rounded-[26px] border border-stroke-default bg-bg-surface p-5">
        <h2 className="text-xl font-semibold text-content-primary">Create release</h2>
        <label className="mt-4 block">
          <span className="mb-2 block text-sm text-content-secondary">Release name</span>
          <input
            value={title}
            onChange={(event) => setTitle(event.target.value)}
            className="input"
            placeholder="e.g. Midnight Demo"
          />
        </label>
        <div className="mt-5 flex justify-end gap-2">
          <button type="button" onClick={onClose} className="rounded-full border border-stroke-default px-4 py-2 text-sm text-content-secondary">
            Cancel
          </button>
          <button
            type="button"
            disabled={!title.trim()}
            onClick={() => onCreate(title.trim())}
            className="rounded-full bg-brand px-4 py-2 text-sm font-semibold text-content-inverse disabled:opacity-50"
          >
            Create
          </button>
        </div>
      </div>
    </div>
  );
}

export function CommandCenterPage() {
  const router = useRouter();
  const { user, isLoading: authLoading } = useAuthStore();
  const { releases, isLoading, error, loadCommandCenter, createRelease } = useReleaseStore();
  const { tasks, selectedTaskId, selectTask, completeTask, updateRequirement, createTask, error: taskError } = useTaskStore();
  const { activity } = useActivityStore();
  const { signals, runCheck } = useAIStore();
  const [showCreateModal, setShowCreateModal] = useState(false);

  useEffect(() => {
    if (authLoading) return;
    if (!user) {
      router.replace('/auth');
      return;
    }
    void loadCommandCenter().then((data) => {
      if (data) void runCheck(data);
    });
  }, [authLoading, loadCommandCenter, router, runCheck, user]);

  const primaryRelease = useMemo(() => selectPrimaryRelease(releases, tasks), [releases, tasks]);
  const selectedTask = tasks.find((task) => task.id === selectedTaskId) || null;
  const nextActions = useMemo(
    () =>
      tasks
        .filter((task) => task.status !== TASK_DONE_STATUS && task.status !== 'cancelled')
        .sort((left, right) => {
          const leftDue = left.dueDate ? new Date(left.dueDate).getTime() : Number.POSITIVE_INFINITY;
          const rightDue = right.dueDate ? new Date(right.dueDate).getTime() : Number.POSITIVE_INFINITY;
          return leftDue - rightDue;
        })
        .slice(0, 5),
    [tasks]
  );

  const handleSignalAction = async (signal: AISignal) => {
    const release = releases.find((candidate) => candidate.id === signal.releaseId);
    if (!release) return;
    const task = await createTask({
      title: signal.title.includes('Campaign') ? 'Build release campaign checklist' : `Resolve: ${signal.title}`,
      releaseId: release.id,
      state: signal.state || release.state,
      autoGenerated: true,
      requirement: {
        type: 'approval',
        spec: 'Review the generated plan and approve the next action.',
        satisfied: false,
      },
    });
    if (task) selectTask(task.id);
  };

  const handleCreateRelease = async (title: string) => {
    const release = await createRelease(title, 'idea');
    setShowCreateModal(false);
    if (release) router.push(`/dashboard/releases/${release.id}`);
  };

  if (isLoading || authLoading) {
    return <main className="min-h-screen bg-bg-base p-6 text-content-primary">Loading Command Center...</main>;
  }

  return (
    <main className="min-h-screen bg-bg-base text-content-primary">
      <div className="mx-auto max-w-[1440px] px-4 pb-24 pt-4 sm:px-6 lg:px-8">
        <header className="mb-5 flex flex-col gap-3 rounded-[24px] border border-stroke-default bg-bg-surface p-4 lg:flex-row lg:items-center lg:justify-between">
          <div>
            <p className="saas-eyebrow">Command Center</p>
            <h1 className="mt-1 text-3xl text-content-primary">Today&apos;s release work</h1>
          </div>
          <div className="flex flex-wrap items-center gap-2">
            <span className="rounded-full border border-stroke-default bg-bg-elevated px-3 py-2 text-sm text-content-secondary">Default org</span>
            <label className="relative min-w-[220px] flex-1 sm:flex-none">
              <Search className="pointer-events-none absolute left-3 top-1/2 h-4 w-4 -translate-y-1/2 text-content-tertiary" />
              <input className="input h-10 rounded-full pl-9" placeholder="Search releases or tasks" />
            </label>
            <button type="button" className="inline-flex h-10 w-10 items-center justify-center rounded-full border border-stroke-default bg-bg-elevated">
              <Bell className="h-4 w-4" />
            </button>
            <button type="button" className="rounded-full border border-stroke-default bg-bg-elevated px-3 py-2 text-sm">
              {user?.name || user?.email || 'Profile'}
            </button>
          </div>
        </header>

        {error || taskError ? (
          <p className="mb-4 rounded-2xl border border-status-error/35 bg-status-error/10 px-4 py-3 text-sm text-status-error">
            {error || taskError}
          </p>
        ) : null}

        <div className="grid gap-5 lg:grid-cols-[minmax(0,7fr)_minmax(320px,3fr)]">
          <div className="space-y-5">
            <FocusCard
              release={primaryRelease}
              tasks={tasks}
              onContinue={(release) => router.push(`/dashboard/releases/${release.id}`)}
            />

            <section className="panel-shell p-5">
              <div className="mb-4 flex items-center justify-between">
                <h2 className="text-xl font-semibold">Next Actions Queue</h2>
                <span className="text-sm text-content-secondary">Top 5</span>
              </div>
              {nextActions.length ? (
                <div className="space-y-3">
                  {nextActions.map((task) => (
                    <div key={task.id} className="rounded-[18px] border border-stroke-subtle bg-bg-elevated p-4">
                      <div className="flex flex-col gap-3 sm:flex-row sm:items-center sm:justify-between">
                        <div>
                          <p className="font-semibold text-content-primary">{task.title}</p>
                          <p className="mt-1 text-sm text-content-secondary">
                            {task.release?.title || 'Release'} {task.dueDate ? `• ${new Date(task.dueDate).toLocaleDateString()}` : ''}
                          </p>
                        </div>
                        <button
                          type="button"
                          onClick={() => selectTask(task.id)}
                          className="rounded-full border border-brand/25 bg-brand px-4 py-2 text-sm font-semibold text-content-inverse"
                        >
                          {task.autoGenerated ? 'Review' : task.requirement ? 'Start' : 'Generate'}
                        </button>
                      </div>
                    </div>
                  ))}
                </div>
              ) : (
                <p className="rounded-[18px] border border-stroke-subtle bg-bg-elevated p-4 text-sm text-content-secondary">
                  No open actions. Create a release or generate a plan to fill the queue.
                </p>
              )}
            </section>

            <section className="panel-shell p-5">
              <h2 className="mb-4 text-xl font-semibold">AI Signals</h2>
              <div className="space-y-3">
                {signals.length ? (
                  signals.slice(0, 4).map((signal) => (
                    <AISignalCard key={signal.id} signal={signal} onAction={handleSignalAction} />
                  ))
                ) : (
                  <p className="rounded-[18px] border border-stroke-subtle bg-bg-elevated p-4 text-sm text-content-secondary">
                    No AI signals yet. Signals appear after release or task changes.
                  </p>
                )}
              </div>
            </section>
          </div>

          <aside className="space-y-5">
            <section className="panel-shell p-5">
              <div className="mb-4 flex items-center justify-between">
                <h2 className="text-xl font-semibold">Readiness Overview</h2>
                <button
                  type="button"
                  onClick={() => setShowCreateModal(true)}
                  className="inline-flex h-9 w-9 items-center justify-center rounded-full bg-brand text-content-inverse"
                >
                  <Plus className="h-4 w-4" />
                </button>
              </div>
              {releases.length ? (
                <div className="space-y-4">
                  {releases.map((release) => {
                    const readiness = calculateOverallReadiness(tasks.filter((task) => task.releaseId === release.id));
                    return (
                      <button
                        key={release.id}
                        type="button"
                        onClick={() => router.push(`/dashboard/releases/${release.id}`)}
                        className="block w-full rounded-[18px] border border-stroke-subtle bg-bg-elevated p-4 text-left hover:bg-bg-hover"
                      >
                        <p className="font-semibold text-content-primary">{release.title}</p>
                        <p className="mb-3 mt-1 text-sm text-content-secondary">{release.artistName}</p>
                        <ReadinessBar value={readiness} />
                      </button>
                    );
                  })}
                </div>
              ) : (
                <button
                  type="button"
                  onClick={() => setShowCreateModal(true)}
                  className="w-full rounded-[18px] border border-dashed border-brand/35 bg-brand-muted p-5 text-left text-sm text-content-primary"
                >
                  No releases yet. Create one to activate your Command Center.
                </button>
              )}
            </section>

            <section className="panel-shell p-5">
              <h2 className="mb-4 text-xl font-semibold">Team Activity</h2>
              <div className="space-y-3">
                {activity.length ? (
                  activity.map((entry) => (
                    <div key={entry.id} className="rounded-[16px] border border-stroke-subtle bg-bg-elevated p-3">
                      <p className="text-sm text-content-primary">{entry.message}</p>
                      <p className="mt-1 text-xs text-content-tertiary">{new Date(entry.createdAt).toLocaleString()}</p>
                    </div>
                  ))
                ) : (
                  <p className="text-sm text-content-secondary">No team activity yet.</p>
                )}
              </div>
            </section>
          </aside>
        </div>
      </div>

      <TaskDetailModal
        task={selectedTask}
        allTasks={tasks}
        onClose={() => selectTask(null)}
        onSatisfyRequirement={(task) => {
          void updateRequirement(task.id, task.requirement ? { ...task.requirement, satisfied: true } : null);
        }}
        onComplete={(task) => {
          void completeTask(task.id).then((updated) => {
            if (updated) void runCheck({ releases, tasks: useTaskStore.getState().tasks, releaseId: updated.releaseId });
          });
        }}
      />

      {showCreateModal ? <QuickCreateModal onClose={() => setShowCreateModal(false)} onCreate={handleCreateRelease} /> : null}
    </main>
  );
}
