const sectionOrder: TaskSectionKey[] = ['overdue', 'today', 'week', 'upcoming', 'no_due_date'];

export default function WorkspacePreviewPage() {
  const [scopeId, setScopeId] = useState<string | null>(null);
  const scoped = scopeId ? releases.find((r) => r.id === scopeId) ?? null : null;

  const visibleTasks = useMemo(
    () => (scopeId ? tasks.filter((t) => t.releaseId === scopeId) : tasks),
    [scopeId]
  );
  const sections = useMemo(() => groupTasksIntoSections(visibleTasks), [visibleTasks]);

  const stats = useMemo(() => computeWorkspaceStats(releases.length, tasks), []);

  return (
    <main className="min-h-screen bg-bg-base text-content-primary">
      <div className="mx-auto max-w-[1440px] px-4 pb-24 pt-10 sm:px-6">
        <header className="space-y-4">
          <div>
            <p className="text-[11px] font-semibold uppercase tracking-[0.18em] text-content-tertiary">
              Workspace preview
            </p>
            <h1 className="mt-1 font-display text-2xl font-semibold tracking-tight text-content-primary sm:text-3xl">
              Welcome back
            </h1>
            <p className="mt-1 text-sm text-content-secondary">
              Mock data. Temporary route at{' '}
              <code className="rounded bg-bg-elevated px-1.5 py-0.5 text-content-primary">
                /dashboard/preview
              </code>
              .
            </p>
          </div>
          <StatChips
            activeReleases={stats.activeReleases}
            tasksDone={stats.tasksDone}
            tasksTotal={stats.tasksTotal}
            overdue={stats.overdueCount}
            dueToday={stats.dueTodayCount}
          />
        </header>

        <div className="mt-8 grid gap-6 lg:grid-cols-[minmax(0,1fr)_minmax(360px,420px)]">
          <section className="space-y-3">
            <div className="flex items-center justify-between">
              <h2 className="text-xs font-semibold uppercase tracking-[0.16em] text-content-tertiary">
                Releases
              </h2>
              <p className="text-xs text-content-tertiary">Click a card to scope tasks</p>
            </div>
            <div className="grid gap-3 sm:grid-cols-2">
              {releases.map((release) => (
                <WorkspaceReleaseCard
                  key={release.id}
                  release={release}
                  tasksDone={release.tasksDone}
                  tasksTotal={release.tasksTotal}
                  selected={scopeId === release.id}
                  onSelect={(id) => setScopeId((current) => (current === id ? null : id))}
                />
              ))}
            </div>
          </section>

          <aside className="space-y-3">
            <div className="flex flex-wrap items-center justify-between gap-2">
              <h2 className="text-xs font-semibold uppercase tracking-[0.16em] text-content-tertiary">
                Tasks
              </h2>
              <ScopePill
                release={
                  scoped
                    ? { id: scoped.id, title: scoped.title, artistName: scoped.artistName }
                    : null
                }
                onClear={() => setScopeId(null)}
              />
            </div>

            <div className="space-y-4">
              {sectionOrder.map((sectionKey) => {
                const sectionTasks = sections[sectionKey];
                return (
                  <div
                    key={sectionKey}
                    className="border border-stroke-default bg-bg-surface"
                  >
                    <div className="flex items-baseline justify-between gap-3 border-b border-stroke-subtle px-4 py-3">
                      <p
                        className={`text-sm font-semibold ${
                          sectionKey === 'overdue'
                            ? 'text-status-error'
                            : 'text-content-primary'
                        }`}
                      >
                        {getTaskSectionLabel(sectionKey)}
                        <span className="ml-2 font-normal text-content-tertiary">
                          ({sectionTasks.length})
                        </span>
                      </p>
                    </div>
                    {sectionTasks.length === 0 ? (
                      <div className="px-4 py-6">
                        <p className="text-xs text-content-tertiary">
                          {getTaskSectionDescription(sectionKey)}
                        </p>
                      </div>
                    ) : (
                      <div>
                        {sectionTasks.map((task) => (
                          <TaskRow key={task.id} task={task} />
                        ))}
                      </div>
                    )}
                  </div>
                );
              })}
            </div>
          </aside>
        </div>
      </div>
    </main>
  );
}
