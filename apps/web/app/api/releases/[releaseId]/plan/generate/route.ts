import { NextRequest, NextResponse } from 'next/server';

import {
  PLANNER_MAX_RETRIES,
  PLANNER_TIMEOUT_MS,
  PLAN_DRAFTS_TABLE,
  RELEASES_TABLE,
  classifyPlannerFailure,
  countAutoGeneratedTasks,
  createAdminClient,
  getPlannerTemplate,
  isReleasePlannerEnabled,
  loadOwnedRelease,
  loadPlanDraft,
  loadPlannerTeam,
  requireActiveAuthenticatedUser,
  toAssignableMembers,
  todayYmd,
} from '../_shared';
import { generateStructuredAiOutput, isAiConfigured } from '@/lib/ai/provider';
import {
  applyDeltaToDraft,
  buildDraftFromTemplate,
  buildPlannerMessages,
  parsePlannerAiDelta,
  parseReleasePlanIntake,
  toPromptTasks,
  validatePlannerDelta,
  type PlannerAiDelta,
  type ReleasePlanDraftDoc,
} from '@/lib/release-planning';

// Same arithmetic as the route this supersedes. Vercel's plan-default function
// timeout (10-15s) would kill the invocation before the provider's retry
// budget produces a handled failure, and 60 is the Hobby-plan ceiling, so the
// budget has to fit inside it: 2 attempts x PLANNER_TIMEOUT_MS + ~1.5s backoff
// + auth/DB pre-work is about 55s worst case. Raising either constant means
// redoing this math.
export const maxDuration = 60;

/**
 * POST — turn the intake answers into a draft plan.
 *
 * The order matters. The answers are saved before the model is called, so a
 * manager who hits a bad minute still has their seven answers when they retry.
 * The deterministic draft is built before the model is called too, so a
 * failure downgrades to "here is the standard playbook plan" rather than
 * losing the whole flow at its front door.
 */
export async function POST(
  request: NextRequest,
  context: { params: Promise<{ releaseId: string }> }
) {
  if (!isReleasePlannerEnabled()) {
    return NextResponse.json({ error: 'Not found.' }, { status: 404 });
  }

  const auth = await requireActiveAuthenticatedUser(request);
  if ('error' in auth) return auth.error;

  const { releaseId } = await context.params;
  if (!releaseId) {
    return NextResponse.json({ error: 'Release id is required.' }, { status: 400 });
  }

  const body = (await request.json().catch(() => null)) as
    | { intake?: unknown; replace?: unknown }
    | null;
  if (!body) {
    return NextResponse.json({ error: 'A JSON body with intake answers is required.' }, { status: 400 });
  }

  const intakeResult = parseReleasePlanIntake(body.intake);
  if (!intakeResult.ok) {
    return NextResponse.json({ error: intakeResult.error }, { status: 400 });
  }
  const intake = intakeResult.intake;
  const replace = body.replace === true;

  const adminClient = createAdminClient(auth.supabaseUrl);
  if (!adminClient) {
    return NextResponse.json({ error: 'Server environment is not configured' }, { status: 500 });
  }

  const loaded = await loadOwnedRelease(adminClient, releaseId, auth.user.id);
  if ('error' in loaded) return loaded.error;
  const release = loaded.release;

  // --- Refuse to stack a plan on top of something that already exists --------

  const existing = await loadPlanDraft(adminClient, releaseId, auth.user.id);
  if ('error' in existing) return existing.error;
  if (existing.draft) {
    if (existing.draft.status === 'approved') {
      return NextResponse.json(
        { error: 'This release already has an approved plan.' },
        { status: 409 }
      );
    }
    if (!replace) {
      // A second click, a double submit, or a stale tab. The client asks again
      // with replace when the manager really means "start over".
      return NextResponse.json(
        { error: 'This release already has a draft plan.', code: 'draft_exists' },
        { status: 409 }
      );
    }
  }

  const taskCount = await countAutoGeneratedTasks(adminClient, releaseId);
  if ('error' in taskCount) return taskCount.error;
  if (taskCount.count > 0) {
    return NextResponse.json(
      { error: 'This release already has a rollout plan.' },
      { status: 409 }
    );
  }

  // --- Save the answers first -------------------------------------------------

  const contextSave = await adminClient
    .from(RELEASES_TABLE)
    .update({ release_context: intake })
    .eq('id', releaseId)
    .eq('owner_user_id', auth.user.id);
  if (contextSave.error) {
    console.error('[plan] could not save intake answers:', contextSave.error);
    // Non-fatal: the answers also travel inside the draft document below, so
    // the plan is still correct. Only the prefill for a future re-run is lost.
  }

  // --- The deterministic draft ------------------------------------------------

  const template = getPlannerTemplate();
  let doc: ReleasePlanDraftDoc = buildDraftFromTemplate({
    template,
    intake,
    ownerUserId: auth.user.id,
    generatedAt: new Date().toISOString(),
  });

  // --- Tailoring, if there is a model to tailor with --------------------------

  let delta: PlannerAiDelta | null = null;

  if (!isAiConfigured()) {
    doc = { ...doc, ai: { applied: false, rationale: null, failure: 'not_configured' } };
  } else {
    const team = await loadPlannerTeam(adminClient, releaseId, auth.user);
    const assignable = toAssignableMembers(team.ok ? team.members : []);

    const messages = buildPlannerMessages({
      release: {
        title: release.title || '',
        artistName: release.artist_name || intake.artist_name,
        releaseDate: release.release_date || intake.release_date,
      },
      intake,
      tasks: toPromptTasks(doc.tasks),
      members: assignable.prompt,
      todayYmd: todayYmd(),
    });

    try {
      delta = await generateStructuredAiOutput<PlannerAiDelta>({
        messages,
        timeoutMs: PLANNER_TIMEOUT_MS,
        maxRetries: PLANNER_MAX_RETRIES,
        model: process.env.AI_PLANNER_MODEL || undefined,
        parse: parsePlannerAiDelta,
        invalidFormatMessage: 'The response was not the expected JSON.',
      });
    } catch (error) {
      const failure = classifyPlannerFailure(error);
      console.error('[plan] tailoring failed for release', releaseId, failure, error);
      doc = { ...doc, ai: { applied: false, rationale: null, failure } };
    }

    if (delta) {
      const validation = validatePlannerDelta(
        delta,
        doc.tasks.map((task) => ({ id: task.id, optional: task.optional })),
        Array.from(assignable.ids)
      );
      if (validation.ok) {
        doc = applyDeltaToDraft(doc, delta);
      } else {
        // One bad reference means the whole response is untrustworthy, so none
        // of it is applied. The manager still gets the playbook plan.
        console.error('[plan] tailoring rejected for release', releaseId, validation.error);
        delta = null;
        doc = { ...doc, ai: { applied: false, rationale: null, failure: 'invalid_output' } };
      }
    }
  }

  // --- Save the draft ---------------------------------------------------------

  const { data, error } = await adminClient
    .from(PLAN_DRAFTS_TABLE)
    .upsert(
      {
        owner_user_id: auth.user.id,
        release_id: releaseId,
        status: 'draft',
        doc,
        approved_at: null,
        approved_task_count: null,
      },
      { onConflict: 'release_id' }
    )
    .select('id,status,updated_at')
    .single();

  if (error) {
    return NextResponse.json(
      { error: error.message || 'Could not save the plan draft.' },
      { status: 500 }
    );
  }

  if (delta) {
    const audit = await adminClient
      .from(RELEASES_TABLE)
      .update({ ai_tailoring_response: { ...delta, tailored_at: new Date().toISOString() } })
      .eq('id', releaseId);
    if (audit.error) {
      console.error('[plan] draft saved but the audit record did not:', audit.error);
    }
  }

  const row = data as { id: string; status: string; updated_at: string | null };

  return NextResponse.json({
    draft: {
      id: row.id,
      status: row.status === 'approved' ? 'approved' : 'draft',
      doc,
      updatedAt: row.updated_at || '',
      approvedAt: null,
    },
  });
}
