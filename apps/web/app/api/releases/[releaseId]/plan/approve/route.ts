import { NextRequest, NextResponse } from 'next/server';

import {
  PLAN_DRAFTS_TABLE,
  RELEASES_TABLE,
  countAutoGeneratedTasks,
  createAdminClient,
  isReleasePlannerEnabled,
  loadOwnedRelease,
  loadPlanDraft,
  loadPlannerTeam,
  requireActiveAuthenticatedUser,
  toAssignableMembers,
} from '../_shared';
import { instantiateDraftPlan, PlanApprovalError } from '@/lib/release-planning-server';
import { writePlannerPending } from '@/lib/release-planner-pending';
import { writeTemplatePending } from '@/lib/release-template-pending';

/**
 * POST — approve the draft and schedule the plan.
 *
 * The single irreversible step in the planner, so it is the careful one:
 *
 *  - The draft is read from the database, never from the request. A client
 *    cannot approve a plan the server has not seen.
 *  - The row is CLAIMED with a conditional update before any task is written,
 *    so two clicks or two tabs cannot both schedule the same plan. If the
 *    insert then fails, the claim is released and nothing was created.
 *  - A teammate who left the team does not block approval. Their tasks come
 *    back to the owner and the response says so.
 */
export async function POST(
  request: NextRequest,
  context: { params: Promise<{ releaseId: string }> }
) {
  if (!isReleasePlannerEnabled()) {
    return NextResponse.json({ error: 'Not found.' }, { status: 404 });
  }

  const auth = await requireActiveAuthenticatedUser(request);
  if ('error' in auth) return auth.error;

  const { releaseId } = await context.params;
  if (!releaseId) {
    return NextResponse.json({ error: 'Release id is required.' }, { status: 400 });
  }

  const adminClient = createAdminClient(auth.supabaseUrl);
  if (!adminClient) {
    return NextResponse.json({ error: 'Server environment is not configured' }, { status: 500 });
  }

  const loaded = await loadOwnedRelease(adminClient, releaseId, auth.user.id);
  if ('error' in loaded) return loaded.error;
  const release = loaded.release;

  const releaseDate = release.release_date ? String(release.release_date).slice(0, 10) : '';
  if (!releaseDate) {
    // Every task is dated from release day, so there is nothing to schedule
    // against until one exists.
    return NextResponse.json(
      { error: 'Set a release date before approving the plan.' },
      { status: 400 }
    );
  }

  const existing = await loadPlanDraft(adminClient, releaseId, auth.user.id);
  if ('error' in existing) return existing.error;
  if (!existing.draft) {
    return NextResponse.json({ error: 'No plan draft to approve.' }, { status: 404 });
  }
  if (existing.draft.status === 'approved') {
    return NextResponse.json({ error: 'This plan was already approved.' }, { status: 409 });
  }

  const taskCount = await countAutoGeneratedTasks(adminClient, releaseId);
  if ('error' in taskCount) return taskCount.error;
  if (taskCount.count > 0) {
    return NextResponse.json(
      { error: 'This release already has a rollout plan.' },
      { status: 409 }
    );
  }

  const team = await loadPlannerTeam(adminClient, releaseId, auth.user);
  if (!team.ok) {
    return NextResponse.json(
      { error: 'Could not work out where to file these activities. Try again.' },
      { status: 500 }
    );
  }
  const assignable = toAssignableMembers(team.members);
  // The owner can always hold a task, whatever the membership rows say.
  assignable.ids.add(auth.user.id);

  // --- Claim the draft before writing anything --------------------------------

  const approvedAt = new Date();
  const claim = await adminClient
    .from(PLAN_DRAFTS_TABLE)
    .update({ status: 'approved', approved_at: approvedAt.toISOString() })
    .eq('id', existing.draft.id)
    .eq('owner_user_id', auth.user.id)
    .eq('status', 'draft')
    .select('id');

  if (claim.error) {
    return NextResponse.json(
      { error: claim.error.message || 'Could not approve the plan.' },
      { status: 500 }
    );
  }
  if ((claim.data || []).length === 0) {
    // Someone else got there first. Their tasks are the real ones.
    return NextResponse.json({ error: 'This plan was already approved.' }, { status: 409 });
  }

  // --- Create the tasks -------------------------------------------------------

  let created: { tasksCreated: number; taskIds: string[]; warnings: string[] };
  try {
    created = await instantiateDraftPlan({
      doc: existing.draft.doc,
      draftId: existing.draft.id,
      releaseId,
      releaseDate,
      workspaceId: team.workspaceId,
      ownerUserId: auth.user.id,
      assignableUserIds: assignable.ids,
      approvedAtMs: approvedAt.getTime(),
      supabaseClient: adminClient,
    });
  } catch (error) {
    // Release the claim so the draft is still there to fix and retry.
    const release_ = await adminClient
      .from(PLAN_DRAFTS_TABLE)
      .update({ status: 'draft', approved_at: null })
      .eq('id', existing.draft.id);
    if (release_.error) {
      console.error('[plan] could not release the approval claim:', release_.error);
    }

    if (error instanceof PlanApprovalError && error.reason === 'empty_plan') {
      return NextResponse.json(
        { error: 'This plan has no tasks left. Add one before approving.' },
        { status: 400 }
      );
    }

    console.error('[plan] approval failed for release', releaseId, error);
    return NextResponse.json(
      { error: 'Could not schedule the plan. Your draft is untouched. Try again.' },
      { status: 500 }
    );
  }

  // --- Settle the release -----------------------------------------------------

  // Clear both pending markers. `planner_pending` is this feature's own, and
  // `template_pending` matters because a release created before the planner
  // shipped can still be planned here: left set, the schedule route would
  // instantiate a second, duplicate set of tasks the next time its date moved.
  const nextMetadata = writeTemplatePending(
    writePlannerPending(release.metadata, false),
    false
  );

  const settle = await adminClient
    .from(RELEASES_TABLE)
    .update({ metadata: nextMetadata })
    .eq('id', releaseId)
    .eq('owner_user_id', auth.user.id);
  if (settle.error) {
    console.error('[plan] tasks created but the release flags did not clear:', settle.error);
  }

  const stamp = await adminClient
    .from(PLAN_DRAFTS_TABLE)
    .update({ approved_task_count: created.tasksCreated })
    .eq('id', existing.draft.id);
  if (stamp.error) {
    console.error('[plan] tasks created but the draft count did not stamp:', stamp.error);
  }

  return NextResponse.json({
    tasksCreated: created.tasksCreated,
    taskIds: created.taskIds,
    warnings: created.warnings,
  });
}
