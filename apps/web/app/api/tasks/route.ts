import { NextRequest, NextResponse } from 'next/server';
import { groupTasksIntoSections } from '@/lib/tasks';
import {
  TASKS_TABLE,
  buildReadOnlyResponse,
  buildTaskSchemaResponse,
  createTaskNotification,
  requireAuthenticatedAdmin,
  requireAuthenticatedAdminOrInternal,
  isTaskSchemaMissingError,
  isReadOnlyWorkspaceMember,
  loadWorkspaceAccessContext,
  ensureWorkspaceAccess,
  loadTaskDetail,
  type TaskRow,
} from '@/lib/tasks-server';
import { TaskService } from '@/lib/services/task-service';
import { ASSIGN_OUTSIDE_TEAM_MESSAGE, isTeamAssignee } from '@/lib/task-assignee-server';

// Allowed POST body fields. Same allowlist discipline as the PATCH route —
// only `assignedToUserId` is accepted for assignee writes (the legacy
// `assigned_to` workspace_members column is deprecated for new writes).
const TASK_POST_ALLOWED_FIELDS = new Set([
  'title',
  'description',
  'releaseId',
  'groupId',
  'workspaceId',
  'assignedToUserId',
  'dueDate',
  'priority',
  'status',
  'state',
  'requirement',
  'dependencies',
  'autoGenerated',
  'source',
  'groupName',
  'groupColor',
]);

function validateTaskPostBody(body: unknown): { ok: true } | { error: string } {
  if (!body || typeof body !== 'object') {
    return { error: 'Request body must be a JSON object.' };
  }

  for (const key of Object.keys(body as Record<string, unknown>)) {
    if (!TASK_POST_ALLOWED_FIELDS.has(key)) {
      return { error: `Unknown field: ${key}` };
    }
  }

  return { ok: true };
}

export async function GET(request: NextRequest) {
  const auth = await requireAuthenticatedAdmin(request);
  if ('error' in auth) return auth.error;

  const { adminClient } = auth;

  const taskService = new TaskService(adminClient);

  try {
    const access = await loadWorkspaceAccessContext(adminClient, auth.user);
    if (!access.membershipIds.length) {
      return NextResponse.json({ tasks: [], sections: groupTasksIntoSections([]) });
    }

    const releaseId = request.nextUrl.searchParams.get('release');
    const priority = request.nextUrl.searchParams.get('priority') || undefined;
    const status = request.nextUrl.searchParams.get('status') || undefined;
    const mineOnly = request.nextUrl.searchParams.get('mine') === '1';

    const tasks = await taskService.getTasksForUser(auth.user.id, access.workspaceIds, {
      releaseId,
      priority,
      status,
      mineOnly,
    });

    const createdTasksResult = await adminClient
      .from(TASKS_TABLE)
      .select('id', { count: 'exact', head: true })
      .in('workspace_id', access.workspaceIds)
      .eq('created_by', auth.user.id);

    const createdTaskCount = createdTasksResult.count || 0;

    return NextResponse.json({
      tasks,
      sections: groupTasksIntoSections(tasks),
      createdTaskCount,
    });
  } catch (error) {
    if (isTaskSchemaMissingError(error)) return buildTaskSchemaResponse();
    return NextResponse.json(
      { error: error instanceof Error ? error.message : 'Could not load tasks.' },
      { status: 500 }
    );
  }
}

export async function POST(request: NextRequest) {
  // *OrInternal: the Chappi/MCP tool layer creates tasks by calling this route
  // internally, so it also accepts the MCP internal actor (URG-183).
  const auth = await requireAuthenticatedAdminOrInternal(request);
  if ('error' in auth) return auth.error;

  const { adminClient } = auth;

  const taskService = new TaskService(adminClient);

  try {
    const body = await request.json();
    const validation = validateTaskPostBody(body);
    if ('error' in validation) {
      return NextResponse.json({ error: validation.error }, { status: 400 });
    }

    const access = await loadWorkspaceAccessContext(adminClient, auth.user);
    const workspaceId = body.workspaceId || access.primaryWorkspaceId;

    if (!workspaceId) {
      return NextResponse.json({ error: 'Team not found.' }, { status: 404 });
    }

    const workspaceAccess = await ensureWorkspaceAccess(adminClient, workspaceId, auth.user, access);
    if ('error' in workspaceAccess) return workspaceAccess.error;

    // Guests are read-only (founder decision, 2026-07-23).
    if (isReadOnlyWorkspaceMember(access, workspaceId)) {
      return buildReadOnlyResponse();
    }

    // Whoever the activity is handed to has to be on this team. The PATCH route
    // has always checked; creating with an assignee did not, so any user id
    // on the platform was accepted. An absent or null assignee is fine (it
    // means "me" or "nobody" in createTask).
    if (typeof body.assignedToUserId === 'string' && body.assignedToUserId) {
      const allowed = await isTeamAssignee(adminClient, workspaceId, body.assignedToUserId);
      if (!allowed) {
        return NextResponse.json({ error: ASSIGN_OUTSIDE_TEAM_MESSAGE }, { status: 400 });
      }
    }

    const createdRow = await taskService.createTask(auth.user.id, workspaceId, body);

    // Map the row before returning (URG-234). `createTask` resolves to the raw
    // inserted row — snake_case `release_id`, `workspace_id`, `due_date` — but
    // every read path in the app returns the camelCase `Task` shape, and the
    // client appends this response straight into `useTaskStore`. A snake_case
    // object in that list has no `releaseId`, so it failed every
    // `task.releaseId === scopedReleaseId` filter and the activity stayed
    // invisible until a reload re-fetched it properly mapped.
    //
    // `loadTaskDetail` is the same mapper the sibling PATCH route already runs
    // over its updated row, so create and update now return identical shapes.
    const task = createdRow
      ? await loadTaskDetail(adminClient, createdRow as TaskRow, auth.user.id)
      : null;

    // Creating an activity ALREADY assigned to a teammate is the same "you
    // have new work" moment as reassigning one, and until 2026-08-29 it
    // notified nobody — only the PATCH route's reassignment did. Same guard
    // as there: never for the creator assigning to themself (which is also
    // every template-instantiated task). createTaskNotification carries the
    // bell row, the push mirror and the assignment email, and swallows its
    // own failures.
    const createdTaskId = String((createdRow as TaskRow | null)?.id || '');
    const createdAssigneeId = String(
      (createdRow as { assigned_to_user_id?: string } | null)?.assigned_to_user_id || ''
    );
    if (createdTaskId && createdAssigneeId && createdAssigneeId !== auth.user.id) {
      void createTaskNotification(adminClient, {
        userId: createdAssigneeId,
        type: 'task_assigned',
        taskId: createdTaskId,
        actorId: auth.user.id,
      });
    }

    return NextResponse.json({ task });
  } catch (error) {
    if (isTaskSchemaMissingError(error)) return buildTaskSchemaResponse();
    return NextResponse.json(
      { error: error instanceof Error ? error.message : 'Could not create task.' },
      { status: 500 }
    );
  }
}
