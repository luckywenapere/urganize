// SERVER-ONLY: moves a rollout's plan so it stays lined up with release day.
//
// The decisions live in lib/plan-dates.ts (pure, tested); this module turns
// them into writes. Called by POST /api/releases/[releaseId]/schedule, the ONE
// place a rollout's date changes, right after the new date is saved.
//
// Four properties worth keeping:
//
//  - SCOPED TO THE ONE ROLLOUT, and never touching a finished activity: every
//    write carries `release_id = …` and `status <> 'done'`, so an activity
//    somebody ticks off while this runs is not dragged along with the rest.
//  - ONE WRITE PER SHARED DUE DATE, not one per activity. A 64-activity single
//    has about fifteen distinct due dates, so this is fifteen statements, keyed
//    by id so nothing depends on comparing stored timestamps as strings.
//  - IT NEVER THROWS. The date is already saved by the time this runs, and the
//    user got the thing they asked for; a write that fails is COUNTED and
//    reported so the caller can say so, rather than surfacing as a 500 over a
//    save that worked. (The schedule route's own philosophy: write the date
//    first and independently.)
//  - IT DOES NOT RETRY ITSELF INTO A DOUBLE MOVE. The distance is measured
//    from the release date the row held before this save. A retry after a
//    partial failure measures from the NEW date, finds nothing to move, and
//    leaves the stragglers for a person to drag — worse than perfect, much
//    better than moving half the plan twice.

import type { SupabaseClient } from '@supabase/supabase-js';
import { inferPlanReleaseDate, planActivityShift, type PlanDateTask } from '@/lib/plan-dates';

const TASKS_TABLE = 'tasks';

/** How many due-date groups are written at once. Small on purpose: this runs
 * inside a request, beside everything else the request does. */
const WRITE_CONCURRENCY = 5;

export type AlignPlanResult = {
  /** Activities whose due date actually changed. */
  moved: number;
  /** Activities that should have moved but whose write failed. */
  failed: number;
  keptDone: number;
  keptManual: number;
  deltaDays: number;
  /** Where the old release day came from: the row's own previous date, or
   * read back off the plan because the rollout had none. Null when there was
   * no way to tell, in which case nothing moved. */
  anchor: 'previous' | 'inferred' | null;
  fromDate: string | null;
  /** True when the plan itself could not be read. Nothing moved. */
  loadFailed: boolean;
};

/** One task row, as the planning helpers want it. Exported for tests. */
export function toPlanDateTask(row: Record<string, unknown>): PlanDateTask {
  const metadata = (row.metadata ?? {}) as Record<string, unknown>;
  const template = (metadata.template ?? {}) as Record<string, unknown>;
  // Both keys: instantiate.ts writes task_id, and readTemplateTaskId in
  // lib/tasks-server.ts reads either for rows written under the older name.
  const stepId = template.task_id ?? template.template_task_id;
  return {
    id: String(row.id ?? ''),
    dueDate: typeof row.due_date === 'string' && row.due_date ? row.due_date : null,
    status: String(row.status ?? ''),
    autoGenerated: row.auto_generated === true,
    templateTaskId: typeof stepId === 'string' && stepId ? stepId : null,
    templateId: typeof template.template_id === 'string' ? template.template_id : null,
  };
}

async function loadPlanTasks(
  adminClient: SupabaseClient,
  releaseId: string
): Promise<PlanDateTask[] | null> {
  const { data, error } = await adminClient
    .from(TASKS_TABLE)
    .select('id,due_date,status,auto_generated,metadata')
    .eq('release_id', releaseId);
  if (error) {
    console.error(`[plan-dates] could not read the plan for ${releaseId}:`, error.message);
    return null;
  }
  return ((data ?? []) as Record<string, unknown>[]).map(toPlanDateTask);
}

export async function alignPlanToReleaseDate(
  adminClient: SupabaseClient,
  params: {
    releaseId: string;
    /** The release date BEFORE this save, YYYY-MM-DD, or null if it had none. */
    previousDate: string | null;
    /** The release date just saved, YYYY-MM-DD. */
    nextDate: string;
    /** Breaks a tie between playbooks when reading the old date off the plan. */
    releaseType?: string | null;
  }
): Promise<AlignPlanResult> {
  const { releaseId, previousDate, nextDate, releaseType } = params;
  const nothing: AlignPlanResult = {
    moved: 0,
    failed: 0,
    keptDone: 0,
    keptManual: 0,
    deltaDays: 0,
    anchor: null,
    fromDate: null,
    loadFailed: false,
  };

  const tasks = await loadPlanTasks(adminClient, releaseId);
  if (!tasks) return { ...nothing, loadFailed: true };
  if (tasks.length === 0) return nothing;

  let fromDate = previousDate;
  let anchor: AlignPlanResult['anchor'] = previousDate ? 'previous' : null;
  if (!fromDate) {
    // A rollout with activities and no date: the state the rename bug left
    // rollouts in. The plan remembers the day it was built for.
    const inferred = inferPlanReleaseDate(tasks, { releaseType });
    if (!inferred) return nothing;
    fromDate = inferred.date;
    anchor = 'inferred';
  }

  const shift = planActivityShift(tasks, fromDate, nextDate);
  const base = {
    ...nothing,
    keptDone: shift.keptDone,
    keptManual: shift.keptManual,
    deltaDays: shift.deltaDays,
    anchor,
    fromDate,
  };
  if (shift.moves.length === 0) return base;

  const nowIso = new Date().toISOString();
  let moved = 0;
  let failed = 0;

  for (let start = 0; start < shift.moves.length; start += WRITE_CONCURRENCY) {
    const batch = shift.moves.slice(start, start + WRITE_CONCURRENCY);
    const results = await Promise.all(
      batch.map(async (move) => {
        try {
          const { data, error } = await adminClient
            .from(TASKS_TABLE)
            .update({ due_date: move.toDue, updated_at: nowIso })
            .eq('release_id', releaseId)
            .in('id', move.taskIds)
            .neq('status', 'done')
            .select('id');
          if (error) {
            console.error(`[plan-dates] could not move activities on ${releaseId}:`, error.message);
            return { moved: 0, failed: move.taskIds.length };
          }
          return { moved: Array.isArray(data) ? data.length : 0, failed: 0 };
        } catch (error) {
          console.error(`[plan-dates] could not move activities on ${releaseId}:`, error);
          return { moved: 0, failed: move.taskIds.length };
        }
      })
    );
    for (const result of results) {
      moved += result.moved;
      failed += result.failed;
    }
  }

  return { ...base, moved, failed };
}
