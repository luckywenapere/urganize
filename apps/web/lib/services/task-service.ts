import { SupabaseClient } from '@supabase/supabase-js';
import { 
  TASKS_TABLE, 
  loadTasks, 
  loadTaskDetail, 
  type TaskRow 
} from '@/lib/tasks-server';
import { Task, TaskStatus, TaskPriority, TaskRequirement } from '@/types/tasks';
import { ReleasePipelineState } from '@/types/releases';

export class TaskService {
  constructor(private adminClient: SupabaseClient) {}

  async getTasksForUser(userId: string, workspaceIds: string[], filters: {
    releaseId?: string | null;
    priority?: string;
    status?: string;
  } = {}) {
    let query = this.adminClient
      .from(TASKS_TABLE)
      .select('id,workspace_id,group_id,release_id,created_by,assigned_to_user_id,assigned_to,title,description,status,priority,due_date,completed_at,position,requirement,dependencies,state,auto_generated,metadata,created_at,updated_at')
      .eq('assigned_to_user_id', userId)
      .in('workspace_id', workspaceIds)
      .order('due_date', { ascending: true, nullsFirst: false })
      .order('position', { ascending: true });

    if (filters.releaseId) query = query.eq('release_id', filters.releaseId);
    if (filters.priority) query = query.eq('priority', filters.priority);
    if (filters.status) query = query.eq('status', filters.status);

    const { data, error } = await query;
    if (error) throw error;

    return loadTasks(this.adminClient, (data || []) as TaskRow[], userId);
  }

  async getWorkspaceTasks(workspaceId: string, userId: string, filters: {
    releaseId?: string | null;
    priority?: string;
    status?: string;
  } = {}) {
    let query = this.adminClient
      .from(TASKS_TABLE)
      .select('id,workspace_id,group_id,release_id,created_by,assigned_to_user_id,assigned_to,title,description,status,priority,due_date,completed_at,position,requirement,dependencies,state,auto_generated,metadata,created_at,updated_at')
      .eq('workspace_id', workspaceId)
      .order('updated_at', { ascending: false });

    if (filters.releaseId) query = query.eq('release_id', filters.releaseId);
    if (filters.priority) query = query.eq('priority', filters.priority);
    if (filters.status) query = query.eq('status', filters.status);

    const { data, error } = await query;
    if (error) throw error;

    return loadTasks(this.adminClient, (data || []) as TaskRow[], userId);
  }

  async getTaskById(taskId: string, userId: string) {
    const { data, error } = await this.adminClient
      .from(TASKS_TABLE)
      .select('id,workspace_id,group_id,release_id,created_by,assigned_to_user_id,assigned_to,title,description,status,priority,due_date,completed_at,position,requirement,dependencies,state,auto_generated,metadata,created_at,updated_at')
      .eq('id', taskId)
      .maybeSingle();

    if (error) throw error;
    if (!data) return null;

    return loadTaskDetail(this.adminClient, data as TaskRow, userId);
  }

  async updateTask(taskId: string, userId: string, updates: Partial<TaskRow>) {
    const { data, error } = await this.adminClient
      .from(TASKS_TABLE)
      .update({
        ...updates,
        updated_at: new Date().toISOString(),
      })
      .eq('id', taskId)
      .select()
      .maybeSingle();
    if (error) throw error;
    return data;
  }

  async createTask(userId: string, workspaceId: string, data: {
    title: string;
    description?: string | null;
    releaseId?: string | null;
    groupId?: string | null;
    priority?: TaskPriority;
    dueDate?: string | null;
    status?: TaskStatus;
    requirement?: TaskRequirement | null;
    dependencies?: string[];
    state?: ReleasePipelineState;
    autoGenerated?: boolean;
    metadata?: any;
    assignedTo?: string | null;
  }) {
    const { data: result, error } = await this.adminClient
      .from(TASKS_TABLE)
      .insert({
        workspace_id: workspaceId,
        created_by: userId,
        assigned_to_user_id: data.assignedTo ?? userId,
        title: data.title,
        description: data.description,
        release_id: data.releaseId,
        group_id: data.groupId,
        priority: data.priority || 'none',
        due_date: data.dueDate,
        status: data.status || 'todo',
        requirement: data.requirement,
        dependencies: data.dependencies || [],
        state: data.state || 'idea',
        auto_generated: data.autoGenerated || false,
        metadata: data.metadata || {},
        updated_at: new Date().toISOString(),
      })
      .select()
      .maybeSingle();
    if (error) throw error;
    return result;
  }

  async deleteTask(taskId: string, workspaceId: string) {
    const { error } = await this.adminClient
      .from(TASKS_TABLE)
      .delete()
      .eq('id', taskId)
      .eq('workspace_id', workspaceId);

    if (error) throw error;
    return true;
  }
}
