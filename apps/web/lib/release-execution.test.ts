import { describe, expect, it } from 'vitest';
import { getTaskCompletionBlocker, isRequirementSatisfied } from './release-execution';
import {
  TASK_DONE_STATUS,
  TASK_LOCKED_STATUS,
  TASK_PENDING_STATUS,
  type ExecutionTask,
} from './execution-types';

/**
 * The dependency-blocker gate — the rule that decides whether ticking an
 * activity is allowed at all.
 *
 * It had NO coverage until 2026-09-07, which is worth knowing because of what
 * depends on it: the UrgAns release planner's whole parity claim is that an
 * approved plan's rows "are indistinguishable from template-instantiated
 * ones", and this function plus the cascade beside it is where that claim is
 * either true or not. A field-by-field read of the two write paths
 * (`instantiate.ts` vs `release-planning-server.ts`) showed the `dependencies`
 * column identically shaped on both — which is a reason to EXPECT parity, not
 * evidence of it. These tests are the evidence for the gate half.
 *
 * Two callers share it and must keep sharing it: `useTaskStore.completeTask`
 * (the checkbox) and `TaskService.completeTaskWithCascade` (the agent). The
 * PATCH route deliberately enforces nothing, so a tool hitting a raw update
 * would bypass the gate entirely — which is exactly why the service method
 * exists.
 */

/** A template-instantiated activity: the shape `instantiate.ts` writes. */
function templateTask(over: Partial<ExecutionTask> & { id: string }): ExecutionTask {
  return {
    // No `id` here: `over` is typed as carrying one and the spread below is
    // what supplies it. Naming it twice is what TS2783 flags.
    workspaceId: 'ws-1',
    groupId: null,
    releaseId: 'rel-1',
    createdBy: 'owner-1',
    assignedToUserId: 'owner-1',
    assignedTo: null,
    title: 'A template activity',
    description: 'Why this matters.',
    status: TASK_PENDING_STATUS,
    priority: 'none',
    dueDate: '2026-10-01',
    completedAt: null,
    position: 0,
    requirement: null,
    dependencies: [],
    state: 'planning',
    autoGenerated: true,
    taskType: 'task',
    templateTaskId: 'w5_cover_art_final_approved',
    durationDays: 1,
    compressedRunway: false,
    groupName: null,
    ...over,
  } as ExecutionTask;
}

/**
 * A manager-added activity inside an approved plan: the ONE shape that
 * legitimately differs from the template path. `release-planning-server.ts`
 * gives it only `task_type` and `compressed_runway`, because it claims no
 * template provenance it does not have — so `templateTaskId` and
 * `durationDays` are null and `description` came from the draft's `why`.
 */
function plannerTask(over: Partial<ExecutionTask> & { id: string }): ExecutionTask {
  return templateTask({
    templateTaskId: null,
    durationDays: null,
    description: 'Because the manager said so.',
    ...over,
  });
}

describe('getTaskCompletionBlocker', () => {
  it('lets a ready activity through', () => {
    const task = templateTask({ id: 't1' });
    expect(getTaskCompletionBlocker(task, [task])).toBeNull();
  });

  it('refuses a locked activity and names the chain', () => {
    const task = templateTask({ id: 't1', status: TASK_LOCKED_STATUS });
    expect(getTaskCompletionBlocker(task, [task])).toBe(
      'Complete the dependency chain first.'
    );
  });

  it('refuses an activity whose dependency is not done, naming it', () => {
    const blocker = templateTask({ id: 'dep', title: 'Master the record' });
    const task = templateTask({ id: 't1', dependencies: ['dep'] });
    expect(getTaskCompletionBlocker(task, [task, blocker])).toBe(
      'Waiting on Master the record.'
    );
  });

  it('names every unmet dependency, not just the first', () => {
    const one = templateTask({ id: 'd1', title: 'Master the record' });
    const two = templateTask({ id: 'd2', title: 'Approve the artwork' });
    const task = templateTask({ id: 't1', dependencies: ['d1', 'd2'] });
    expect(getTaskCompletionBlocker(task, [task, one, two])).toBe(
      'Waiting on Master the record, Approve the artwork.'
    );
  });

  it('lets it through once every dependency is done', () => {
    const one = templateTask({ id: 'd1', status: TASK_DONE_STATUS });
    const two = templateTask({ id: 'd2', status: TASK_DONE_STATUS });
    const task = templateTask({ id: 't1', dependencies: ['d1', 'd2'] });
    expect(getTaskCompletionBlocker(task, [task, one, two])).toBeNull();
  });

  it('counts only the dependencies that are NOT done', () => {
    const done = templateTask({ id: 'd1', status: TASK_DONE_STATUS, title: 'Done one' });
    const open = templateTask({ id: 'd2', title: 'Still open' });
    const task = templateTask({ id: 't1', dependencies: ['d1', 'd2'] });
    expect(getTaskCompletionBlocker(task, [task, done, open])).toBe(
      'Waiting on Still open.'
    );
  });

  it('skips a dependency id that resolves to nothing rather than blocking forever', () => {
    // A dangling id must not be readable as "unmet": there is no activity to
    // complete, so blocking on it would strand the row with no way out. The
    // planner's approval path translates draft ids to real row ids, so this is
    // the shape a translation miss would take.
    const task = templateTask({ id: 't1', dependencies: ['ghost'] });
    expect(getTaskCompletionBlocker(task, [task])).toBeNull();
  });

  it('being locked outranks naming the dependencies', () => {
    // Both conditions hold here. The chain message is the one that renders,
    // and it is the more useful of the two: a locked row is not the user's to
    // unblock one dependency at a time.
    const blocker = templateTask({ id: 'dep', title: 'Master the record' });
    const task = templateTask({
      id: 't1',
      status: TASK_LOCKED_STATUS,
      dependencies: ['dep'],
    });
    expect(getTaskCompletionBlocker(task, [task, blocker])).toBe(
      'Complete the dependency chain first.'
    );
  });

  it('refuses an unsatisfied requirement, quoting its spec', () => {
    const task = templateTask({
      id: 't1',
      requirement: { type: 'file_upload', spec: 'Upload the master.', satisfied: false },
    });
    expect(getTaskCompletionBlocker(task, [task])).toBe('Upload the master.');
  });

  it('falls back to generic copy when an unsatisfied requirement has no spec', () => {
    const task = templateTask({
      id: 't1',
      requirement: { type: 'approval', spec: '', satisfied: false },
    });
    expect(getTaskCompletionBlocker(task, [task])).toBe(
      'Complete the required proof before marking this done.'
    );
  });

  it('lets a satisfied requirement through', () => {
    const task = templateTask({
      id: 't1',
      requirement: { type: 'approval', spec: 'Signed off.', satisfied: true },
    });
    expect(getTaskCompletionBlocker(task, [task])).toBeNull();
  });

  it('checks dependencies before the requirement', () => {
    // An unmet dependency is somebody else's work and an unsatisfied
    // requirement is yours, so the dependency is the more actionable answer.
    const blocker = templateTask({ id: 'dep', title: 'Master the record' });
    const task = templateTask({
      id: 't1',
      dependencies: ['dep'],
      requirement: { type: 'file_upload', spec: 'Upload the master.', satisfied: false },
    });
    expect(getTaskCompletionBlocker(task, [task, blocker])).toBe(
      'Waiting on Master the record.'
    );
  });

  /**
   * The planner-parity question, asked directly.
   *
   * The two write paths differ in exactly two columns plus a metadata block
   * (`assigned_to_user_id`, `description`, `metadata.planner`), and a
   * manager-added activity additionally carries no `templateTaskId` and no
   * `durationDays`. If the gate read ANY of those, an approved plan would
   * behave differently from a template-instantiated one — which is the whole
   * thing the planner promises it does not do.
   */
  describe('parity between the two write paths', () => {
    it('gates an approved-plan activity exactly like a template one', () => {
      const dep = plannerTask({ id: 'dep', title: 'Master the record' });
      const planner = plannerTask({ id: 't1', dependencies: ['dep'] });
      const template = templateTask({ id: 't1', dependencies: ['dep'] });

      expect(getTaskCompletionBlocker(planner, [planner, dep])).toBe(
        getTaskCompletionBlocker(template, [template, dep])
      );
      expect(getTaskCompletionBlocker(planner, [planner, dep])).toBe(
        'Waiting on Master the record.'
      );
    });

    it('is unmoved by every field the two paths disagree about', () => {
      // Vary all four at once and require an identical verdict. This is the
      // structural half of the claim: the gate has no way to tell the paths
      // apart, so it cannot treat them differently.
      const base = templateTask({ id: 't1' });
      const varied = templateTask({
        id: 't1',
        assignedToUserId: 'someone-else',
        description: 'A why-line from a draft.',
        templateTaskId: null,
        durationDays: null,
      });
      expect(getTaskCompletionBlocker(varied, [varied])).toBe(
        getTaskCompletionBlocker(base, [base])
      );
    });

    it('blocks a template activity waiting on an approved-plan one, and the reverse', () => {
      // A real approved plan holds both kinds, so the graph is mixed. Neither
      // direction may be special-cased.
      const plannerDep = plannerTask({ id: 'p1', title: 'A hand-added step' });
      const templateTarget = templateTask({ id: 't1', dependencies: ['p1'] });
      expect(getTaskCompletionBlocker(templateTarget, [templateTarget, plannerDep])).toBe(
        'Waiting on A hand-added step.'
      );

      const templateDep = templateTask({ id: 't2', title: 'A playbook step' });
      const plannerTarget = plannerTask({ id: 'p2', dependencies: ['t2'] });
      expect(getTaskCompletionBlocker(plannerTarget, [plannerTarget, templateDep])).toBe(
        'Waiting on A playbook step.'
      );
    });
  });
});

describe('isRequirementSatisfied', () => {
  it('treats an absent requirement as satisfied', () => {
    // Most activities carry none, so the absence has to read as "nothing to
    // prove" rather than "unproven".
    expect(isRequirementSatisfied(null)).toBe(true);
    expect(isRequirementSatisfied(undefined)).toBe(true);
  });

  it('requires satisfied to be exactly true', () => {
    expect(
      isRequirementSatisfied({ type: 'approval', spec: 'Sign off.', satisfied: true })
    ).toBe(true);
    expect(
      isRequirementSatisfied({ type: 'approval', spec: 'Sign off.', satisfied: false })
    ).toBe(false);
  });
});
