/**
 * Planner v2 on the server: write a preview (no rows written) and use a plan
 * (the activities land). Called by POST /api/releases/[id]/plan/v2.
 *
 * Credits follow the existing planner logic (lib/release-plan-build-server.ts):
 * a team's first plan is free; otherwise a hold before and a charge after, by
 * the model calls actually made, so a quick plan (no model answer) costs
 * nothing. Using a plan makes no model call and is not charged.
 *
 * Saving reuses the plan document and instantiateDraftPlan, so a v2 plan is an
 * ordinary built plan to everything downstream (the plan summary, suggestions,
 * date re-flow): every task is core, first-up tasks are focus, and the v2 card
 * (built for, budget split, answers) rides on the document as `planner_v2`.
 */

