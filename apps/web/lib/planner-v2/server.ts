export const PLAN_V2_TIMEOUT_MS = 38_000;
export const PLAN_V2_DEADLINE_MS = 52_000;
export const PLAN_V2_MAX_OUTPUT_TOKENS = 6_000;

/**
 * The day the plan counts from. A dated rollout keeps its date. An undated one
 * stays undated (2026-10-26, Oyin: the planner never depends on a date): its
 * tasks are relative to release day until the "Set your release date" row is
 * used. A song already out takes a past date on the row, else the answer, else
 * a fair guess from "when did it come out".
 */
export function resolvePlanV2ReleaseDate(
  rowDate: string | null | undefined,
  answers: Pick<PlannerV2Answers, 'stage' | 'release_date' | 'out_when'>,
  todayYmd: string
): { releaseDate: string | null; fromAnswers: boolean } {
  const row = rowDate ? String(rowDate).slice(0, 10) : '';
  if (answers.stage === 'out') {
    if (row && daysBetween(row, todayYmd) >= 0) return { releaseDate: row, fromAnswers: false };
    if (answers.release_date && daysBetween(answers.release_date, todayYmd) >= 0) {
      return { releaseDate: answers.release_date, fromAnswers: true };
    }
    return { releaseDate: outReleaseDate(answers.out_when, todayYmd), fromAnswers: true };
  }
  if (row) return { releaseDate: row, fromAnswers: false };
  return { releaseDate: null, fromAnswers: false };
}

export type PreviewPlanV2Result =
  | { ok: true; written: WrittenPlanV2; releaseDate: string | null }
  | { ok: false; status: number; error: string; code?: string };

export async function previewPlanV2(
  admin: SupabaseClient,
  params: {
    release: PlannerReleaseRow;
    actor: { id: string; email?: string | null };
    answers: PlannerV2Answers;
    mode: PlanV2Mode;
    todayYmd: string;
    startedAt: number;
  }
): Promise<PreviewPlanV2Result> {
  const { release, actor, answers, mode, todayYmd, startedAt } = params;
  const { releaseDate } = resolvePlanV2ReleaseDate(release.release_date, answers, todayYmd);
  const artistFacts = await loadPlannerArtistFacts(admin, release.id);
  const ctx: PlanV2Context = { answers, releaseDate, todayYmd, artistFacts };
  const { template } = getPlannerTemplate(answers.release_type);

  const ownerTeam = await getTeamAccessForUser(actor.id, actor.email);
  const firstPlan = await isFirstPlanFreeForTeam(admin, 'release.draft_plan', ownerTeam.ownerUserId);
  const gate: EmbeddedRunGate =
    isCreditsEnabled() && firstPlan
      ? { metered: false }
      : await beginEmbeddedRun(admin, {
          workspaceId: ownerTeam.primaryWorkspaceId,
          ownerUserId: ownerTeam.ownerUserId,
          team: ownerTeam,
        });
  if (gate.metered && !gate.ok) {
    return { ok: false, status: 429, error: gate.message, code: 'out_of_credits' };
  }

  // Through the router (lib/ai/routed.ts), by surface: gpt-5.4 for a first
  // plan or another angle, its quick sibling for a tweak. With the router off
  // this is exactly lib/ai/planner-model.ts's model (AI_PLANNER_MODEL pins).
  const surface = planV2Surface(mode.kind);
  const model = legacyModelFor(surface);
  const collector = createUsageCollector(model ?? null);
  const requestId = `embedded:${randomUUID()}`;

  const written = await writePlanV2({
    ctx,
    title: release.title || '',
    template,
    mode,
    configured: isAiConfigured(),
    model,
    call: async (messages) => {
      return generateRoutedStructuredOutput<PlanV2>({
          surface,
          messages,
          // Normal sampling (> 0): two runs of the same answers differ. The
          // gateway ignores it for reasoning models, whose own default is 1.
          temperature: 0.9,
          timeoutMs: PLAN_V2_TIMEOUT_MS,
          maxRetries: 1,
          parse: parsePlanV2,
          invalidFormatMessage: 'The response was not the expected JSON.',
          jsonSchema: { name: 'rollout_plan', schema: PLAN_V2_JSON_SCHEMA },
          maxOutputTokens: PLAN_V2_MAX_OUTPUT_TOKENS,
          reasoningEffort: 'low',
          deadlineMs: startedAt + PLAN_V2_DEADLINE_MS,
          onUsage: collector.onUsage,
          onFailure: collector.onFailure,
        });
    },
    onWalletEmpty: () =>
      reportAiWalletEmpty(admin, {
        feature: 'planner',
        workspaceId: ownerTeam.primaryWorkspaceId,
        ownerUserId: ownerTeam.ownerUserId,
        actorUserId: actor.id,
      }),
  });

  const charge = await settleEmbeddedRun(admin, {
    gate,
    workspaceId: ownerTeam.primaryWorkspaceId,
    ownerUserId: ownerTeam.ownerUserId,
    actorUserId: actor.id,
    requestId,
    actionId: 'release.draft_plan',
    calls: collector.calls,
  });
  await recordRequestUsage(admin, {
    context: {
      requestId,
      feature: 'plan',
      workspaceId: ownerTeam.primaryWorkspaceId,
      ownerUserId: ownerTeam.ownerUserId,
      actorUserId: actor.id,
      releaseId: release.id,
    },
    calls: collector.calls,
    failures: collector.failures,
    creditsCharged: gate.metered && gate.ok ? charge.credits : 0,
  });

  return { ok: true, written, releaseDate };
}

const TAG_FOR_CHANNEL: Record<string, string[]> = {
  distribution: ['distribution'],
  spotify: ['editorial', 'marketing'],
  apple: ['editorial', 'marketing'],
  audiomack: ['editorial', 'marketing'],
  boomplay: ['editorial', 'marketing'],
  shows: ['event', 'marketing'],
  merch: ['physical'],
};

/** The v2 plan as a plan document every existing reader understands. */
export function planV2ToDoc(params: {
  plan: PlanV2;
  answers: PlannerV2Answers;
  source: PlanV2Source;
  releaseDate: string | null;
  ownerUserId: string;
  templateId: string;
  templateVersion: string;
  generatedAt: string;
}): ReleasePlanDraftDoc {
  const { plan, answers, source, releaseDate, ownerUserId } = params;
  const keyToId = new Map(plan.tasks.map((task) => [task.key, `v2_${task.key}`]));
  const tasks: DraftTask[] = plan.tasks.map((task) => {
    const extra = [task.done_when ? `Done when: ${task.done_when}` : '', task.cost_naira > 0 ? `Budget: ${formatNaira(task.cost_naira)}.` : '']
      .filter(Boolean)
      .join(' ');
    const tags = [...(TAG_FOR_CHANNEL[task.channel] ?? ['marketing']), `channel:${task.channel}`];
    if (task.offset_days === 0 && task.phase === 'release') tags.push('release_day');
    if (task.cost_naira > 0) tags.push('paid');
    return {
      id: keyToId.get(task.key) as string,
      template_task_id: null,
      origin: 'ai',
      // "Smart link", never "pre-save link" (Oyin, Oct 29, 2026, #850).
      title: smartLinkWording(task.title),
      why: [task.why, extra].filter(Boolean).join(' ').slice(0, 600),
      phase: derivePlanPhase(task.offset_days),
      offset_days: task.offset_days,
      duration_days: task.duration_days,
      role: task.owner_role,
      assignee_user_id: ownerUserId,
      optional: false,
      task_type: task.offset_days === 0 && task.phase === 'release' ? 'event_milestone' : 'task',
      tags,
      depends_on: task.depends_on.map((dep) => keyToId.get(dep)).filter((id): id is string => Boolean(id)),
      removed: false,
      removed_by: null,
      removed_reason: null,
      change_reason: null,
      assignee_basis: null,
      edited: false,
      focus: task.first_up,
      focus_reason: task.first_up ? 'First up' : null,
      key: true,
    };
  });

  return {
    schema_version: PLAN_DRAFT_SCHEMA_VERSION,
    template_id: params.templateId,
    template_version: params.templateVersion,
    release_type: answers.release_type,
    generated_at: params.generatedAt,
    generated_for_release_date: releaseDate,
    intake: toLegacyIntake(answers, releaseDate),
    ai: {
      applied: source !== 'fallback',
      rationale: plan.built_for.summary || null,
      failure: source === 'fallback' ? 'unavailable' : null,
      warnings: plan.warnings.slice(0, 5),
    },
    applied_exclusions: [],
    tasks,
    core_only: true,
    planner_v2: {
      version: 1,
      source,
      built_for: plan.built_for,
      budget: plan.budget,
      assumptions: plan.assumptions,
      answers,
    },
  };
}

export type ApplyPlanV2Result =
  | { ok: true; tasksCreated: number; releaseDate: string | null }
  | { ok: false; status: number; error: string; code?: string };

export async function applyPlanV2(
  admin: SupabaseClient,
  params: {
    release: PlannerReleaseRow;
    actor: { id: string; email?: string | null };
    answers: PlannerV2Answers;
    plan: PlanV2;
    source: PlanV2Source;
    todayYmd: string;
    loadTeam: () => Promise<{ ok: true; workspaceId: string; members: WorkspaceMember[] } | { ok: false }>;
    /**
     * Tasks that lead the plan, added after it is checked: a record's
     * "Finish ..." tasks (2026-10-27, lib/next-records-rollout.ts). They are
     * the team's own facts, so they never count against UrgAns's pace or size.
     */
    leadTasks?: PlanV2Task[];
  }
): Promise<ApplyPlanV2Result> {
  const { release, actor, answers, source, todayYmd } = params;
  const checked = params.plan;
  const releaseId = release.id;
  const { releaseDate, fromAnswers } = resolvePlanV2ReleaseDate(release.release_date, answers, todayYmd);

  // The plan came back from the browser: hold it to the same rules again.
  const issues = validatePlanV2(checked, { answers, releaseDate, todayYmd });
  if (issues.length) {
    return { ok: false, status: 400, error: 'This plan is out of date. Make it again.', code: 'invalid_plan' };
  }
  const plan: PlanV2 = params.leadTasks?.length ? { ...checked, tasks: [...params.leadTasks, ...checked.tasks] } : checked;

  const existingTasks = await countAutoGeneratedTasks(admin, releaseId);
  if ('error' in existingTasks) return { ok: false, status: 500, error: existingTasks.error };
  if (existingTasks.count > 0) {
    return { ok: false, status: 409, error: 'This rollout already has its plan.', code: 'tasks_exist' };
  }
  const existingRow = await readPlanRow(admin, releaseId);
  if ('error' in existingRow) return { ok: false, status: 500, error: existingRow.error };
  if (existingRow.row?.status === 'approved') {
    return { ok: false, status: 409, error: 'This rollout already has its plan.', code: 'tasks_exist' };
  }

  const intake = toLegacyIntake(answers, releaseDate);
  const contextSave = await admin
    .from('releases')
    .update({
      release_context: intake,
      release_type: answers.release_type,
      ...(fromAnswers ? { release_date: releaseDate } : {}),
    })
    .eq('id', releaseId)
    // The rollout's owner, not the actor (#854): a Manager plans rollouts that
    // the team owner owns. loadOwnedRelease already checked they may.
    .eq('owner_user_id', release.owner_user_id);
  if (contextSave.error && fromAnswers) {
    return { ok: false, status: 500, error: 'Could not save the release date. Try again.' };
  }

  const team = await params.loadTeam();
  if (!team.ok) return { ok: false, status: 500, error: 'Could not work out where to file these activities. Try again.' };
  const assignable = toAssignableMembers(team.members);

  const { template } = getPlannerTemplate(answers.release_type);
  let doc = planV2ToDoc({
    plan,
    answers,
    source,
    releaseDate,
    ownerUserId: actor.id,
    templateId: template.id,
    templateVersion: template.version,
    generatedAt: new Date().toISOString(),
  });

  // Teammates by role, the same heuristic the playbook plan uses.
  if (answers.team !== 'solo') {
    const history = await loadPastAssignments(admin, {
      workspaceId: team.workspaceId,
      ownerUserId: actor.id,
      excludeReleaseId: releaseId,
    });
    doc = applyOwnerProposals(
      doc,
      proposeTaskOwners({
        tasks: doc.tasks.map((task) => ({ id: task.id, templateTaskId: task.template_task_id, role: task.role })),
        history,
        members: assignable.assignable,
        creatorUserId: actor.id,
        memberNames: assignable.names,
      })
    );
  }

  const approvedAt = new Date();
  const approvedAtIso = approvedAt.toISOString();
  let planRowId: string;
  if (!existingRow.row) {
    const inserted = await admin
      .from('release_plan_drafts')
      .insert({ owner_user_id: actor.id, release_id: releaseId, status: 'approved', doc, approved_at: approvedAtIso, approved_task_count: null })
      .select('id')
      .single();
    if (inserted.error) {
      if (inserted.error.code === '23505') {
        return { ok: false, status: 409, error: 'This plan is already being created.', code: 'plan_in_progress' };
      }
      return { ok: false, status: 500, error: inserted.error.message || 'Could not save the plan.' };
    }
    planRowId = (inserted.data as { id: string }).id;
  } else {
    const claim = await admin
      .from('release_plan_drafts')
      .update({ status: 'approved', approved_at: approvedAtIso, doc, approved_task_count: null })
      .eq('id', existingRow.row.id)
      .eq('status', 'draft')
      .select('id');
    if (claim.error) return { ok: false, status: 500, error: claim.error.message || 'Could not save the plan.' };
    if ((claim.data || []).length === 0) {
      return { ok: false, status: 409, error: 'This plan is already being created.', code: 'plan_in_progress' };
    }
    planRowId = existingRow.row.id;
  }

  assignable.ids.add(actor.id);
  let created: { tasksCreated: number };
  try {
    created = releaseDate
      ? await instantiateDraftPlan({
          doc,
          draftId: planRowId,
          releaseId,
          releaseDate,
          workspaceId: team.workspaceId,
          ownerUserId: actor.id,
          assignableUserIds: assignable.ids,
          approvedAtMs: approvedAt.getTime(),
          supabaseClient: admin,
        })
      : await insertUndatedPlan(admin, {
          doc,
          plan,
          draftId: planRowId,
          releaseId,
          workspaceId: team.workspaceId,
          ownerUserId: actor.id,
          assignableUserIds: assignable.ids,
          approvedAtMs: approvedAt.getTime(),
        });
  } catch (error) {
    await admin.from('release_plan_drafts').update({ status: 'draft', approved_at: null }).eq('id', planRowId);
    console.error('[plan-v2] building the plan failed for rollout', releaseId, error);
    return { ok: false, status: 500, error: 'Could not save the plan. Nothing was created. Try again.' };
  }

  const settle = await admin
    .from('releases')
    .update({ metadata: writePlannedByUrgans(writeTemplatePending(writePlannerPending(release.metadata, false), false), true) })
    .eq('id', releaseId)
    // The rollout's owner, not the actor (#854): a Manager plans rollouts that
    // the team owner owns. loadOwnedRelease already checked they may.
    .eq('owner_user_id', release.owner_user_id);
  if (settle.error) console.error('[plan-v2] activities created but the rollout flags did not clear:', settle.error);
  const stamp = await admin.from('release_plan_drafts').update({ approved_task_count: created.tasksCreated }).eq('id', planRowId);
  if (stamp.error) console.error('[plan-v2] activities created but the plan count did not stamp:', stamp.error);

  return { ok: true, tasksCreated: created.tasksCreated, releaseDate };
}

/** Any parseable day: the rows are built against it, then their dates are cleared. */
const UNDATED_BUILD_ANCHOR = '2000-01-01';

/**
 * An undated plan (2026-10-26): the same rows the plan document always makes,
 * with no due date. Each keeps its offset from release day and whether it is
 * prep for now in `metadata.planner_v2`, which is what the task list reads
 * ("Now", "4 weeks before", "Release week", "After release") and what the
 * schedule route turns into real due dates when the date is set
 * (./dates-server.ts). Grouping by phase is unchanged: metadata.phase comes
 * from the offset.
 */
export async function insertUndatedPlan(
  admin: SupabaseClient,
  params: {
    doc: ReleasePlanDraftDoc;
    plan: PlanV2;
    draftId: string;
    releaseId: string;
    workspaceId: string;
    ownerUserId: string;
    assignableUserIds: Set<string>;
    approvedAtMs: number;
  }
): Promise<{ tasksCreated: number }> {
  const { rows } = buildTaskRowsFromDraft({
    doc: params.doc,
    draftId: params.draftId,
    releaseId: params.releaseId,
    releaseDate: UNDATED_BUILD_ANCHOR,
    workspaceId: params.workspaceId,
    ownerUserId: params.ownerUserId,
    assignableUserIds: params.assignableUserIds,
    approvedAtMs: params.approvedAtMs,
  });
  const nowByDraftId = new Map(params.plan.tasks.map((task) => [`v2_${task.key}`, task.now]));
  const offsetByDraftId = new Map(params.doc.tasks.map((task) => [task.id, task.offset_days]));
  const undated = rows.map((row) => {
    const metadata = { ...(row.metadata as Record<string, unknown>) };
    const planner = (metadata.planner ?? {}) as Record<string, unknown>;
    const draftTaskId = String(planner.draft_task_id ?? '');
    const offset = offsetByDraftId.get(draftTaskId) ?? 0;
    const now = nowByDraftId.get(draftTaskId) === true;
    metadata.template = { ...((metadata.template ?? {}) as Record<string, unknown>), compressed_runway: false };
    metadata.planner_v2 = { offset_days: offset, now, when: relativeWhenLabel(offset, now) };
    return { ...row, due_date: null, metadata };
  });
  const { data, error } = await admin.from('tasks').insert(undated).select('id');
  if (error) throw new Error(`Failed to insert the undated plan: ${error.message}`);
  return { tasksCreated: (data ?? []).length };
}

/** The rollout's artist's saved facts as one prompt line, so a plan for an
 *  artist who said no playlist pitching has none. Never throws. */
async function loadPlannerArtistFacts(admin: SupabaseClient, releaseId: string): Promise<string> {
  try {
    const { data } = await admin.from('releases').select('artist_id').eq('id', releaseId).maybeSingle();
    const artistId = (data as { artist_id?: string | null } | null)?.artist_id;
    if (!artistId) return '';
    return formatArtistFactsForPlanner(await listArtistFacts(admin, artistId));
  } catch {
    return '';
  }
}
