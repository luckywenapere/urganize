import type { Release } from '@/types/releases';
import type { Task, TaskStatus, TaskRequirement } from '@/types/tasks';

export type { TaskRequirement };

export type ExecutionTask = Task & {
  requirement: TaskRequirement | null;
  dependencies: string[];
  state: string;
  autoGenerated: boolean;
};

export type ExecutionRelease = Release & {
  readinessScore: number;
  /** Phase 3 signed cover-art URL resolved from `releases.artwork_asset_id`
   * via lib/cover-art.ts. Null when the release has no artwork asset or the
   * lookup degraded (callers show a neutral placeholder). The legacy
   * release_metadata.artwork_url fallback is not surfaced here — it stays
   * exclusive to /api/releases. */
  coverArtUrl?: string | null;
};

export type ActivityLogEntry = {
  id: string;
  releaseId: string | null;
  taskId: string | null;
  actorName: string;
  action: string;
  message: string;
  createdAt: string;
};

export type CommandCenterData = {
  releases: ExecutionRelease[];
  tasks: ExecutionTask[];
  activity: ActivityLogEntry[];
  todaysDirective: ExecutionTask | null;
};

export const TASK_DONE_STATUS: TaskStatus = 'done';
export const TASK_PENDING_STATUS: TaskStatus = 'todo';
export const TASK_LOCKED_STATUS = 'locked' as TaskStatus;
