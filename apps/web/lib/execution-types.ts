import type { Task, TaskStatus } from '@/lib/tasks';

export const RELEASE_PIPELINE_STATES = [
  'idea',
  'planning',
  'asset_prep',
  'distribution',
  'campaign',
  'post_release',
] as const;

export type ReleasePipelineState = (typeof RELEASE_PIPELINE_STATES)[number];

export type TaskRequirementType = 'file_upload' | 'field_completion' | 'approval' | 'external_action';

export type TaskRequirement = {
  type: TaskRequirementType;
  spec: string;
  satisfied: boolean;
};

export type ExecutionTask = Task & {
  requirement: TaskRequirement | null;
  dependencies: string[];
  state: ReleasePipelineState;
  autoGenerated: boolean;
};

export type ExecutionRelease = {
  id: string;
  title: string;
  artistName: string;
  releaseDate: string | null;
  description: string | null;
  status: string;
  state: ReleasePipelineState;
  readinessScore: number;
  createdAt: string;
  updatedAt: string;
};

export type AISignalSeverity = 'info' | 'warning' | 'critical';

export type AISignal = {
  id: string;
  releaseId: string | null;
  taskId?: string | null;
  state?: ReleasePipelineState | null;
  severity: AISignalSeverity;
  title: string;
  message: string;
  actionLabel?: string;
  createdAt: string;
};

export type ActivityLogEntry = {
  id: string;
  releaseId: string | null;
  taskId: string | null;
  actorName: string;
  action: string;
  message: string;
  createdAt: string;
};

export type CommandCenterData = {
  releases: ExecutionRelease[];
  tasks: ExecutionTask[];
  activity: ActivityLogEntry[];
};

export const TASK_DONE_STATUS: TaskStatus = 'done';
export const TASK_PENDING_STATUS: TaskStatus = 'todo';
export const TASK_LOCKED_STATUS = 'locked' as TaskStatus;
