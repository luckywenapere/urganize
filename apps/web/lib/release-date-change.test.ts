import { describe, expect, it } from 'vitest';
import { describeDateChange, earliestPickableDay } from './release-date-change';
import type { PlanDateTask } from './plan-dates';

function task(over: Partial<PlanDateTask> & { id: string }): PlanDateTask {
  return { dueDate: '2026-12-01', status: 'todo', autoGenerated: true, ...over };
}

describe('describeDateChange', () => {
  it('says how many move, which way, and what stays', () => {
    const tasks = [
      task({ id: 'a' }),
      task({ id: 'b', dueDate: '2026-12-05' }),
      task({ id: 'c', status: 'done' }),
      task({ id: 'd', autoGenerated: false }),
    ];
    expect(describeDateChange(tasks, '2026-12-12', '2026-12-19')).toEqual({
      headline: '2 activities move 7 days later.',
      detail: '1 done and 1 you added yourself stay where they are.',
    });
  });

  it('says earlier, and one day / one activity in the singular', () => {
    expect(describeDateChange([task({ id: 'a' })], '2026-12-12', '2026-12-11')).toEqual({
      headline: '1 activity moves 1 day earlier.',
      detail: null,
    });
  });

  it('names only the kind that stays', () => {
    const tasks = [task({ id: 'a' }), task({ id: 'b', status: 'done' }), task({ id: 'c', status: 'done' })];
    expect(describeDateChange(tasks, '2026-12-12', '2026-12-26')?.detail).toBe(
      '2 done stay where they are.'
    );
    const manual = [task({ id: 'a' }), task({ id: 'b', autoGenerated: false })];
    expect(describeDateChange(manual, '2026-12-12', '2026-12-26')?.detail).toBe(
      '1 you added yourself stays where it is.'
    );
  });

  it('says nothing moves when no activity would', () => {
    expect(describeDateChange([task({ id: 'a', status: 'done' })], '2026-12-12', '2026-12-19')).toEqual({
      headline: 'Nothing in the plan moves.',
      detail: '1 done stays where it is.',
    });
  });

  it('is null when the day is unchanged or missing', () => {
    expect(describeDateChange([task({ id: 'a' })], '2026-12-12', '2026-12-12')).toBeNull();
    expect(describeDateChange([task({ id: 'a' })], '2026-12-12', '')).toBeNull();
    expect(describeDateChange([task({ id: 'a' })], null, '2026-12-19')).toBeNull();
  });
});

describe('earliestPickableDay', () => {
  it('is today while release day is still ahead', () => {
    expect(earliestPickableDay('2026-12-12', '2026-11-08')).toBe('2026-11-08');
    expect(earliestPickableDay('2026-11-08', '2026-11-08')).toBe('2026-11-08');
  });

  it('has no floor once the rollout has dropped, so a wrong date can be fixed', () => {
    expect(earliestPickableDay('2026-11-01', '2026-11-08')).toBeNull();
  });

  it('is today when there is no date', () => {
    expect(earliestPickableDay(null, '2026-11-08')).toBe('2026-11-08');
  });
});
