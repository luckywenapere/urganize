// Keeping a rollout's plan lined up with its release day.
//
// Every activity a playbook generates is dated from release day: instantiate.ts
// writes due = release date + the step's offset_days, and approval does the
// same for a planner-built plan. The stored due dates are ABSOLUTE though, so
// anything that moves release day without moving the plan leaves the two out of
// step — and the timeline, which lays every activity out against release day,
// shows the release-day posts three weeks before release day.
//
// Two questions come up, and both are answered here, purely:
//
//  1. WHAT DAY WAS THIS PLAN BUILT FOR? (inferPlanReleaseDate) Asked when a
//     rollout has activities but no date — which is exactly the state UrgAns's
//     rename bug left rollouts in (see lib/release-edit.ts). The plan knows the
//     answer: each generated activity records which playbook step it came from,
//     so its due date minus that step's offset is the release day it was built
//     for. The most common answer across the plan wins, so a few activities a
//     manager dragged or finished do not change it.
//
//  2. WHICH ACTIVITIES MOVE, AND TO WHERE, WHEN RELEASE DAY MOVES?
//     (planActivityShift) Every open activity the plan generated moves by the
//     same number of days, which keeps each one's distance from release day —
//     including any a manager deliberately dragged. Finished activities keep
//     their dates, because those are history. Activities a person added by hand
//     keep theirs too: nothing says they were planned against release day, and
//     one of them may be a real appointment ("radio interview on the 28th") that
//     moving would silently break.
//
// Dates are handled as CALENDAR DAYS, never as instants in the local timezone:
// a due date's leading YYYY-MM-DD is the day it was written for, and a shift
// rewrites that part and keeps the rest of the string (time and offset) exactly
// as stored. That is what makes this identical on a server in UTC and a phone
// in Lagos, and immune to daylight-saving changes.

import { ALBUM_RELEASE_TEMPLATE } from '@/lib/release-templates/album';
import { EP_RELEASE_TEMPLATE } from '@/lib/release-templates/ep';
import { SINGLE_RELEASE_TEMPLATE } from '@/lib/release-templates/single';
import type { Template } from '@/lib/release-templates/types';

const MS_PER_DAY = 86_400_000;

/** What both sides can supply: the server reads these off task rows, the
 * client off its Task model (which has no template id). */
export type PlanDateTask = {
  id: string;
  dueDate: string | null;
  status: string;
  /** True for a row a playbook or the planner generated. */
  autoGenerated?: boolean;
  /** metadata.template.task_id — the playbook step, when there is one. */
  templateTaskId?: string | null;
  /** metadata.template.template_id, when known (server side). */
  templateId?: string | null;
};

/** Every playbook ever WRITTEN, flag-blind on purpose: a stored plan was built
 * by whichever playbook was switched on at the time, and reading it back must
 * not depend on today's flags. */
const AUTHORED_TEMPLATES: Template[] = [
  SINGLE_RELEASE_TEMPLATE,
  EP_RELEASE_TEMPLATE,
  ALBUM_RELEASE_TEMPLATE,
];

const OFFSETS_BY_TEMPLATE = new Map<string, Map<string, number>>(
  AUTHORED_TEMPLATES.map((template) => [
    template.id,
    new Map(template.tasks.map((task) => [task.id, task.offset_days])),
  ])
);

/** Fewer matched activities than this and there is no pattern to trust. */
const MIN_MATCHED = 3;
/** The winning day must be what at least this share of matched activities say. */
const MIN_AGREEMENT = 0.5;

const DAY_PATTERN = /^(\d{4})-(\d{2})-(\d{2})/;

/** Days since the epoch for a YYYY-MM-DD at the start of a string, or null. */
function dayNumber(value: string | null | undefined): number | null {
  const match = DAY_PATTERN.exec(String(value ?? ''));
  if (!match) return null;
  const [, y, m, d] = match;
  const ms = Date.UTC(Number(y), Number(m) - 1, Number(d));
  if (Number.isNaN(ms)) return null;
  // Reject rolled-over dates such as 2026-02-30, which Date.UTC would turn into
  // 2 March without complaint.
  const check = new Date(ms);
  if (
    check.getUTCFullYear() !== Number(y) ||
    check.getUTCMonth() + 1 !== Number(m) ||
    check.getUTCDate() !== Number(d)
  ) {
    return null;
  }
  return Math.round(ms / MS_PER_DAY);
}

function formatDay(day: number): string {
  return new Date(day * MS_PER_DAY).toISOString().slice(0, 10);
}

/** Calendar days from `from` to `to` (positive when `to` is later), or null. */
export function dayDifference(from: string, to: string): number | null {
  const a = dayNumber(from);
  const b = dayNumber(to);
  if (a === null || b === null) return null;
  return b - a;
}

/**
 * Moves a stored due date by whole days, keeping everything after the date
 * exactly as it was. Returns null for a value that does not start with a real
 * calendar day, so the caller can leave it alone rather than guess.
 */
export function addDaysToDue(due: string, days: number): string | null {
  const day = dayNumber(due);
  if (day === null) return null;
  return formatDay(day + days) + due.slice(10);
}

export type InferredPlanDate = {
  /** YYYY-MM-DD. */
  date: string;
  /** Activities that matched a playbook step. */
  matched: number;
  /** How many of those put release day on `date`. */
  agreeing: number;
};

/**
 * The release day a plan was built for, read back off its own activities, or
 * null when there is not enough agreement to say.
 *
 * `releaseType` breaks a tie between playbooks that share step ids; otherwise
 * the playbook that recognises the most steps wins.
 */
export function inferPlanReleaseDate(
  tasks: readonly PlanDateTask[],
  options: { releaseType?: string | null } = {}
): InferredPlanDate | null {
  const preferred = options.releaseType ? `${options.releaseType}_` : 'single_';

  let best: { votes: Map<number, number>; matched: number; templateId: string } | null = null;

  for (const template of AUTHORED_TEMPLATES) {
    const offsets = OFFSETS_BY_TEMPLATE.get(template.id)!;
    const votes = new Map<number, number>();
    let matched = 0;

    for (const task of tasks) {
      const stepId = task.templateTaskId;
      if (!stepId) continue;
      // A row that says which playbook built it only counts for that playbook.
      if (task.templateId && task.templateId !== template.id) continue;
      const offset = offsets.get(stepId);
      if (offset === undefined) continue;
      const due = dayNumber(task.dueDate);
      if (due === null) continue;
      matched += 1;
      const releaseDay = due - offset;
      votes.set(releaseDay, (votes.get(releaseDay) ?? 0) + 1);
    }

    if (matched === 0) continue;
    const better =
      !best ||
      matched > best.matched ||
      (matched === best.matched && template.id.startsWith(preferred));
    if (better) best = { votes, matched, templateId: template.id };
  }

  if (!best || best.matched < MIN_MATCHED) return null;

  let winnerDay: number | null = null;
  let winnerVotes = 0;
  for (const [day, count] of best.votes) {
    // Ties go to the earlier day, only so the answer is deterministic.
    if (count > winnerVotes || (count === winnerVotes && winnerDay !== null && day < winnerDay)) {
      winnerDay = day;
      winnerVotes = count;
    }
  }
  if (winnerDay === null || winnerVotes / best.matched < MIN_AGREEMENT) return null;

  return { date: formatDay(winnerDay), matched: best.matched, agreeing: winnerVotes };
}

export type PlanActivityMove = {
  /** The due date as stored. */
  fromDue: string;
  /** The same moment, `deltaDays` later. */
  toDue: string;
  /** Every activity sharing that due date, so one write moves them all. */
  taskIds: string[];
};

export type PlanActivityShift = {
  deltaDays: number;
  moves: PlanActivityMove[];
  movingCount: number;
  keptDone: number;
  keptManual: number;
  keptUndated: number;
};

/**
 * Which activities move, and where to, when release day moves from `fromDate`
 * to `toDate` (both YYYY-MM-DD). Moves nothing when either date is unusable or
 * the two are the same day.
 */
export function planActivityShift(
  tasks: readonly PlanDateTask[],
  fromDate: string,
  toDate: string
): PlanActivityShift {
  const empty: PlanActivityShift = {
    deltaDays: 0,
    moves: [],
    movingCount: 0,
    keptDone: 0,
    keptManual: 0,
    keptUndated: 0,
  };
  const deltaDays = dayDifference(fromDate, toDate);
  if (deltaDays === null || deltaDays === 0) return { ...empty, deltaDays: deltaDays ?? 0 };

  const byDue = new Map<string, PlanActivityMove>();
  let keptDone = 0;
  let keptManual = 0;
  let keptUndated = 0;
  let movingCount = 0;

  for (const task of tasks) {
    if (task.status === 'done') {
      keptDone += 1;
      continue;
    }
    if (task.autoGenerated !== true) {
      keptManual += 1;
      continue;
    }
    if (!task.dueDate) {
      keptUndated += 1;
      continue;
    }
    const toDue = addDaysToDue(task.dueDate, deltaDays);
    if (toDue === null) {
      keptUndated += 1;
      continue;
    }
    const existing = byDue.get(task.dueDate);
    if (existing) existing.taskIds.push(task.id);
    else byDue.set(task.dueDate, { fromDue: task.dueDate, toDue, taskIds: [task.id] });
    movingCount += 1;
  }

  return { deltaDays, moves: [...byDue.values()], movingCount, keptDone, keptManual, keptUndated };
}
