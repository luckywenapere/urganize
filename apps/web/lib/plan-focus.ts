export const PLAN_STATUS_FILTERS = ['all', 'todo', 'in_progress', 'done', 'cancelled'] as const;
export type PlanStatusFilter = (typeof PLAN_STATUS_FILTERS)[number];

export const PLAN_WHEN_FILTERS = ['any', 'overdue', 'week', 'month', 'later'] as const;
export type PlanWhenFilter = (typeof PLAN_WHEN_FILTERS)[number];

/** 'all', 'me', 'unassigned', or a user id. */
export type PlanAssigneeFilter = string;

export type PlanFilters = {
  query: string;
  status: PlanStatusFilter;
  assignee: PlanAssigneeFilter;
  when: PlanWhenFilter;
};

export const EMPTY_PLAN_FILTERS: PlanFilters = {
  query: '',
  status: 'all',
  assignee: 'all',
  when: 'any',
};

export const PLAN_STATUS_LABELS: Record<PlanStatusFilter, string> = {
  all: 'Any status',
  todo: 'To do',
  in_progress: 'In progress',
  done: 'Done',
  cancelled: 'Cancelled',
};

export const PLAN_WHEN_LABELS: Record<PlanWhenFilter, string> = {
  any: 'Any date',
  overdue: 'Overdue',
  week: 'Next 7 days',
  month: 'Next 30 days',
  later: 'Later',
};

export function hasActivePlanFilters(filters: PlanFilters): boolean {
  return (
    filters.query.trim() !== '' ||
    filters.status !== 'all' ||
    filters.assignee !== 'all' ||
    filters.when !== 'any'
  );
}

export type PlanFilterTask = PlanFocusTask &
  Pick<Task, 'title' | 'assignedToUserId' | 'compressedRunway' | 'completedAt'>;

function matchesStatus(task: PlanFilterTask, status: PlanStatusFilter): boolean {
  switch (status) {
    case 'all':
      return true;
    case 'done':
      return task.status === 'done';
    case 'cancelled':
      return task.status === 'cancelled';
    case 'in_progress':
      return ACTIVE.has(task.status);
    case 'todo':
      return isOpenTask(task) && !ACTIVE.has(task.status);
  }
}

function matchesWhen(task: PlanFilterTask, when: PlanWhenFilter, now: Date): boolean {
  if (when === 'any') return true;
  if (when === 'overdue') {
    if (!isOpenTask(task)) return false;
    // Same rule as the buckets: catch-up work is overdue in all but colour.
    const section = getTaskSectionKey(task as Task, now);
    return section === 'overdue' || section === 'catch_up';
  }
  const days = daysUntilDue(task.dueDate, now);
  if (days === null) return false;
  if (when === 'week') return days >= 0 && days <= 7;
  if (when === 'month') return days >= 0 && days <= 30;
  return days > 30;
}

function matchesAssignee(
  task: PlanFilterTask,
  assignee: PlanAssigneeFilter,
  currentUserId: string | null
): boolean {
  if (assignee === 'all') return true;
  if (assignee === 'unassigned') return !task.assignedToUserId;
  if (assignee === 'me') return Boolean(currentUserId) && task.assignedToUserId === currentUserId;
  return task.assignedToUserId === assignee;
}

/**
 * What the list shows. With a search or a filter on, it looks across EVERY
 * task, key or not, cancelled or not — a search that missed tucked-away work
 * would make "kept, not lost" untrue. With neither, it shows the key tasks
 * unless `showAll`.
 *
 * Cancelled work (URG-389, Oct 19, 2026) is left out of the plain list unless
 * `showCancelled`: it was dropped on purpose, so it should not sit among the
 * work still owed. It is never deleted, it is counted (`cancelledCount`) so
 * the quiet "Show cancelled · n" control can bring it back, and it is not
 * counted in `liveCount` or `hiddenCount`, which describe the live plan.
 */
export function selectPlanTasks<T extends PlanFilterTask>(
  tasks: T[],
  options: {
    filters: PlanFilters;
    showAll: boolean;
    showCancelled?: boolean;
    currentUserId?: string | null;
    now?: Date;
  }
): {
  visible: T[];
  hiddenCount: number;
  filtering: boolean;
  /** Activities that are not cancelled: the plan's real size. */
  liveCount: number;
  cancelledCount: number;
} {
  const { filters, showAll, showCancelled = false } = options;
  const now = options.now ?? new Date();
  const filtering = hasActivePlanFilters(filters);
  const live = tasks.filter((task) => task.status !== 'cancelled');
  const liveCount = live.length;
  const cancelledCount = tasks.length - liveCount;

  if (filtering) {
    const terms = parseSearchTerms(filters.query);
    const visible = tasks.filter(
      (task) =>
        (terms.length === 0 || matchesSearchTerms(task.title, terms)) &&
        matchesStatus(task, filters.status) &&
        matchesWhen(task, filters.when, now) &&
        matchesAssignee(task, filters.assignee, options.currentUserId ?? null)
    );
    return { visible, hiddenCount: 0, filtering, liveCount, cancelledCount };
  }

  const keyIds = selectKeyTaskIds(live);
  const hiddenCount = liveCount - keyIds.size;
  const keep = (task: T) =>
    task.status === 'cancelled' ? showCancelled : showAll || keyIds.has(task.id);
  return { visible: tasks.filter(keep), hiddenCount, filtering, liveCount, cancelledCount };
}

/** Read the key flag the planner writes at `metadata.planner.key`. */
export function readPlanKey(metadata: unknown): boolean | null {
  if (!metadata || typeof metadata !== 'object') return null;
  const planner = (metadata as { planner?: unknown }).planner;
  if (!planner || typeof planner !== 'object') return null;
  const key = (planner as { key?: unknown }).key;
  return typeof key === 'boolean' ? key : null;
}

/** Part of a smaller plan (URG-318): its core, or a suggestion someone added.
 *  False for every plan built before 2026-10-16 and for hand-made tasks. */
export function readPlanCore(metadata: unknown): boolean {
  if (!metadata || typeof metadata !== 'object') return false;
  const planner = (metadata as { planner?: unknown }).planner;
  if (!planner || typeof planner !== 'object') return false;
  const p = planner as { core?: unknown; suggested?: unknown };
  return p.core === true || p.suggested === true;
}

/** Metadata with `planner.key` set, everything else kept as it was. */
export function withPlanKey(metadata: unknown, key: boolean): Record<string, unknown> {
  const base =
    metadata && typeof metadata === 'object' && !Array.isArray(metadata)
      ? (metadata as Record<string, unknown>)
      : {};
  const planner =
    base.planner && typeof base.planner === 'object' && !Array.isArray(base.planner)
      ? (base.planner as Record<string, unknown>)
      : {};
  return { ...base, planner: { ...planner, key } };
}

