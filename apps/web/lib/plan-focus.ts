/**
 * Key tasks: the short list a rollout plan shows by default (URG-258, Femi's
 * design review, 2026-10-13).
 *
 * The planner generates 60+ activities for a single and the eye stops after
 * the first five to eight, so everything below that line was being missed.
 * The plan now opens on the few that matter and keeps the rest one quiet tap
 * away ("Show all N"). Nothing is deleted or rewritten: the decision is made
 * here, on read, from what each task already carries.
 *
 * Three sources, in order:
 *  1. `planKey === true` — UrgAns (or the planner's own fallback rule) marked
 *     it key when the plan was built, or a person pinned it to the main list.
 *  2. A task a person added by hand (`autoGenerated === false`), unless they
 *     tucked it away (`planKey === false`). They chose to write it down.
 *  3. Work already underway (in progress, blocked, in review) — hiding what
 *     someone has started is how it gets forgotten.
 *
 * Then a top-up so the list never goes thin as key work gets ticked off: open
 * tasks ranked by priority, then by date (soonest first, which also puts the
 * earliest phase first). A plan with flags tops up to {@link MIN_OPEN_KEY};
 * an older plan with no flags at all gets {@link LEGACY_KEY_COUNT}, which is
 * what makes plans built before this change look short too, without touching
 * their rows.
 */

/** The fewest open tasks the main list shows, when the plan has that many. */
export const MIN_OPEN_KEY = 5;
/** How many tasks an older plan (no key flags anywhere) shows by default. */
export const LEGACY_KEY_COUNT = 8;
/** The most tasks the planner marks key in a new plan. */
export const MAX_KEY_TASKS = 10;

export type PlanFocusTask = Pick<
  Task,
  'id' | 'releaseId' | 'status' | 'priority' | 'dueDate' | 'position' | 'autoGenerated'
> & { planKey?: boolean | null; taskType?: Task['taskType'] };

const ACTIVE = new Set<Task['status']>(['in_progress', 'blocked', 'in_review']);
const PRIORITY_RANK: Record<Task['priority'], number> = {
  urgent: 0,
  high: 1,
  medium: 2,
  low: 3,
  none: 3,
};

export function isOpenTask(task: Pick<Task, 'status'>): boolean {
  return !isTaskClosed(task.status);
}

function dueMs(task: PlanFocusTask): number {
  if (!task.dueDate) return Number.POSITIVE_INFINITY;
  const ms = new Date(task.dueDate).getTime();
  return Number.isNaN(ms) ? Number.POSITIVE_INFINITY : ms;
}

/** Ranking for the top-up: priority, then soonest date, then plan order. */
export function compareForTopUp(a: PlanFocusTask, b: PlanFocusTask): number {
  const byPriority = PRIORITY_RANK[a.priority] - PRIORITY_RANK[b.priority];
  if (byPriority !== 0) return byPriority;
  const byDate = dueMs(a) - dueMs(b);
  if (byDate !== 0) return byDate;
  return (a.position ?? 0) - (b.position ?? 0);
}

/** The key-task ids of ONE rollout's tasks. */
function selectForRollout(tasks: PlanFocusTask[]): Set<string> {
  const keep = new Set<string>();
  const hasFlags = tasks.some((task) => typeof task.planKey === 'boolean');

  for (const task of tasks) {
    if (task.planKey === true) keep.add(task.id);
    else if (task.autoGenerated === false && task.planKey !== false) keep.add(task.id);
    else if (ACTIVE.has(task.status)) keep.add(task.id);
  }

  const target = hasFlags ? MIN_OPEN_KEY : LEGACY_KEY_COUNT;
  // An older plan has no AI pick, so soonest-first alone would fill the list
  // with this week's chores. Keep its next open milestone (usually release
  // day) in view so the date everything builds to is never tucked away.
  if (!hasFlags) {
    const milestone = tasks
      .filter((task) => task.taskType === 'event_milestone' && isOpenTask(task))
      .sort((a, b) => dueMs(a) - dueMs(b))[0];
    if (milestone) keep.add(milestone.id);
  }
  let openCount = tasks.filter((task) => keep.has(task.id) && isOpenTask(task)).length;
  if (openCount >= target) return keep;

  const candidates = tasks
    .filter((task) => !keep.has(task.id) && isOpenTask(task))
    .sort(compareForTopUp);
  for (const task of candidates) {
    if (openCount >= target) break;
    keep.add(task.id);
    openCount += 1;
  }
  return keep;
}

/**
 * Which tasks the main list shows. Decided per rollout, so an unscoped list
 * holding several rollouts gives each its own short list. A task with no
 * rollout is always shown.
 */
export function selectKeyTaskIds(tasks: PlanFocusTask[]): Set<string> {
  const byRollout = new Map<string, PlanFocusTask[]>();
  const keep = new Set<string>();
  for (const task of tasks) {
    if (!task.releaseId) {
      keep.add(task.id);
      continue;
    }
    const list = byRollout.get(task.releaseId);
    if (list) list.push(task);
    else byRollout.set(task.releaseId, [task]);
  }
  for (const list of byRollout.values()) {
    for (const id of selectForRollout(list)) keep.add(id);
  }
  return keep;
}

