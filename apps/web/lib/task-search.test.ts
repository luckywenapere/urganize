import { describe, expect, it } from 'vitest';
import {
  TASK_SEARCH_RESULT_LIMIT,
  matchesSearchTerms,
  parseSearchTerms,
  searchTasks,
} from './task-search';
import type { Task } from '@/types/tasks';

/**
 * The mobile search surface's ranking rules. Nothing else in the app reads
 * them, so a regression would show up only as the right activity quietly
 * failing to surface for a query that names it — which is exactly the class of
 * bug that gets reported as "search doesn't work" with no way to reproduce it.
 */

const makeTask = (overrides: Partial<Task> = {}): Task => ({
  id: 'task-1',
  workspaceId: 'ws-1',
  groupId: null,
  releaseId: 'rel-1',
  createdBy: 'user-1',
  assignedToUserId: null,
  assignedTo: null,
  title: 'Sample',
  description: null,
  status: 'todo',
  priority: 'medium',
  dueDate: null,
  completedAt: null,
  position: 1,
  requirement: null,
  dependencies: [],
  state: 'planning',
  autoGenerated: false,
  taskType: 'task',
  templateTaskId: null,
  durationDays: null,
  compressedRunway: false,
  groupName: null,
  groupColor: null,
  createdAt: '2026-08-01T00:00:00.000Z',
  updatedAt: '2026-08-01T00:00:00.000Z',
  ...overrides,
});

const titles = (tasks: { task: Task }[]) => tasks.map((entry) => entry.task.title);

describe('parseSearchTerms', () => {
  it('lowercases and splits on whitespace', () => {
    expect(parseSearchTerms('Cover Art')).toEqual(['cover', 'art']);
  });

  it('collapses runs of whitespace and trims the edges', () => {
    expect(parseSearchTerms('  cover   art \n')).toEqual(['cover', 'art']);
  });

  it('is empty for a blank query — the caller must show a hint, not everything', () => {
    expect(parseSearchTerms('')).toEqual([]);
    expect(parseSearchTerms('   ')).toEqual([]);
  });
});

describe('matchesSearchTerms', () => {
  it('needs every term, in any order', () => {
    expect(matchesSearchTerms('Cover art final approved', ['art', 'cover'])).toBe(true);
    expect(matchesSearchTerms('Cover art final approved', ['cover', 'master'])).toBe(false);
  });

  it('is case-insensitive on the text side too', () => {
    expect(matchesSearchTerms('PRESS KIT', ['press'])).toBe(true);
  });

  it('never matches with no terms — an empty query is not a match-all', () => {
    expect(matchesSearchTerms('Press kit', [])).toBe(false);
  });
});

describe('searchTasks', () => {
  it('returns nothing for a blank query', () => {
    const tasks = [makeTask({ title: 'Brief the designer' })];
    expect(searchTasks(tasks, '   ')).toEqual({ results: [], hiddenCount: 0 });
  });

  it('finds an activity by a word in its title', () => {
    const tasks = [
      makeTask({ id: 'a', title: 'Brief the designer' }),
      makeTask({ id: 'b', title: 'Upload to distributor' }),
    ];
    expect(titles(searchTasks(tasks, 'distributor').results)).toEqual(['Upload to distributor']);
  });

  it('matches terms in any order', () => {
    const tasks = [makeTask({ title: 'Cover art final approved' })];
    expect(searchTasks(tasks, 'art cover').results).toHaveLength(1);
  });

  it('ranks a title that STARTS with the query above one that merely contains it', () => {
    const tasks = [
      makeTask({ id: 'a', title: 'Send the press kit to blogs' }),
      makeTask({ id: 'b', title: 'Press kit live' }),
    ];
    expect(titles(searchTasks(tasks, 'press kit').results)).toEqual([
      'Press kit live',
      'Send the press kit to blogs',
    ]);
  });

  it('ranks a title match above a description-only match', () => {
    const tasks = [
      makeTask({ id: 'a', title: 'Week 6 asset check', description: 'Confirm the master is final' }),
      makeTask({ id: 'b', title: 'Master delivered' }),
    ];
    const results = searchTasks(tasks, 'master').results;
    expect(titles(results)).toEqual(['Master delivered', 'Week 6 asset check']);
    expect(results.map((entry) => entry.matchedIn)).toEqual(['title', 'description']);
  });

  it('finds an activity by its description when the title says nothing', () => {
    const tasks = [
      makeTask({ title: 'Begin outreach', description: 'Pitch curators and playlist owners' }),
    ];
    const results = searchTasks(tasks, 'playlist').results;
    expect(results).toHaveLength(1);
    expect(results[0].matchedIn).toBe('description');
  });

  it('spans title and description for a multi-word query', () => {
    const tasks = [makeTask({ title: 'Begin outreach', description: 'Send to playlist curators' })];
    expect(searchTasks(tasks, 'outreach playlist').results).toHaveLength(1);
  });

  it('sorts completed activities after live ones in the same tier', () => {
    const tasks = [
      makeTask({ id: 'a', title: 'Master upload', status: 'done' }),
      makeTask({ id: 'b', title: 'Master check', status: 'todo' }),
    ];
    expect(titles(searchTasks(tasks, 'master').results)).toEqual(['Master check', 'Master upload']);
  });

  it('still finds a completed activity — searching to reopen one is legitimate', () => {
    const tasks = [makeTask({ title: 'Master upload', status: 'done' })];
    expect(searchTasks(tasks, 'master').results).toHaveLength(1);
  });

  it('a live description match never outranks a done title match', () => {
    // Tier beats status: the tiers are about what the user typed, the status
    // tiebreak only orders rows that are equally good matches.
    const tasks = [
      makeTask({ id: 'a', title: 'Asset check', description: 'the master', status: 'todo' }),
      makeTask({ id: 'b', title: 'Master upload', status: 'done' }),
    ];
    expect(titles(searchTasks(tasks, 'master').results)).toEqual(['Master upload', 'Asset check']);
  });

  it('preserves the incoming order for equally-ranked matches', () => {
    const tasks = [
      makeTask({ id: 'a', title: 'Master three' }),
      makeTask({ id: 'b', title: 'Master one' }),
      makeTask({ id: 'c', title: 'Master two' }),
    ];
    expect(titles(searchTasks(tasks, 'master').results)).toEqual([
      'Master three',
      'Master one',
      'Master two',
    ]);
  });

  it('caps the list and reports what it is holding back', () => {
    const tasks = Array.from({ length: 12 }, (_, index) =>
      makeTask({ id: `t-${index}`, title: `Master ${index}` })
    );
    const outcome = searchTasks(tasks, 'master');
    expect(outcome.results).toHaveLength(TASK_SEARCH_RESULT_LIMIT);
    expect(outcome.hiddenCount).toBe(12 - TASK_SEARCH_RESULT_LIMIT);
  });

  it('reports no hidden matches when everything fits', () => {
    const tasks = [makeTask({ title: 'Master upload' })];
    expect(searchTasks(tasks, 'master').hiddenCount).toBe(0);
  });

  it('honours an explicit limit', () => {
    const tasks = [
      makeTask({ id: 'a', title: 'Master one' }),
      makeTask({ id: 'b', title: 'Master two' }),
    ];
    const outcome = searchTasks(tasks, 'master', 1);
    expect(outcome.results).toHaveLength(1);
    expect(outcome.hiddenCount).toBe(1);
  });

  it('is empty for an empty activity list', () => {
    expect(searchTasks([], 'master')).toEqual({ results: [], hiddenCount: 0 });
  });

  it('tolerates a null description', () => {
    const tasks = [makeTask({ title: 'Brief the designer', description: null })];
    expect(() => searchTasks(tasks, 'master')).not.toThrow();
    expect(searchTasks(tasks, 'master').results).toEqual([]);
  });
});
