import { describe, expect, it } from 'vitest';
import { ALBUM_RELEASE_TEMPLATE } from '@/lib/release-templates/album';
import { EP_RELEASE_TEMPLATE } from '@/lib/release-templates/ep';
import { SINGLE_RELEASE_TEMPLATE } from '@/lib/release-templates/single';
import type { Template } from '@/lib/release-templates/types';
import {
  addDaysToDue,
  dayDifference,
  inferPlanReleaseDate,
  planActivityShift,
  type PlanDateTask,
} from './plan-dates';

const MS_PER_DAY = 86_400_000;

/** A plan exactly as instantiate.ts writes it for `releaseDate`. */
function planFor(template: Template, releaseDate: string): PlanDateTask[] {
  const epoch = Date.parse(`${releaseDate}T00:00:00Z`);
  return template.tasks.map((task, index) => ({
    id: `t${index}`,
    dueDate: new Date(epoch + task.offset_days * MS_PER_DAY).toISOString().replace('.000Z', '+00:00'),
    status: 'todo',
    autoGenerated: true,
    templateTaskId: task.id,
    templateId: template.id,
  }));
}

describe('inferPlanReleaseDate', () => {
  it('reads the release day back off an untouched single plan', () => {
    const result = inferPlanReleaseDate(planFor(SINGLE_RELEASE_TEMPLATE, '2026-10-30'));
    expect(result?.date).toBe('2026-10-30');
    expect(result?.matched).toBe(SINGLE_RELEASE_TEMPLATE.tasks.length);
  });

  it('does the same for EP and album plans', () => {
    expect(inferPlanReleaseDate(planFor(EP_RELEASE_TEMPLATE, '2027-02-12'))?.date).toBe('2027-02-12');
    expect(inferPlanReleaseDate(planFor(ALBUM_RELEASE_TEMPLATE, '2027-05-07'))?.date).toBe('2027-05-07');
  });

  it('works on the client shape, which carries no template id', () => {
    const tasks = planFor(SINGLE_RELEASE_TEMPLATE, '2026-10-30').map((task) => ({
      ...task,
      templateId: null,
    }));
    expect(inferPlanReleaseDate(tasks)?.date).toBe('2026-10-30');
  });

  it('survives a handful of activities being dragged or done', () => {
    const tasks = planFor(SINGLE_RELEASE_TEMPLATE, '2026-10-30');
    // Drag five activities a week later, and finish three: evidence, not noise.
    for (const task of tasks.slice(0, 5)) task.dueDate = addDaysToDue(task.dueDate!, 7);
    for (const task of tasks.slice(10, 13)) task.status = 'done';
    expect(inferPlanReleaseDate(tasks)?.date).toBe('2026-10-30');
  });

  it('ignores activities with no template origin', () => {
    const tasks: PlanDateTask[] = [
      ...planFor(SINGLE_RELEASE_TEMPLATE, '2026-10-30'),
      { id: 'm1', dueDate: '2026-12-25T00:00:00+00:00', status: 'todo', autoGenerated: false, templateTaskId: null },
    ];
    expect(inferPlanReleaseDate(tasks)?.date).toBe('2026-10-30');
  });

  it('gives no answer when there is not enough to go on', () => {
    expect(inferPlanReleaseDate([])).toBeNull();
    const two = planFor(SINGLE_RELEASE_TEMPLATE, '2026-10-30').slice(0, 2);
    expect(inferPlanReleaseDate(two)).toBeNull();
  });

  it('gives no answer when the activities disagree too much to trust', () => {
    // Every activity moved by a different amount: nothing agrees.
    const tasks = planFor(SINGLE_RELEASE_TEMPLATE, '2026-10-30').map((task, index) => ({
      ...task,
      dueDate: addDaysToDue(task.dueDate!, index),
    }));
    expect(inferPlanReleaseDate(tasks)).toBeNull();
  });

  it('skips unreadable due dates rather than failing', () => {
    const tasks = planFor(SINGLE_RELEASE_TEMPLATE, '2026-10-30');
    tasks[0].dueDate = 'not a date';
    tasks[1].dueDate = null;
    expect(inferPlanReleaseDate(tasks)?.date).toBe('2026-10-30');
  });

  it('reads the calendar day as written, not shifted by a timezone', () => {
    // A naive wall-clock string from a manual edit must not slide a day.
    const tasks = planFor(SINGLE_RELEASE_TEMPLATE, '2026-10-30').map((task) => ({
      ...task,
      dueDate: task.dueDate!.slice(0, 10) + 'T23:30:00',
    }));
    expect(inferPlanReleaseDate(tasks)?.date).toBe('2026-10-30');
  });
});

describe('planActivityShift', () => {
  it('moves every open plan activity by the same number of days', () => {
    const tasks = planFor(SINGLE_RELEASE_TEMPLATE, '2026-10-30');
    const shift = planActivityShift(tasks, '2026-10-30', '2026-11-20');
    expect(shift.deltaDays).toBe(21);
    expect(shift.movingCount).toBe(tasks.length);
    const releaseDay = SINGLE_RELEASE_TEMPLATE.tasks.findIndex((task) => task.offset_days === 0);
    const moved = shift.moves.find((move) => move.taskIds.includes(`t${releaseDay}`));
    expect(moved?.toDue.slice(0, 10)).toBe('2026-11-20');
  });

  it('keeps finished activities where they were — they are history', () => {
    const tasks = planFor(SINGLE_RELEASE_TEMPLATE, '2026-10-30');
    tasks[0].status = 'done';
    const shift = planActivityShift(tasks, '2026-10-30', '2026-11-20');
    expect(shift.keptDone).toBe(1);
    expect(shift.moves.some((move) => move.taskIds.includes('t0'))).toBe(false);
  });

  it('keeps activities a person added by hand — they may be pinned to a real appointment', () => {
    const tasks: PlanDateTask[] = [
      ...planFor(SINGLE_RELEASE_TEMPLATE, '2026-10-30'),
      { id: 'radio', dueDate: '2026-10-28T00:00:00+00:00', status: 'todo', autoGenerated: false, templateTaskId: null },
    ];
    const shift = planActivityShift(tasks, '2026-10-30', '2026-11-20');
    expect(shift.keptManual).toBe(1);
    expect(shift.moves.some((move) => move.taskIds.includes('radio'))).toBe(false);
  });

  it('leaves undated activities alone', () => {
    const tasks: PlanDateTask[] = [
      { id: 'u', dueDate: null, status: 'todo', autoGenerated: true, templateTaskId: null },
    ];
    const shift = planActivityShift(tasks, '2026-10-30', '2026-11-20');
    expect(shift.keptUndated).toBe(1);
    expect(shift.movingCount).toBe(0);
  });

  it('moves nothing when the date did not really change', () => {
    const shift = planActivityShift(planFor(SINGLE_RELEASE_TEMPLATE, '2026-10-30'), '2026-10-30', '2026-10-30');
    expect(shift.deltaDays).toBe(0);
    expect(shift.moves).toEqual([]);
  });

  it('moves earlier as well as later', () => {
    const shift = planActivityShift(planFor(SINGLE_RELEASE_TEMPLATE, '2026-10-30'), '2026-10-30', '2026-10-09');
    expect(shift.deltaDays).toBe(-21);
    expect(shift.moves.length).toBeGreaterThan(0);
  });

  it('groups activities sharing a due date into one write', () => {
    const tasks = planFor(SINGLE_RELEASE_TEMPLATE, '2026-10-30');
    const distinctDates = new Set(tasks.map((task) => task.dueDate)).size;
    const shift = planActivityShift(tasks, '2026-10-30', '2026-11-20');
    expect(shift.moves.length).toBe(distinctDates);
    const ids = shift.moves.flatMap((move) => move.taskIds);
    expect(new Set(ids).size).toBe(ids.length);
  });

  it('refuses to guess when either date is unusable', () => {
    const tasks = planFor(SINGLE_RELEASE_TEMPLATE, '2026-10-30');
    expect(planActivityShift(tasks, 'soon', '2026-11-20').moves).toEqual([]);
    expect(planActivityShift(tasks, '2026-10-30', '').moves).toEqual([]);
  });

  it('keeps the time of day and the offset of a moved activity exactly as stored', () => {
    const tasks: PlanDateTask[] = [
      { id: 'a', dueDate: '2026-10-01T15:30:00+00:00', status: 'todo', autoGenerated: true, templateTaskId: null },
      { id: 'b', dueDate: '2026-10-01T23:30:00-05:00', status: 'todo', autoGenerated: true, templateTaskId: null },
      { id: 'c', dueDate: '2026-10-01T09:00:00', status: 'todo', autoGenerated: true, templateTaskId: null },
    ];
    const shift = planActivityShift(tasks, '2026-10-30', '2026-10-31');
    const byId = new Map(shift.moves.flatMap((move) => move.taskIds.map((id) => [id, move.toDue])));
    expect(byId.get('a')).toBe('2026-10-02T15:30:00+00:00');
    expect(byId.get('b')).toBe('2026-10-02T23:30:00-05:00');
    expect(byId.get('c')).toBe('2026-10-02T09:00:00');
  });

  it('crosses month and year ends', () => {
    expect(addDaysToDue('2026-12-31T00:00:00+00:00', 1)).toBe('2027-01-01T00:00:00+00:00');
    expect(addDaysToDue('2028-03-01', -1)).toBe('2028-02-29');
  });
});

describe('date helpers', () => {
  it('counts calendar days across a daylight-saving change without drifting', () => {
    expect(dayDifference('2026-03-28', '2026-03-30')).toBe(2);
    expect(dayDifference('2026-10-24', '2026-10-26')).toBe(2);
  });

  it('returns null for anything that is not a calendar day', () => {
    expect(dayDifference('2026-02-30', '2026-03-01')).toBeNull();
    expect(dayDifference('', '2026-03-01')).toBeNull();
  });
});
