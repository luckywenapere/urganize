// The usage dashboard at /admin/metrics (2026-10-07): every rule that decides a
// number lives here, pure and tested. lib/usage-metrics-server.ts only reads and
// shapes rows; components/admin/MetricsView.tsx only displays.
//
// "ACTIVE" ON THIS PAGE IS WIDER THAN ON THE SCOREBOARD, ON PURPOSE. The
// scoreboard follows the strategy doc: a member is active when they DID
// something. Here a person is active on a day if any of these happened:
//   - the last-seen ping recorded them (the app was open and visible),
//   - they did something (the same 18 activity tables as the scoreboard),
//   - they opened the app (the login-ping's scheduled_notifications rows,
//     which reach back to 2026-07-23, before the ping existed),
//   - they signed in.
// That is what lets it count a manager who opened the app, looked at their
// rollouts and left: the retention question the founder wants answered.
//
// Days and weeks are Lagos calendar days (UTC+1, no daylight saving). "Last 7
// days" and "last 30 days" are rolling windows that end now.

import type { LatestEvent } from './admin-read-server';
import { isOnline, presenceDay, type PresenceSurface, PRESENCE_SURFACES } from './presence';

const DAY_MS = 24 * 60 * 60 * 1000;

/** How many people the "recently active" table lists. */
export const RECENT_LIMIT = 30;
/** How many people each of the two quiet lists shows at most. */
export const QUIET_LIMIT = 25;
/** Daily active series length, and the weekly series length. */
export const DAILY_POINTS = 30;
export const WEEKLY_POINTS = 12;
/** "Gone quiet": last seen between these many days ago. */
export const QUIET_FROM_DAYS = 31;
export const QUIET_TO_DAYS = 90;

export type MetricsPerson = {
  userId: string;
  email: string | null;
  name: string | null;
  role: string | null;
  /** When the account was made. */
  createdAt: string | null;
  lastSignInAt: string | null;
  onboardingCompleted: boolean;
};

export type MetricsPresence = {
  userId: string;
  /** Lagos calendar day, "YYYY-MM-DD". */
  day: string;
  lastSeenAt: string;
  surface: PresenceSurface;
};

export type MetricsRelease = {
  id: string;
  /** The team it belongs to; null for an orphan with no team. */
  workspaceId: string | null;
  ownerUserId: string | null;
  createdAt: string | null;
  /** A date with no time ("2026-10-02"). */
  releaseDate: string | null;
  status: string | null;
  isTest: boolean;
  plannerPending: boolean;
  templatePending: boolean;
  plannedByUrgans: boolean;
  /** null when no plan draft row exists; otherwise whether the model's changes
   *  were applied (doc.ai.applied). */
  draftAiApplied: boolean | null;
  taskCount: number;
  doneCount: number;
  autoTaskCount: number;
};

export type MetricsTask = {
  releaseId: string | null;
  status: string | null;
  completedAt: string | null;
  updatedAt: string | null;
  createdAt: string | null;
  autoGenerated: boolean;
};

export type MetricsTeam = { workspaceId: string; name: string | null; memberUserIds: string[] };

export type UsageMetricsInput = {
  now: Date;
  people: MetricsPerson[];
  presence: MetricsPresence[];
  /** For each person, the times (ms) they did something. */
  activity: Map<string, number[]>;
  latestEvents: Map<string, LatestEvent>;
  /** Times (ms) someone opened the app, from the login-ping. */
  appOpens: Array<{ userId: string; at: number }>;
  releases: MetricsRelease[];
  tasks: MetricsTask[];
  teams: MetricsTeam[];
  urgansTurns: Array<{ userId: string | null; at: number }>;
  /** AI cost rows already in US dollars; null when no source could be read. */
  aiCost: { rows: Array<{ userId: string | null; at: number; usd: number }>; source: string } | null;
  waitlistTotal: number | null;
  /** People left out of every number ("our team"). */
  hiddenUserIds: Set<string>;
};

export type PersonRef = { userId: string; name: string; email: string | null; team: string | null };
export type OnlinePerson = PersonRef & { lastSeenAt: string; surface: PresenceSurface };
export type SeriesPoint = { key: string; tick: string; label: string; value: number };
export type RecentPerson = PersonRef & {
  lastSeenAt: string;
  lastThing: string;
  actions7d: number;
  actions30d: number;
  joinedAt: string | null;
  surface: PresenceSurface | null;
  online: boolean;
};
export type QuietPerson = PersonRef & { lastSeenAt: string };

export type PlanSplit = { urgans: number; playbook: number; own: number; none: number };

export type UsageMetrics = {
  generatedAt: string;
  /** The first day the ping recorded anyone; null while it has recorded nothing. */
  presenceSince: string | null;
  online: OnlinePerson[];
  active: {
    today: number;
    last7d: number;
    last30d: number;
    /** Today divided by the last 30 days; null when nobody was active. */
    stickiness: number | null;
    /** Active in the last 7 days and joined in the last 7 days. */
    newPeople7d: number;
    daily: SeriesPoint[];
    /** People seen by the ping in the last 7 days, by the kind of device they
     *  used most recently. */
    surfaces7d: Record<PresenceSurface, number>;
  };
  rollouts: {
    total: number;
    tests: number;
    last7d: number;
    last30d: number;
    goingOutNext30d: number;
    outLast30d: number;
    weekly: SeriesPoint[];
    plans: PlanSplit;
  };
  accounts: {
    total: number;
    curators: number;
    new7d: number;
    new30d: number;
    /** Share of non-curator accounts that finished onboarding; null with none. */
    onboardingRate: number | null;
    weekly: SeriesPoint[];
    waitlist: number | null;
  };
  work: {
    activitiesDone7d: number;
    activitiesDone30d: number;
    addedByHand7d: number;
    urgansTurns7d: number;
    urgansPeople7d: number;
    aiCostUsd30d: number | null;
    aiCostSource: string | null;
  };
  betweenReleases: QuietPerson[];
  betweenReleasesCount: number;
  goneQuiet: QuietPerson[];
  goneQuietCount: number;
  recent: RecentPerson[];
};

const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

/** "2026-10-07" -> "Oct 7". */
export function shortDayLabel(day: string): string {
  const month = Number(day.slice(5, 7)) - 1;
  const date = Number(day.slice(8, 10));
  return `${MONTHS[month] ?? ''} ${date}`;
}

function dayToMs(day: string): number {
  return Date.parse(`${day}T00:00:00.000Z`);
}

function addDays(day: string, days: number): string {
  return new Date(dayToMs(day) + days * DAY_MS).toISOString().slice(0, 10);
}

/** The Monday that starts the Lagos week a day falls in. */
export function weekStartDay(day: string): string {
  const dow = new Date(dayToMs(day)).getUTCDay(); // 0 Sunday .. 6 Saturday
  return addDays(day, -((dow + 6) % 7));
}

function dayOfMs(ms: number): string {
  return presenceDay(new Date(ms));
}

function parseMs(value: string | null | undefined): number | null {
  if (!value) return null;
  const ms = Date.parse(value);
  return Number.isFinite(ms) ? ms : null;
}

/** The last `count` Lagos days ending today, oldest first. */
export function trailingDays(now: Date, count: number): string[] {
  const today = presenceDay(now);
  return Array.from({ length: count }, (_, index) => addDays(today, index - (count - 1)));
}

/** The Monday of each of the last `count` Lagos weeks, oldest first. */
export function trailingWeeks(now: Date, count: number): string[] {
  const current = weekStartDay(presenceDay(now));
  return Array.from({ length: count }, (_, index) => addDays(current, (index - (count - 1)) * 7));
}

/** Where a release stands on its plan. The draft row is the authority when it
 *  exists; otherwise the pending flags, then whether the playbook made tasks. */
export function classifyPlan(release: MetricsRelease): keyof PlanSplit {
  if (release.plannerPending) return 'none';
  if (release.draftAiApplied === true) return 'urgans';
  if (release.draftAiApplied === false) return 'playbook';
  if (release.plannedByUrgans) return 'urgans';
  if (release.templatePending) return 'none';
  if (release.autoTaskCount > 0) return 'playbook';
  if (release.taskCount > 0) return 'own';
  return 'none';
}

/** A rollout the team is still working towards: not a test, not archived, and
 *  either its date is today or later, or it has no date and is not finished. */
export function isOpenRollout(release: MetricsRelease, today: string): boolean {
  if (release.isTest || release.status === 'archived') return false;
  if (release.releaseDate) return release.releaseDate >= today;
  return release.taskCount === 0 || release.doneCount < release.taskCount;
}

function displayName(person: MetricsPerson | undefined, userId: string): string {
  const name = person?.name?.trim();
  if (name) return name;
  const email = person?.email?.trim();
  if (email) return email.split('@')[0];
  return `Account ${userId.slice(0, 8)}`;
}

type Seen = { at: number; thing: string };

export function buildUsageMetrics(input: UsageMetricsInput): UsageMetrics {
  const { now, hiddenUserIds } = input;
  const nowMs = now.getTime();
  const today = presenceDay(now);
  const since7 = nowMs - 7 * DAY_MS;
  const since30 = nowMs - 30 * DAY_MS;
  const visible = (userId: string | null | undefined): userId is string =>
    !!userId && !hiddenUserIds.has(userId);

  const peopleById = new Map(input.people.map((person) => [person.userId, person]));

  // Teams per person, for the "team" column and the between-releases rule.
  const teamsByPerson = new Map<string, MetricsTeam[]>();
  for (const team of input.teams) {
    for (const userId of team.memberUserIds) {
      const list = teamsByPerson.get(userId) ?? [];
      list.push(team);
      teamsByPerson.set(userId, list);
    }
  }
  const teamLabel = (userId: string): string | null => {
    const names = (teamsByPerson.get(userId) ?? [])
      .map((team) => team.name?.trim())
      .filter((name): name is string => !!name);
    return names.length > 0 ? Array.from(new Set(names)).join(' / ') : null;
  };
  const ref = (userId: string): PersonRef => {
    const person = peopleById.get(userId);
    return { userId, name: displayName(person, userId), email: person?.email ?? null, team: teamLabel(userId) };
  };

  // Every moment each person was seen, and the days they were active.
  const activeDays = new Map<string, Set<string>>();
  const lastSeen = new Map<string, Seen>();
  const latestSurface = new Map<string, { at: number; surface: PresenceSurface }>();
  const markDay = (userId: string, day: string) => {
    const set = activeDays.get(userId) ?? new Set<string>();
    set.add(day);
    activeDays.set(userId, set);
  };
  const markSeen = (userId: string, at: number, thing: string) => {
    if (at > nowMs) at = nowMs;
    const current = lastSeen.get(userId);
    if (!current || at > current.at) lastSeen.set(userId, { at, thing });
  };

  let presenceSince: string | null = null;
  for (const row of input.presence) {
    if (!presenceSince || row.day < presenceSince) presenceSince = row.day;
    if (!visible(row.userId)) continue;
    markDay(row.userId, row.day);
    const at = parseMs(row.lastSeenAt);
    if (at === null) continue;
    markSeen(row.userId, at, 'had the app open');
    const surface = latestSurface.get(row.userId);
    if (!surface || at > surface.at) latestSurface.set(row.userId, { at, surface: row.surface });
  }
  for (const [userId, times] of input.activity) {
    if (!visible(userId)) continue;
    for (const at of times) markDay(userId, dayOfMs(at));
    const latest = input.latestEvents.get(userId);
    if (latest) markSeen(userId, latest.at, latest.label);
  }
  for (const open of input.appOpens) {
    if (!visible(open.userId)) continue;
    markDay(open.userId, dayOfMs(open.at));
    markSeen(open.userId, open.at, 'opened the app');
  }
  for (const person of input.people) {
    if (!visible(person.userId)) continue;
    const at = parseMs(person.lastSignInAt);
    if (at === null) continue;
    markDay(person.userId, dayOfMs(at));
    markSeen(person.userId, at, 'signed in');
  }

  // Active counts.
  const days30 = trailingDays(now, DAILY_POINTS);
  const days7 = new Set(days30.slice(-7));
  const window30 = new Set(days30);
  let today1 = 0;
  let last7 = 0;
  let last30 = 0;
  let newPeople7d = 0;
  const dailyCounts = new Map<string, number>(days30.map((day) => [day, 0]));
  for (const [userId, days] of activeDays) {
    let in7 = false;
    let in30 = false;
    for (const day of days) {
      if (dailyCounts.has(day)) dailyCounts.set(day, (dailyCounts.get(day) ?? 0) + 1);
      if (days7.has(day)) in7 = true;
      if (window30.has(day)) in30 = true;
    }
    if (days.has(today)) today1 += 1;
    if (in7) last7 += 1;
    if (in30) last30 += 1;
    const joined = parseMs(peopleById.get(userId)?.createdAt);
    if (in7 && joined !== null && joined >= since7) newPeople7d += 1;
  }

  const surfaces7d = Object.fromEntries(PRESENCE_SURFACES.map((surface) => [surface, 0])) as Record<
    PresenceSurface,
    number
  >;
  for (const { at, surface } of latestSurface.values()) {
    if (at >= since7) surfaces7d[surface] += 1;
  }

  // Online now: the latest presence row per person, within the window.
  const onlineByUser = new Map<string, OnlinePerson>();
  for (const row of input.presence) {
    if (!visible(row.userId) || !isOnline(row.lastSeenAt, now)) continue;
    const current = onlineByUser.get(row.userId);
    if (current && Date.parse(current.lastSeenAt) >= Date.parse(row.lastSeenAt)) continue;
    onlineByUser.set(row.userId, { ...ref(row.userId), lastSeenAt: row.lastSeenAt, surface: row.surface });
  }
  const online = Array.from(onlineByUser.values()).sort(
    (a, b) => Date.parse(b.lastSeenAt) - Date.parse(a.lastSeenAt)
  );

  // Rollouts. "Our team" is hidden by owner.
  const releases = input.releases.filter((release) => visible(release.ownerUserId) || !release.ownerUserId);
  const real = releases.filter((release) => !release.isTest);
  const weeks = trailingWeeks(now, WEEKLY_POINTS);
  const weekIndex = new Map(weeks.map((week, index) => [week, index]));
  const rolloutWeekly = weeks.map(() => 0);
  const plans: PlanSplit = { urgans: 0, playbook: 0, own: 0, none: 0 };
  let rollouts7 = 0;
  let rollouts30 = 0;
  let goingOut = 0;
  let outRecently = 0;
  const in30Days = addDays(today, 30);
  const before30Days = addDays(today, -30);
  for (const release of real) {
    plans[classifyPlan(release)] += 1;
    const created = parseMs(release.createdAt);
    if (created !== null) {
      if (created >= since7) rollouts7 += 1;
      if (created >= since30) rollouts30 += 1;
      const index = weekIndex.get(weekStartDay(dayOfMs(created)));
      if (index !== undefined) rolloutWeekly[index] += 1;
    }
    if (release.status !== 'archived' && release.releaseDate) {
      if (release.releaseDate >= today && release.releaseDate <= in30Days) goingOut += 1;
      if (release.releaseDate < today && release.releaseDate >= before30Days) outRecently += 1;
    }
  }

  // Accounts.
  const people = input.people.filter((person) => visible(person.userId));
  const signupWeekly = weeks.map(() => 0);
  let curators = 0;
  let new7 = 0;
  let new30 = 0;
  let nonCurators = 0;
  let onboarded = 0;
  for (const person of people) {
    if (person.role === 'curator') {
      curators += 1;
    } else {
      nonCurators += 1;
      if (person.onboardingCompleted) onboarded += 1;
    }
    const created = parseMs(person.createdAt);
    if (created === null) continue;
    if (created >= since7) new7 += 1;
    if (created >= since30) new30 += 1;
    const index = weekIndex.get(weekStartDay(dayOfMs(created)));
    if (index !== undefined) signupWeekly[index] += 1;
  }

  // Work.
  const releaseOwner = new Map(input.releases.map((release) => [release.id, release.ownerUserId]));
  let done7 = 0;
  let done30 = 0;
  let byHand7 = 0;
  for (const task of input.tasks) {
    const owner = task.releaseId ? releaseOwner.get(task.releaseId) : null;
    if (owner && hiddenUserIds.has(owner)) continue;
    if (task.status === 'done') {
      const doneAt = parseMs(task.completedAt) ?? parseMs(task.updatedAt);
      if (doneAt !== null && doneAt >= since7) done7 += 1;
      if (doneAt !== null && doneAt >= since30) done30 += 1;
    }
    const created = parseMs(task.createdAt);
    if (!task.autoGenerated && created !== null && created >= since7) byHand7 += 1;
  }
  let turns7 = 0;
  const urgansPeople = new Set<string>();
  for (const turn of input.urgansTurns) {
    if (turn.userId && hiddenUserIds.has(turn.userId)) continue;
    if (turn.at < since7) continue;
    turns7 += 1;
    if (turn.userId) urgansPeople.add(turn.userId);
  }
  let aiCostUsd30d: number | null = null;
  if (input.aiCost) {
    aiCostUsd30d = 0;
    for (const row of input.aiCost.rows) {
      if (row.userId && hiddenUserIds.has(row.userId)) continue;
      if (row.at >= since30) aiCostUsd30d += row.usd;
    }
  }

  // Between releases and gone quiet.
  const betweenReleases: QuietPerson[] = [];
  const goneQuiet: QuietPerson[] = [];
  const quietFrom = nowMs - QUIET_FROM_DAYS * DAY_MS;
  const quietTo = nowMs - QUIET_TO_DAYS * DAY_MS;
  for (const [userId, seen] of lastSeen) {
    const person = peopleById.get(userId);
    const entry = { ...ref(userId), lastSeenAt: new Date(seen.at).toISOString() };
    if (seen.at >= since30) {
      if (person?.role === 'curator') continue;
      const teamIds = new Set((teamsByPerson.get(userId) ?? []).map((team) => team.workspaceId));
      const hasOpen = input.releases.some(
        (release) => release.workspaceId !== null && teamIds.has(release.workspaceId) && isOpenRollout(release, today)
      );
      if (!hasOpen) betweenReleases.push(entry);
    } else if (seen.at <= quietFrom && seen.at >= quietTo) {
      goneQuiet.push(entry);
    }
  }
  const newestFirst = (a: QuietPerson, b: QuietPerson) => Date.parse(b.lastSeenAt) - Date.parse(a.lastSeenAt);
  betweenReleases.sort(newestFirst);
  goneQuiet.sort(newestFirst);

  // Recently active.
  const recent: RecentPerson[] = Array.from(lastSeen.entries())
    .sort((a, b) => b[1].at - a[1].at)
    .slice(0, RECENT_LIMIT)
    .map(([userId, seen]) => {
      const times = input.activity.get(userId) ?? [];
      const lastSeenAt = new Date(seen.at).toISOString();
      return {
        ...ref(userId),
        lastSeenAt,
        lastThing: seen.thing,
        actions7d: times.filter((at) => at >= since7 && at <= nowMs).length,
        actions30d: times.filter((at) => at >= since30 && at <= nowMs).length,
        joinedAt: peopleById.get(userId)?.createdAt ?? null,
        surface: latestSurface.get(userId)?.surface ?? null,
        online: onlineByUser.has(userId),
      };
    });

  const series = (keys: string[], values: number[], label: (key: string) => string): SeriesPoint[] =>
    keys.map((key, index) => ({
      key,
      // The day of the month only: thirty "Oct 7" labels cannot fit under
      // thirty bars on a phone. The readout above the chart has the full date.
      tick: String(Number(key.slice(8, 10))),
      label: label(key),
      value: values[index] ?? 0,
    }));

  return {
    generatedAt: now.toISOString(),
    presenceSince,
    online,
    active: {
      today: today1,
      last7d: last7,
      last30d: last30,
      stickiness: last30 > 0 ? today1 / last30 : null,
      newPeople7d,
      daily: series(
        days30,
        days30.map((day) => dailyCounts.get(day) ?? 0),
        (day) => shortDayLabel(day)
      ),
      surfaces7d,
    },
    rollouts: {
      total: real.length,
      tests: releases.length - real.length,
      last7d: rollouts7,
      last30d: rollouts30,
      goingOutNext30d: goingOut,
      outLast30d: outRecently,
      weekly: series(weeks, rolloutWeekly, (week) => `Week of ${shortDayLabel(week)}`),
      plans,
    },
    accounts: {
      total: people.length,
      curators,
      new7d: new7,
      new30d: new30,
      onboardingRate: nonCurators > 0 ? onboarded / nonCurators : null,
      weekly: series(weeks, signupWeekly, (week) => `Week of ${shortDayLabel(week)}`),
      waitlist: input.waitlistTotal,
    },
    work: {
      activitiesDone7d: done7,
      activitiesDone30d: done30,
      addedByHand7d: byHand7,
      urgansTurns7d: turns7,
      urgansPeople7d: urgansPeople.size,
      aiCostUsd30d,
      aiCostSource: input.aiCost?.source ?? null,
    },
    betweenReleases: betweenReleases.slice(0, QUIET_LIMIT),
    betweenReleasesCount: betweenReleases.length,
    goneQuiet: goneQuiet.slice(0, QUIET_LIMIT),
    goneQuietCount: goneQuiet.length,
    recent,
  };
}
