import { describe, expect, it } from 'vitest';
import {
  EMPTY_PLAN_FILTERS,
  LEGACY_KEY_COUNT,
  MIN_OPEN_KEY,
  readPlanKey,
  selectKeyTaskIds,
  selectPlanTasks,
  withPlanKey,
  type PlanFilterTask,
} from './plan-focus';

const NOW = new Date('2026-10-14T09:00:00Z');

function task(over: Partial<PlanFilterTask> & { id: string }): PlanFilterTask {
  return {
    releaseId: 'r1',
    status: 'todo',
    priority: 'none',
    dueDate: null,
    position: 0,
    autoGenerated: true,
    planKey: null,
    title: `Task ${over.id}`,
    assignedToUserId: 'owner',
    compressedRunway: false,
    completedAt: null,
    ...over,
  };
}

/** n generated tasks, one per day from `startDay` days after NOW. */
function plan(n: number, over: Partial<PlanFilterTask> = {}, startDay = 1): PlanFilterTask[] {
  return Array.from({ length: n }, (_, i) =>
    task({
      id: `t${i}`,
      position: i,
      dueDate: new Date(NOW.getTime() + (startDay + i) * 86_400_000).toISOString(),
      ...over,
    })
  );
}

describe('selectKeyTaskIds', () => {
  it('shows only the flagged key tasks of a new plan', () => {
    const tasks = plan(60, { planKey: false }).map((t, i) =>
      i < 7 ? { ...t, planKey: true } : t
    );
    const keys = selectKeyTaskIds(tasks);
    expect([...keys].sort()).toEqual(['t0', 't1', 't2', 't3', 't4', 't5', 't6']);
  });

  it('tops a new plan up to the minimum with the soonest open work as keys get done', () => {
    const tasks = plan(30, { planKey: false }).map((t, i) =>
      i < 6 ? { ...t, planKey: true, status: i < 4 ? ('done' as const) : t.status } : t
    );
    const keys = selectKeyTaskIds(tasks);
    const open = tasks.filter((t) => keys.has(t.id) && t.status !== 'done');
    expect(open).toHaveLength(MIN_OPEN_KEY);
    // the done keys stay, so progress is visible
    expect(keys.has('t0')).toBe(true);
    // the top-up is the soonest open non-key work
    expect(keys.has('t6')).toBe(true);
    expect(keys.has('t7')).toBe(true);
    expect(keys.has('t8')).toBe(true);
    expect(keys.has('t9')).toBe(false);
  });

  it('gives an older plan with no flags a short list, soonest first', () => {
    const tasks = plan(64).reverse();
    const keys = selectKeyTaskIds(tasks);
    expect(keys.size).toBe(LEGACY_KEY_COUNT);
    expect(keys.has('t0')).toBe(true);
    expect(keys.has(`t${LEGACY_KEY_COUNT - 1}`)).toBe(true);
    expect(keys.has(`t${LEGACY_KEY_COUNT}`)).toBe(false);
  });

  it("keeps an older plan's next open milestone in its short list", () => {
    const tasks = plan(64);
    tasks[50] = { ...tasks[50], taskType: 'event_milestone' };
    tasks[60] = { ...tasks[60], taskType: 'event_milestone' };
    const keys = selectKeyTaskIds(tasks);
    expect(keys.size).toBe(LEGACY_KEY_COUNT);
    expect(keys.has('t50')).toBe(true);
    expect(keys.has('t60')).toBe(false);
    expect(keys.has(`t${LEGACY_KEY_COUNT - 1}`)).toBe(false);
  });

  it('ranks high priority ahead of an earlier date in the top-up', () => {
    const tasks = plan(20);
    tasks[15] = { ...tasks[15], priority: 'high' };
    const keys = selectKeyTaskIds(tasks);
    expect(keys.has('t15')).toBe(true);
    expect(keys.has(`t${LEGACY_KEY_COUNT - 1}`)).toBe(false);
  });

  it('always shows hand-added tasks and work already started', () => {
    const tasks = [
      ...plan(40, { planKey: false }).map((t, i) => (i < 5 ? { ...t, planKey: true } : t)),
      task({ id: 'mine', autoGenerated: false }),
      task({ id: 'started', status: 'in_progress', planKey: false }),
    ];
    const keys = selectKeyTaskIds(tasks);
    expect(keys.has('mine')).toBe(true);
    expect(keys.has('started')).toBe(true);
  });

  it('keeps a hand-added task tucked away when the person said so', () => {
    const tasks = [...plan(10, { planKey: true }), task({ id: 'mine', autoGenerated: false, planKey: false })];
    expect(selectKeyTaskIds(tasks).has('mine')).toBe(false);
  });

  it('a pinned task joins the main list', () => {
    const tasks = plan(30, { planKey: false }).map((t, i) => (i < 6 ? { ...t, planKey: true } : t));
    tasks[25] = { ...tasks[25], planKey: true };
    expect(selectKeyTaskIds(tasks).has('t25')).toBe(true);
  });

  it('decides per rollout', () => {
    const a = plan(20);
    const b = plan(20).map((t) => ({ ...t, id: `b${t.id}`, releaseId: 'r2' }));
    const keys = selectKeyTaskIds([...a, ...b]);
    expect(keys.size).toBe(LEGACY_KEY_COUNT * 2);
  });

  it('shows everything when a plan is already short', () => {
    expect(selectKeyTaskIds(plan(4)).size).toBe(4);
  });
});

describe('selectPlanTasks', () => {
  it('hides the rest behind a count, and Show all reveals it', () => {
    const tasks = plan(64);
    const short = selectPlanTasks(tasks, { filters: EMPTY_PLAN_FILTERS, showAll: false, now: NOW });
    expect(short.visible).toHaveLength(LEGACY_KEY_COUNT);
    expect(short.hiddenCount).toBe(64 - LEGACY_KEY_COUNT);
    const all = selectPlanTasks(tasks, { filters: EMPTY_PLAN_FILTERS, showAll: true, now: NOW });
    expect(all.visible).toHaveLength(64);
  });

  it('searches every task, including the tucked-away ones', () => {
    const tasks = plan(64);
    tasks[50] = { ...tasks[50], title: 'Pitch Spotify editorial' };
    const result = selectPlanTasks(tasks, {
      filters: { ...EMPTY_PLAN_FILTERS, query: 'spotify' },
      showAll: false,
      now: NOW,
    });
    expect(result.visible.map((t) => t.id)).toEqual(['t50']);
    expect(result.filtering).toBe(true);
  });

  it('filters by status', () => {
    const tasks = [
      task({ id: 'a', status: 'done' }),
      task({ id: 'b', status: 'in_progress' }),
      task({ id: 'c', status: 'blocked' }),
      task({ id: 'd' }),
    ];
    const pick = (status: 'todo' | 'in_progress' | 'done') =>
      selectPlanTasks(tasks, { filters: { ...EMPTY_PLAN_FILTERS, status }, showAll: false, now: NOW })
        .visible.map((t) => t.id);
    expect(pick('done')).toEqual(['a']);
    expect(pick('in_progress')).toEqual(['b', 'c']);
    expect(pick('todo')).toEqual(['d']);
  });

  it('filters by assignee, me and unassigned', () => {
    const tasks = [
      task({ id: 'a', assignedToUserId: 'me-id' }),
      task({ id: 'b', assignedToUserId: 'other' }),
      task({ id: 'c', assignedToUserId: null }),
    ];
    const pick = (assignee: string) =>
      selectPlanTasks(tasks, {
        filters: { ...EMPTY_PLAN_FILTERS, assignee },
        showAll: false,
        currentUserId: 'me-id',
        now: NOW,
      }).visible.map((t) => t.id);
    expect(pick('me')).toEqual(['a']);
    expect(pick('other')).toEqual(['b']);
    expect(pick('unassigned')).toEqual(['c']);
  });

  it('filters by date', () => {
    const day = (n: number) => new Date(NOW.getTime() + n * 86_400_000).toISOString();
    const tasks = [
      task({ id: 'late', dueDate: day(-3) }),
      task({ id: 'lateDone', dueDate: day(-3), status: 'done' }),
      task({ id: 'soon', dueDate: day(3) }),
      task({ id: 'month', dueDate: day(20) }),
      task({ id: 'far', dueDate: day(60) }),
      task({ id: 'none', dueDate: null }),
    ];
    const pick = (when: 'overdue' | 'week' | 'month' | 'later') =>
      selectPlanTasks(tasks, { filters: { ...EMPTY_PLAN_FILTERS, when }, showAll: false, now: NOW })
        .visible.map((t) => t.id);
    expect(pick('overdue')).toEqual(['late']);
    expect(pick('week')).toEqual(['soon']);
    expect(pick('month')).toEqual(['soon', 'month']);
    expect(pick('later')).toEqual(['far']);
  });
});

describe('planner.key metadata', () => {
  it('reads the flag and nothing else', () => {
    expect(readPlanKey({ planner: { key: true } })).toBe(true);
    expect(readPlanKey({ planner: { key: false } })).toBe(false);
    expect(readPlanKey({ planner: {} })).toBeNull();
    expect(readPlanKey(null)).toBeNull();
    expect(readPlanKey({ planner: { key: 'yes' } })).toBeNull();
  });

  it('writes the flag without losing the rest of the metadata', () => {
    const before = { template: { task_id: 'x' }, planner: { origin: 'template', focus: true } };
    expect(withPlanKey(before, true)).toEqual({
      template: { task_id: 'x' },
      planner: { origin: 'template', focus: true, key: true },
    });
    expect(withPlanKey(null, false)).toEqual({ planner: { key: false } });
  });
});
