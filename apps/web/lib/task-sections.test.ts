import { describe, expect, it } from 'vitest';
import { createEmptyMyTasksSections, getTaskSectionKey, groupTasksIntoSections } from './tasks';
import type { Task, TaskStatus } from '@/types/tasks';

/**
 * Grouping is status-first as of 2026-08-15 (founder call): every status
 * except 'todo' is its own group, and only 'todo' activities fall through to
 * the due-date groups. These tests pin that rule and the in-place completion
 * beat, both of which are easy to break from the outside — nothing else in the
 * app reads `getTaskSectionKey`'s branches, so a regression would only show up
 * as activities quietly landing in the wrong group.
 */

const DAY_MS = 86400000;

const at = (dayOffset: number) => new Date(Date.now() + dayOffset * DAY_MS).toISOString();

const makeTask = (overrides: Partial<Task> = {}): Task => ({
  id: 'task-1',
  workspaceId: 'ws-1',
  groupId: null,
  releaseId: 'rel-1',
  createdBy: 'user-1',
  assignedToUserId: null,
  assignedTo: null,
  title: 'Sample',
  description: null,
  status: 'todo',
  priority: 'medium',
  dueDate: null,
  completedAt: null,
  position: 1,
  requirement: null,
  dependencies: [],
  state: 'planning',
  autoGenerated: false,
  taskType: 'task',
  templateTaskId: null,
  compressedRunway: false,
  groupName: null,
  groupColor: null,
  createdAt: at(-10),
  updatedAt: at(-1),
  ...overrides,
});

describe('getTaskSectionKey — status wins', () => {
  const statusCases: Array<[TaskStatus, string]> = [
    ['in_progress', 'in_progress'],
    ['blocked', 'blocked'],
    ['in_review', 'in_review'],
    ['backlog', 'backlog'],
    ['locked', 'locked'],
    ['done', 'done'],
    ['cancelled', 'cancelled'],
  ];

  it.each(statusCases)('routes %s to its own group', (status, expected) => {
    // A due date that would otherwise force a time group — status must win.
    expect(getTaskSectionKey(makeTask({ status, dueDate: at(-5) }))).toBe(expected);
  });

  it('routes a status-grouped activity there even with no due date', () => {
    expect(getTaskSectionKey(makeTask({ status: 'in_progress', dueDate: null }))).toBe(
      'in_progress'
    );
  });
});

describe('getTaskSectionKey — todo falls through to due date', () => {
  it('groups an un-started past-due activity as overdue', () => {
    expect(getTaskSectionKey(makeTask({ status: 'todo', dueDate: at(-3) }))).toBe('overdue');
  });

  it('groups a compressed-runway past-due activity as catch up', () => {
    expect(
      getTaskSectionKey(makeTask({ status: 'todo', dueDate: at(-3), compressedRunway: true }))
    ).toBe('catch_up');
  });

  it('groups today, this week and later separately', () => {
    expect(getTaskSectionKey(makeTask({ status: 'todo', dueDate: at(0) }))).toBe('today');
    expect(getTaskSectionKey(makeTask({ status: 'todo', dueDate: at(3) }))).toBe('week');
    expect(getTaskSectionKey(makeTask({ status: 'todo', dueDate: at(30) }))).toBe('upcoming');
  });

  it('groups an undated activity as no due date', () => {
    expect(getTaskSectionKey(makeTask({ status: 'todo', dueDate: null }))).toBe('no_due_date');
  });
});

describe('getTaskSectionKey — the in-place completion beat', () => {
  // The store writes the PRE-tick status as the pending value so the row holds
  // its own group for ~1.5s instead of jumping to Done immediately.
  it('keeps a just-ticked activity in the group it came from', () => {
    const task = makeTask({ id: 'x', status: 'done', dueDate: at(5) });
    expect(getTaskSectionKey(task, new Date(), { x: 'in_progress' })).toBe('in_progress');
  });

  it('falls back to the due-date group when it came from todo', () => {
    const task = makeTask({ id: 'x', status: 'done', dueDate: at(5) });
    expect(getTaskSectionKey(task, new Date(), { x: 'todo' })).toBe('week');
  });

  it('tolerates the legacy `true` marker by using the due-date group', () => {
    const task = makeTask({ id: 'x', status: 'done', dueDate: at(5) });
    expect(getTaskSectionKey(task, new Date(), { x: true })).toBe('week');
  });

  it('tolerates a Set of ids the same way', () => {
    const task = makeTask({ id: 'x', status: 'done', dueDate: at(5) });
    expect(getTaskSectionKey(task, new Date(), new Set(['x']))).toBe('week');
  });

  it('routes to Done once the beat has ended', () => {
    const task = makeTask({ id: 'x', status: 'done', dueDate: at(5) });
    expect(getTaskSectionKey(task, new Date(), {})).toBe('done');
  });

  it('ignores a pending marker belonging to a different activity', () => {
    const task = makeTask({ id: 'x', status: 'done', dueDate: at(5) });
    expect(getTaskSectionKey(task, new Date(), { other: 'in_progress' })).toBe('done');
  });
});

describe('groupTasksIntoSections', () => {
  it('places every activity in exactly one group', () => {
    const tasks = [
      makeTask({ id: 'a', status: 'in_progress' }),
      makeTask({ id: 'b', status: 'blocked' }),
      makeTask({ id: 'c', status: 'todo', dueDate: at(2) }),
      makeTask({ id: 'd', status: 'todo', dueDate: null }),
      makeTask({ id: 'e', status: 'done' }),
    ];

    const sections = groupTasksIntoSections(tasks);
    const placed = Object.values(sections).flat();

    expect(placed).toHaveLength(tasks.length);
    expect(new Set(placed.map((task) => task.id)).size).toBe(tasks.length);
  });

  it('returns a key for every group, so the panel can iterate safely', () => {
    const empty = createEmptyMyTasksSections();
    const grouped = groupTasksIntoSections([]);
    expect(Object.keys(grouped).sort()).toEqual(Object.keys(empty).sort());
    expect(Object.values(grouped).every((group) => group.length === 0)).toBe(true);
  });
});
