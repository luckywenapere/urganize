import { describe, expect, it } from 'vitest';
import {
  buildReleaseTimeline,
  dayOffsetFromRelease,
  dayPosition,
  daysForDragDelta,
  groupItemsByWeek,
  isoForDayOffset,
  itemPosition,
  narrowTimeline,
  toneForSection,
  weekIndexForDay,
  weekLabel,
  weekLongLabel,
} from './release-timeline';
import { getTemplate } from './release-templates/loader';
import type { Task } from '@/types/tasks';

/**
 * The timeline is pure layout over data the app already holds, so these tests
 * are the only place its rules are enforced — there is no component test in
 * this repo to catch a mirrored bar or an off-by-one week.
 *
 * Three of them matter more than the rest:
 *
 *  - the round trip against the LIVE single playbook, which proves the UTC
 *    frame here exactly inverts instantiation's forward math;
 *  - the bar direction, which is the rule most likely to be "corrected"
 *    backwards by someone reading the column name `due_date`;
 *  - the marker/bar split, which is the whole visual argument for this view.
 */

const RELEASE_DATE = '2026-11-20';
const DAY_MS = 86400000;

/** An ISO timestamp `offset` days from RELEASE_DATE, the way instantiation
 * writes one: UTC midnight plus whole days. */
const dueAt = (offset: number) =>
  new Date(Date.UTC(2026, 10, 20) + offset * DAY_MS).toISOString();

const makeTask = (overrides: Partial<Task> = {}): Task => ({
  id: 'task-1',
  workspaceId: 'ws-1',
  groupId: null,
  releaseId: 'rel-1',
  createdBy: 'user-1',
  assignedToUserId: null,
  assignedTo: null,
  title: 'Sample',
  description: null,
  status: 'todo',
  priority: 'none',
  dueDate: null,
  completedAt: null,
  position: 1,
  requirement: null,
  dependencies: [],
  state: 'planning',
  autoGenerated: true,
  taskType: 'task',
  templateTaskId: null,
  durationDays: 1,
  compressedRunway: false,
  groupName: null,
  groupColor: null,
  createdAt: dueAt(-90),
  updatedAt: dueAt(-90),
  ...overrides,
});

describe('day arithmetic', () => {
  it('reads a template due date back as its own offset', () => {
    expect(dayOffsetFromRelease(dueAt(-42), RELEASE_DATE)).toBe(-42);
    expect(dayOffsetFromRelease(dueAt(0), RELEASE_DATE)).toBe(0);
    expect(dayOffsetFromRelease(dueAt(21), RELEASE_DATE)).toBe(21);
  });

  it('round-trips every task in the live single playbook', () => {
    // The property that makes the whole axis trustworthy: whatever
    // instantiation writes, this reads back unchanged. If someone switches
    // either side to local time, this breaks for half the world's timezones.
    const template = getTemplate('single');
    expect(template).not.toBeNull();

    for (const task of template!.tasks) {
      const iso = dueAt(task.offset_days);
      expect(dayOffsetFromRelease(iso, RELEASE_DATE)).toBe(task.offset_days);
    }
  });

  it('survives a date-only due value', () => {
    expect(dayOffsetFromRelease('2026-11-13', RELEASE_DATE)).toBe(-7);
  });

  it('returns null rather than guessing on bad input', () => {
    expect(dayOffsetFromRelease(null, RELEASE_DATE)).toBeNull();
    expect(dayOffsetFromRelease('not a date', RELEASE_DATE)).toBeNull();
    expect(dayOffsetFromRelease(dueAt(0), 'not a date')).toBeNull();
  });

  it('maps days onto weeks with release week as zero', () => {
    expect(weekIndexForDay(0)).toBe(0);
    expect(weekIndexForDay(6)).toBe(0);
    expect(weekIndexForDay(7)).toBe(1);
    // Floor, not truncation: day -1 is the week BEFORE release week.
    expect(weekIndexForDay(-1)).toBe(-1);
    expect(weekIndexForDay(-7)).toBe(-1);
    expect(weekIndexForDay(-8)).toBe(-2);
  });

  it('labels negative weeks the way the playbooks number them', () => {
    // single_v0.3's "Week 6" banner sits at offset -42.
    expect(weekLabel(weekIndexForDay(-42))).toBe('W6');
    expect(weekLabel(0)).toBe('Release');
    expect(weekLabel(2)).toBe('+2');
    expect(weekLongLabel(-1)).toBe('1 week out');
    expect(weekLongLabel(0)).toBe('Release week');
    expect(weekLongLabel(3)).toBe('3 weeks after');
  });

  it('converts an offset back to an ISO date', () => {
    expect(isoForDayOffset(RELEASE_DATE, 0)).toBe('2026-11-20');
    expect(isoForDayOffset(RELEASE_DATE, -42)).toBe('2026-10-09');
  });
});

describe('bars and markers', () => {
  const now = new Date(dueAt(-60));

  it('runs a multi-day bar FORWARD from its due date', () => {
    // The rule most likely to be reversed by someone reading `due_date` as a
    // deadline. The playbooks say otherwise: every 7-day activity is phrased
    // "Begin X ... ongoing across the week" at the offset it starts.
    const timeline = buildReleaseTimeline({
      tasks: [makeTask({ dueDate: dueAt(-42), durationDays: 7 })],
      releaseDate: RELEASE_DATE,
      now,
    });

    const item = timeline!.phases[0].items[0];
    expect(item.startDay).toBe(-42);
    expect(item.endDay).toBe(-36);
    expect(item.isBar).toBe(true);
  });

  it('renders a one-day activity as a marker, not a stub bar', () => {
    const timeline = buildReleaseTimeline({
      tasks: [makeTask({ dueDate: dueAt(-42), durationDays: 1 })],
      releaseDate: RELEASE_DATE,
      now,
    });

    const item = timeline!.phases[0].items[0];
    expect(item.startDay).toBe(-42);
    expect(item.endDay).toBe(-42);
    expect(item.isBar).toBe(false);
  });

  it('treats an unknown duration as a single point rather than inventing one', () => {
    // A manager-added activity carries no duration. A wrong bar is worse than
    // an honest dot.
    const timeline = buildReleaseTimeline({
      tasks: [makeTask({ dueDate: dueAt(-10), durationDays: null })],
      releaseDate: RELEASE_DATE,
      now,
    });

    const item = timeline!.phases[0].items[0];
    expect(item.isBar).toBe(false);
    expect(item.endDay).toBe(item.startDay);
    expect(item.durationDays).toBeNull();
  });

  it('keeps the live single playbook overwhelmingly markers', () => {
    // The finding this whole view is shaped around: ~89% of a release is
    // single-day work. If a future playbook revision changes that, this view's
    // design should be revisited rather than this test relaxed.
    const template = getTemplate('single');
    const tasks = template!.tasks.map((task, index) =>
      makeTask({
        id: `t-${index}`,
        dueDate: dueAt(task.offset_days),
        durationDays: task.duration_days,
        taskType: task.type,
      })
    );

    const timeline = buildReleaseTimeline({ tasks, releaseDate: RELEASE_DATE, now });
    const all = timeline!.phases.flatMap((phase) => phase.items);
    const bars = all.filter((item) => item.isBar);

    expect(all).toHaveLength(64);
    expect(bars).toHaveLength(7);
  });
});

describe('the axis', () => {
  const now = new Date(dueAt(-60));

  it('always reaches two weeks past release day', () => {
    const timeline = buildReleaseTimeline({
      tasks: [makeTask({ dueDate: dueAt(-7) })],
      releaseDate: RELEASE_DATE,
      now,
    });

    const last = timeline!.weeks[timeline!.weeks.length - 1];
    expect(last.index).toBeGreaterThanOrEqual(2);
  });

  it('stretches to cover work scheduled beyond the trailing window', () => {
    const timeline = buildReleaseTimeline({
      tasks: [makeTask({ dueDate: dueAt(60) })],
      releaseDate: RELEASE_DATE,
      now,
    });

    const last = timeline!.weeks[timeline!.weeks.length - 1];
    expect(last.startDay + 6).toBeGreaterThanOrEqual(60);
  });

  it('marks exactly one release week and one current week', () => {
    const timeline = buildReleaseTimeline({
      tasks: [makeTask({ dueDate: dueAt(-70) })],
      releaseDate: RELEASE_DATE,
      now,
    });

    expect(timeline!.weeks.filter((week) => week.isReleaseWeek)).toHaveLength(1);
    expect(timeline!.weeks.filter((week) => week.isCurrentWeek)).toHaveLength(1);
    expect(timeline!.todayDay).toBe(-60);
  });

  it('stretches to bring today onto the axis when the plan has not started', () => {
    // The normal state of a release planned well ahead: today is before the
    // first scheduled activity. The marker is the whole "on track" read, so
    // the axis reaches back for it rather than dropping it.
    const timeline = buildReleaseTimeline({
      tasks: [makeTask({ dueDate: dueAt(-42) })],
      releaseDate: RELEASE_DATE,
      now: new Date(dueAt(-60)),
    });

    expect(timeline!.todayDay).toBe(-60);
    expect(timeline!.weeks.filter((week) => week.isCurrentWeek)).toHaveLength(1);
    expect(dayPosition(-60, timeline!.weeks)).not.toBeNull();
  });

  it('refuses to stretch a hundred empty columns for a long-finished release', () => {
    // Beyond the bound, today is genuinely off the chart and no marker is
    // drawn — better than an axis of empty weeks reaching a line nobody needs.
    const timeline = buildReleaseTimeline({
      tasks: [makeTask({ dueDate: dueAt(-7) })],
      releaseDate: RELEASE_DATE,
      now: new Date(dueAt(700)),
    });

    expect(timeline!.weeks.some((week) => week.isCurrentWeek)).toBe(false);
    expect(dayPosition(timeline!.todayDay!, timeline!.weeks)).toBeNull();
    expect(timeline!.weeks.length).toBeLessThan(20);
  });

  it('returns null without a usable release date', () => {
    // No release day means no axis. The scene shows its own empty state
    // rather than a grid anchored to nothing.
    expect(
      buildReleaseTimeline({ tasks: [makeTask()], releaseDate: null, now })
    ).toBeNull();
    expect(
      buildReleaseTimeline({ tasks: [makeTask()], releaseDate: 'soon', now })
    ).toBeNull();
  });
});

describe('phases', () => {
  const now = new Date(dueAt(-60));

  it('groups into Pre-release, Release and Post-release (URG-292)', () => {
    const timeline = buildReleaseTimeline({
      tasks: [
        makeTask({ id: 'a', dueDate: dueAt(-56), title: 'Setup work' }),
        makeTask({ id: 'b', dueDate: dueAt(-14), title: 'Ramp work' }),
        makeTask({ id: 'c', dueDate: dueAt(0), title: 'Release day' }),
        makeTask({ id: 'd', dueDate: dueAt(14), title: 'After' }),
      ],
      releaseDate: RELEASE_DATE,
      now,
    });

    expect(timeline!.phases.map((phase) => phase.phase)).toEqual([
      'pre_release',
      'release',
      'post_release',
    ]);
    expect(timeline!.phases[0].items.map((item) => item.taskId)).toEqual(['a', 'b']);
  });

  it('puts a task under its stored phase whatever its date', () => {
    const timeline = buildReleaseTimeline({
      tasks: [
        makeTask({ id: 'a', dueDate: dueAt(-56), phase: 'post_release' }),
        makeTask({ id: 'b', dueDate: dueAt(-56) }),
      ],
      releaseDate: RELEASE_DATE,
      now,
    });

    expect(timeline!.phases.map((phase) => [phase.phase, phase.items.map((item) => item.taskId)])).toEqual([
      ['pre_release', ['b']],
      ['post_release', ['a']],
    ]);
  });

  it('omits phases with nothing in them', () => {
    const timeline = buildReleaseTimeline({
      tasks: [makeTask({ dueDate: dueAt(-56) })],
      releaseDate: RELEASE_DATE,
      now,
    });

    expect(timeline!.phases).toHaveLength(1);
    expect(timeline!.phases[0].phase).toBe('pre_release');
  });

  it('spans a phase across all its items', () => {
    const timeline = buildReleaseTimeline({
      tasks: [
        makeTask({ id: 'a', dueDate: dueAt(-56) }),
        makeTask({ id: 'b', dueDate: dueAt(-35), durationDays: 7 }),
      ],
      releaseDate: RELEASE_DATE,
      now,
    });

    const setup = timeline!.phases[0];
    expect(setup.startDay).toBe(-56);
    expect(setup.endDay).toBe(-29);
  });

  it('counts done and attention-needing work for the collapsed row', () => {
    const timeline = buildReleaseTimeline({
      tasks: [
        makeTask({ id: 'a', dueDate: dueAt(-56), status: 'done', completedAt: dueAt(-56) }),
        makeTask({ id: 'b', dueDate: dueAt(-55), status: 'blocked' }),
        // Past-due against `now`, and not flagged as compressed runway.
        makeTask({ id: 'c', dueDate: dueAt(-90), status: 'todo' }),
      ],
      releaseDate: RELEASE_DATE,
      now,
    });

    const totals = timeline!.phases.reduce(
      (accumulator, phase) => ({
        done: accumulator.done + phase.doneCount,
        attention: accumulator.attention + phase.attentionCount,
      }),
      { done: 0, attention: 0 }
    );

    expect(totals.done).toBe(1);
    expect(totals.attention).toBe(2);
  });
});

describe('tone', () => {
  it('inherits the activity list\'s vocabulary rather than recomputing it', () => {
    expect(toneForSection('overdue')).toBe('overdue');
    expect(toneForSection('done')).toBe('done');
    expect(toneForSection('blocked')).toBe('blocked');
    expect(toneForSection('locked')).toBe('blocked');
    expect(toneForSection('in_review')).toBe('in_progress');
    expect(toneForSection('upcoming')).toBe('scheduled');
  });

  it('keeps a compressed runway out of the red', () => {
    // A release created inside its own lead time starts with dozens of
    // past-due activities. Painting those overdue would make the timeline
    // scream on day one about a compressed schedule, not slippage.
    const timeline = buildReleaseTimeline({
      tasks: [makeTask({ dueDate: dueAt(-90), compressedRunway: true })],
      releaseDate: RELEASE_DATE,
      now: new Date(dueAt(-60)),
    });

    expect(timeline!.phases[0].items[0].tone).toBe('catch_up');
    expect(timeline!.phases[0].attentionCount).toBe(0);
  });

  it('lets status beat the calendar', () => {
    const timeline = buildReleaseTimeline({
      tasks: [makeTask({ dueDate: dueAt(-90), status: 'in_progress' })],
      releaseDate: RELEASE_DATE,
      now: new Date(dueAt(-60)),
    });

    expect(timeline!.phases[0].items[0].tone).toBe('in_progress');
  });
});

describe('unscheduled work', () => {
  it('lists dateless activities instead of dropping them', () => {
    const timeline = buildReleaseTimeline({
      tasks: [
        makeTask({ id: 'a', dueDate: dueAt(-10), title: 'Placed' }),
        makeTask({ id: 'b', dueDate: null, title: 'No date yet' }),
      ],
      releaseDate: RELEASE_DATE,
      now: new Date(dueAt(-60)),
    });

    expect(timeline!.placedCount).toBe(1);
    expect(timeline!.unscheduled).toHaveLength(1);
    expect(timeline!.unscheduled[0].title).toBe('No date yet');
  });
});

describe('positioning', () => {
  const weeks = buildReleaseTimeline({
    tasks: [makeTask({ dueDate: dueAt(-14) })],
    releaseDate: RELEASE_DATE,
    now: new Date(dueAt(-14)),
  })!.weeks;

  it('gives a single-day item one day of width, never zero', () => {
    const { widthPercent } = itemPosition({ startDay: -14, endDay: -14 }, weeks);
    const oneDay = 100 / (weeks.length * 7);
    expect(widthPercent).toBeCloseTo(oneDay, 5);
  });

  it('gives a seven-day bar seven days of width', () => {
    const { widthPercent } = itemPosition({ startDay: -14, endDay: -8 }, weeks);
    expect(widthPercent).toBeCloseTo((100 / (weeks.length * 7)) * 7, 5);
  });

  it('places the axis start at zero', () => {
    const { leftPercent } = itemPosition(
      { startDay: weeks[0].startDay, endDay: weeks[0].startDay },
      weeks
    );
    expect(leftPercent).toBe(0);
  });

  it('never escapes the axis', () => {
    const { leftPercent, widthPercent } = itemPosition({ startDay: -9999, endDay: 9999 }, weeks);
    expect(leftPercent).toBeGreaterThanOrEqual(0);
    expect(widthPercent).toBeLessThanOrEqual(100);
  });
});

describe('drag', () => {
  it('snaps to whole days', () => {
    // 10 weeks over 700px is exactly 10px per day.
    expect(daysForDragDelta(10, 700, 10)).toBe(1);
    expect(daysForDragDelta(14, 700, 10)).toBe(1);
    expect(daysForDragDelta(16, 700, 10)).toBe(2);
    expect(daysForDragDelta(-30, 700, 10)).toBe(-3);
  });

  it('reports no movement for a tap', () => {
    expect(daysForDragDelta(0, 700, 10)).toBe(0);
    expect(daysForDragDelta(2, 700, 10)).toBe(0);
  });

  it('refuses to divide by an unmeasured axis', () => {
    expect(daysForDragDelta(100, 0, 10)).toBe(0);
    expect(daysForDragDelta(100, 700, 0)).toBe(0);
  });
});

describe('the mobile week list', () => {
  const now = new Date(dueAt(-60));

  it('lists a run under every week it touches', () => {
    // On a vertical week-by-week list, work genuinely in flight this week has
    // to appear in this week — not only in the week it started.
    const timeline = buildReleaseTimeline({
      tasks: [makeTask({ dueDate: dueAt(-45), durationDays: 7, title: 'Ongoing' })],
      releaseDate: RELEASE_DATE,
      now,
    });

    const groups = groupItemsByWeek(timeline!);
    const weeksHoldingIt = groups.filter((group) =>
      group.items.some((item) => item.title === 'Ongoing')
    );

    // -45 to -39 straddles the -49..-43 and -42..-36 weeks.
    expect(weeksHoldingIt).toHaveLength(2);
  });

  it('drops empty weeks', () => {
    const timeline = buildReleaseTimeline({
      tasks: [makeTask({ dueDate: dueAt(-42) })],
      releaseDate: RELEASE_DATE,
      now,
    });

    const groups = groupItemsByWeek(timeline!);
    expect(groups).toHaveLength(1);
    expect(groups[0].week.index).toBe(-6);
  });
});

describe('narrowTimeline (key tasks, URG-258)', () => {
  const now = new Date(dueAt(-60));
  const tasks = [
    makeTask({ id: 'a', dueDate: dueAt(-50) }),
    makeTask({ id: 'b', dueDate: dueAt(-49), status: 'done' }),
    makeTask({ id: 'c', dueDate: dueAt(-10) }),
    makeTask({ id: 'd', dueDate: dueAt(20) }),
    makeTask({ id: 'e', dueDate: null }),
  ];
  const full = buildReleaseTimeline({ tasks, releaseDate: RELEASE_DATE, now })!;

  it('keeps the whole axis and only the kept activities', () => {
    const short = narrowTimeline(full, new Set(['a', 'b', 'e']));
    expect(short.weeks).toEqual(full.weeks);
    expect(short.phases.flatMap((p) => p.items.map((i) => i.taskId)).sort()).toEqual(['a', 'b']);
    expect(short.unscheduled.map((i) => i.taskId)).toEqual(['e']);
    expect(short.placedCount).toBe(2);
  });

  it('drops empty phases and recounts the ones left', () => {
    const short = narrowTimeline(full, new Set(['b']));
    expect(short.phases).toHaveLength(1);
    expect(short.phases[0].items).toHaveLength(1);
    expect(short.phases[0].doneCount).toBe(1);
  });
});
