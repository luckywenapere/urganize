import { describe, expect, it } from 'vitest';
import { buildUsageMetrics, type MetricsPerson, type MetricsRelease, type UsageMetricsInput } from './usage-metrics';
import {
  attentionRows,
  buildAdminOverview,
  needsYouCards,
  sinceLabel,
  updatedAgo,
  visitsAllTimeLabel,
} from './admin-overview';

// The one-screen admin Overview (URG-369). Its day numbers come from the
// Metrics rules, so these check the new "today" block and the picking.

// 13:00 in Lagos (12:00 UTC) on Sunday 18 October 2026.
const NOW = new Date('2026-10-18T12:00:00.000Z');
const HOUR = 60 * 60 * 1000;
const DAY = 24 * HOUR;
const iso = (msBack: number) => new Date(NOW.getTime() - msBack).toISOString();

function person(userId: string, over: Partial<MetricsPerson> = {}): MetricsPerson {
  return {
    userId,
    email: `${userId}@example.com`,
    name: userId,
    role: 'manager',
    createdAt: '2026-06-01T00:00:00.000Z',
    lastSignInAt: null,
    onboardingCompleted: true,
    ...over,
  };
}

function release(id: string, over: Partial<MetricsRelease> = {}): MetricsRelease {
  return {
    id,
    workspaceId: 'team',
    ownerUserId: 'ada',
    createdAt: '2026-06-01T00:00:00.000Z',
    releaseDate: null,
    status: 'draft',
    isTest: false,
    plannerPending: false,
    templatePending: false,
    plannedByUrgans: false,
    draftAiApplied: null,
    title: 'Midnight',
    touchedCount: 0,
    taskCount: 0,
    doneCount: 0,
    autoTaskCount: 0,
    ...over,
  };
}

function input(over: Partial<UsageMetricsInput> = {}): UsageMetricsInput {
  return {
    now: NOW,
    people: [],
    presence: [],
    activity: new Map(),
    latestEvents: new Map(),
    appOpens: [],
    releases: [],
    tasks: [],
    teams: [],
    urgansTurns: [],
    aiCost: null,
    waitlistTotal: null,
    hiddenUserIds: new Set(),
    ...over,
  };
}

describe('the Overview day numbers', () => {
  const metrics = buildUsageMetrics(
    input({
      people: [
        person('ada'),
        person('new', { createdAt: iso(2 * HOUR) }),
        // 23:30 Lagos yesterday: yesterday, not today.
        person('late', { createdAt: '2026-10-17T22:30:00.000Z' }),
        person('ours', { createdAt: iso(HOUR) }),
      ],
      hiddenUserIds: new Set(['ours']),
      appOpens: [
        { userId: 'ada', at: NOW.getTime() - HOUR },
        { userId: 'late', at: NOW.getTime() - DAY },
        { userId: 'ours', at: NOW.getTime() - HOUR },
      ],
      appOpensAll: [
        { userId: 'ada', at: Date.parse('2026-07-24T09:00:00.000Z') },
        { userId: 'ada', at: NOW.getTime() - HOUR },
        { userId: 'late', at: NOW.getTime() - DAY },
        { userId: 'ours', at: Date.parse('2026-07-23T23:30:00.000Z') },
      ],
      releases: [
        release('r1', { createdAt: iso(HOUR) }),
        release('test', { createdAt: iso(HOUR), isTest: true }),
        release('r-ours', { createdAt: iso(HOUR), ownerUserId: 'ours' }),
      ],
      tasks: [
        // Ticked today, stamped.
        { releaseId: 'r1', status: 'done', completedAt: iso(HOUR), updatedAt: iso(HOUR), createdAt: iso(DAY * 9), autoGenerated: true },
        // Ticked 3 days ago, stamped, edited today: counts on its tick day.
        { releaseId: 'r1', status: 'done', completedAt: iso(3 * DAY), updatedAt: iso(HOUR), createdAt: iso(DAY * 9), autoGenerated: true },
        // Ticked before the fix: no stamp, dated by its last edit.
        { releaseId: 'r1', status: 'done', completedAt: null, updatedAt: iso(2 * DAY), createdAt: iso(DAY * 9), autoGenerated: true },
        // Not done.
        { releaseId: 'r1', status: 'todo', completedAt: null, updatedAt: iso(HOUR), createdAt: iso(DAY * 9), autoGenerated: true },
        // Ours.
        { releaseId: 'r-ours', status: 'done', completedAt: iso(HOUR), updatedAt: iso(HOUR), createdAt: iso(DAY), autoGenerated: true },
      ],
    })
  );

  it('counts today in Lagos and leaves our accounts out', () => {
    expect(metrics.today.signups).toBe(1);
    expect(metrics.today.rollouts).toBe(1);
    expect(metrics.today.visits).toBe(1);
    expect(metrics.today.activeYesterday).toBe(1);
    expect(metrics.active.today).toBe(1);
  });

  it('dates a tick by completed_at, falling back to updated_at only without one', () => {
    expect(metrics.today.ticked).toBe(1);
    expect(metrics.work.activitiesDone7d).toBe(3);
    expect(metrics.today.tickedByUpdatedAt7d).toBe(1);
  });

  it('counts visits all time from the first one recorded', () => {
    expect(metrics.visits.allTime).toBe(3);
    expect(metrics.visits.since).toBe('2026-07-24');
    expect(sinceLabel(metrics.visits.since)).toBe('since 24 Jul');
  });

  it('shows the all-time count as unknown when it could not be read', () => {
    const unread = buildUsageMetrics(input({ appOpensAll: null }));
    expect(unread.visits).toEqual({ allTime: null, since: null });
  });

  it('says Online now is not tracking until the ping has recorded anyone', () => {
    const attention = { reports: 0, pitchPayments: 0 };
    expect(buildAdminOverview({ metrics, cockpit: null, attention }).online).toBeNull();
    const tracked = buildUsageMetrics(
      input({
        people: [person('ada')],
        presence: [{ userId: 'ada', day: '2026-10-18', lastSeenAt: iso(60_000), surface: 'phone_web' }],
      })
    );
    expect(buildAdminOverview({ metrics: tracked, cockpit: null, attention }).online).toBe(1);
  });

  it('leaves This week empty, not zero, when the Scoreboard read failed', () => {
    const overview = buildAdminOverview({ metrics, cockpit: null, attention: { reports: null, pitchPayments: null } });
    expect(overview.week).toBeNull();
    expect(overview.atRisk).toBeNull();
    expect(overview.today.ticked).toEqual({ today: 1, week: 3, datedByEdit7d: 1 });
  });
});

describe('Reports and Pitch payments on the Overview', () => {
  it('show only when they need someone', () => {
    expect(attentionRows({ reports: 0, pitchPayments: 0 })).toEqual([]);
    expect(attentionRows({ reports: null, pitchPayments: null })).toEqual([]);
    expect(attentionRows({ reports: 2, pitchPayments: 0 }).map((row) => row.label)).toEqual(['Reports']);
    expect(attentionRows({ reports: 0, pitchPayments: 1 }).map((row) => row.href)).toEqual(['/admin/pitch-payments']);
    expect(attentionRows({ reports: 0, pitchPayments: 0, curatorApplications: 3 })).toEqual([
      { key: 'curator-applications', label: 'Applications', href: '/admin/curator-applications', count: 3 },
    ]);
  });
});

describe('Updated Xs ago', () => {
  it('reads in seconds, then minutes', () => {
    expect(updatedAgo(iso(2000), NOW)).toBe('Updated just now');
    expect(updatedAgo(iso(40_000), NOW)).toBe('Updated 40s ago');
    expect(updatedAgo(iso(3 * 60_000), NOW)).toBe('Updated 3m ago');
    expect(updatedAgo(null, NOW)).toBe('');
  });
});

describe('the needs you row (2026-11-12, #1241)', () => {
  const team = { workspaceId: 'w' } as unknown as NonNullable<Parameters<typeof needsYouCards>[0]['atRisk']>[number];

  it('is always the same four cards, in order', () => {
    const cards = needsYouCards({ attention: { reports: 8, pitchPayments: 2, curatorApplications: 7 }, atRisk: [team] });
    expect(cards.map((card) => card.label)).toEqual(['Reports', 'Applications', 'Pitch payments', 'Needs a message']);
    expect(cards.map((card) => card.count)).toEqual([8, 7, 2, 1]);
    expect(cards.every((card) => card.waiting)).toBe(true);
  });

  it('is quiet at zero and says so; a count it could not read is a dash, never zero', () => {
    const cards = needsYouCards({ attention: { reports: 0, pitchPayments: null }, atRisk: null });
    expect(cards[0]).toMatchObject({ count: 0, waiting: false, note: 'Nothing waiting' });
    expect(cards[1]).toMatchObject({ count: null, waiting: false, note: "Couldn't read" });
    expect(cards[2]).toMatchObject({ count: null, waiting: false });
    expect(cards[3]).toMatchObject({ count: null, waiting: false, href: null });
  });

  it('opens the page that clears each count', () => {
    const cards = needsYouCards({ attention: { reports: 1, pitchPayments: 1, curatorApplications: 1 }, atRisk: [] });
    expect(cards.slice(0, 3).map((card) => card.href)).toEqual([
      '/admin/issue-reports',
      '/admin/curator-applications',
      '/admin/pitch-payments',
    ]);
  });
});

describe('the visits counters', () => {
  it('labels the all-time count with the day counting started', () => {
    expect(visitsAllTimeLabel('2026-07-24')).toBe('Visits since 24 Jul');
    expect(visitsAllTimeLabel(null)).toBe('Visits all time');
  });

  // The screenshot behind the 2026-11-12 mock read "Visits today 1,240" above
  // "Visits since 7 Nov 918". Both counts come from the same rows with the same
  // filter, so today can never pass all time; this holds the rule in place.
  it('never counts more visits today than all time', () => {
    const opens = [
      { userId: 'a', at: NOW.getTime() - HOUR },
      { userId: 'a', at: NOW.getTime() - 2 * HOUR },
      { userId: 'b', at: NOW.getTime() - 3 * DAY },
      { userId: 'ours', at: NOW.getTime() - HOUR },
    ];
    const metrics = buildUsageMetrics(
      input({ appOpens: opens, appOpensAll: opens, hiddenUserIds: new Set(['ours']) })
    );
    expect(metrics.today.visits).toBe(2);
    expect(metrics.visits.allTime).toBe(3);
    expect(metrics.today.visits).toBeLessThanOrEqual(metrics.visits.allTime ?? 0);
  });
});
